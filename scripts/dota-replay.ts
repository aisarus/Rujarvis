/**
 * Прогон порогов по записи живой игры.
 *
 * ## Зачем отдельно от тестов
 *
 * Запись весит 495 МБ и в репозиторий не кладётся. Но без неё пороги — слова:
 * юнит-тест докажет, что «трое в радиусе» считается правильно, и ничего не
 * скажет о том, сколько раз это спасёт и сколько раз соврёт.
 *
 * Здесь проверяется не код, а замысел. Если числа разошлись — **не подгонять
 * пороги под запись**: значит модуль ведёт себя не так, как считал разведочный
 * скрипт, и надо найти разницу.
 *
 * ## Что печатает
 *
 * Поймано из скольких, тревог без смерти, фору в секундах, реплик про золото.
 * Числа замысла: 18 из 18, четыре тревоги без смерти, 9,1 секунды, пять реплик
 * про золото.
 *
 * ## Запуск
 *
 *     NODE_OPTIONS=--max-old-space-size=4096 pnpm exec tsx scripts/dota-replay.ts
 */
import { createReadStream } from 'node:fs';
import { argv, exit } from 'node:process';
import { createInterface } from 'node:readline';

import { advise, createMemory } from '../jarvis/dota/advice';
import { readPacket, type DotaPacket } from '../jarvis/dota/packet';
import { applyPacket, createState } from '../jarvis/dota/state';
import { judgeDanger, judgeGold } from '../jarvis/dota/thresholds';

const ПАПКА = argv[2] ?? 'C:/Users/ariel/Desktop/Джарвис/разведка-доты/запись-2026-09-21-1255';

/** Столько ждём смерть после того, как тревога смолкла. */
const ОКНО = 15_000;

/** Тревоги ближе этого друг к другу — один эпизод, а не семь. */
const СКЛЕЙКА = 8_000;

interface Эпизод {
  начало: number;
  конец: number;
  clock: number | null;
}

const пакеты: DotaPacket[] = [];
const поток = createInterface({
  input: createReadStream(`${ПАПКА}/gsi.jsonl`),
  crlfDelay: Infinity,
});
for await (const строка of поток) {
  if (!строка) continue;
  let сырая: { t?: number; d?: unknown };
  try { сырая = JSON.parse(строка) as { t?: number; d?: unknown }; } catch { continue; }
  const п = readPacket(сырая.d, сырая.t ?? 0);
  if (п?.self) пакеты.push(п);
}

const смерти: DotaPacket[] = [];
const эпизоды: Эпизод[] = [];
let текущий: Эпизод | null = null;
let состояние = createState();
let золотых = 0;
// Про какой период накопления уже сказано. Считать переходы ворот нельзя:
// порог молчит, пока герой лежит, и одно накопление разорвалось бы на три
// реплики. «Сказать один раз» — это один раз про одни деньги.
let сказаноПро: number | null = null;

// Настоящий голос: то, что человек услышал бы за матч. Порог может ловить всё
// и при этом говорить двадцать пять раз об одной опасности — счёт реплик это
// единственное, что такую беду показывает.
let память = createMemory();
const реплики: { clock: number | null; текст: string }[] = [];

for (let i = 0; i < пакеты.length; i += 1) {
  const п = пакеты[i];
  const былЖив = пакеты[i - 1]?.self?.alive ?? true;
  if (былЖив && п.self?.alive === false) смерти.push(п);

  состояние = applyPacket(состояние, п);

  const золото = judgeGold(состояние);
  if (золото.passed === false && состояние.goldSince !== сказаноПро) {
    золотых += 1;
    сказаноПро = состояние.goldSince;
  }

  const совет = advise(состояние, память, 'full');
  память = совет.memory;
  if (совет.speech) реплики.push({ clock: п.clock, текст: совет.speech });

  const ворота = judgeDanger(п);
  if (ворота.passed === false) {
    if (текущий && п.at - текущий.конец <= СКЛЕЙКА) текущий.конец = п.at;
    else {
      текущий = { начало: п.at, конец: п.at, clock: п.clock };
      эпизоды.push(текущий);
    }
  }
}

// Идём от смерти к тревоге, а не наоборот: длинный эпизод в затяжном замесе
// накрывает и реинкарнацию, и настоящую смерть, и обратный порядок засчитал бы
// ему только одну, объявив вторую упущенной.
const пойманные = new Map<DotaPacket, number>();
const сработавшие = new Set<Эпизод>();
for (const с of смерти) {
  const э = эпизоды.find((э) => с.at >= э.начало && с.at - э.конец <= ОКНО);
  if (!э) continue;
  пойманные.set(с, (с.at - э.начало) / 1000);
  сработавшие.add(э);
}

const впустую = эпизоды.length - сработавшие.size;
const форы = [...пойманные.values()];
const средняя = форы.length ? форы.reduce((a, б) => a + б, 0) / форы.length : 0;
const времяПеч = (ч: number | null) => (ч === null
  ? '--:--'
  : `${String(Math.floor(Math.abs(ч) / 60)).padStart(2, '0')}:${String(Math.abs(ч) % 60).padStart(2, '0')}`);

console.log(`пакетов: ${пакеты.length}`);
console.log(`героя убивали: ${смерти.length} (настоящих смертей по счётчику: ${состояние.deaths})`);
console.log(`тревог: ${эпизоды.length}, из них без смерти: ${впустую}`);
console.log(`поймано: ${пойманные.size} из ${смерти.length}`);
console.log(`фора в среднем: ${средняя.toFixed(1)} с, худшая: ${Math.min(...форы).toFixed(1)} с`);
console.log(`реплик про золото: ${золотых}`);
console.log(`вслух за матч: ${реплики.length}`);
for (const р of реплики) console.log(`   ${времяПеч(р.clock)}  ${р.текст}`);

const упущенные = смерти.filter((с) => !пойманные.has(с));
if (упущенные.length) {
  console.log('');
  console.log('не поймано:');
  for (const с of упущенные) {
    const ближайший = с.enemies
      .map((в) => Math.hypot(в.x - с.self!.x, в.y - с.self!.y))
      .sort((a, б) => a - б)[0];
    console.log(`  ${времяПеч(с.clock)}  ближайший враг ${ближайший ? Math.round(ближайший) : 'не виден'}`);
  }
}

// Замысел: 18 из 18, четыре тревоги без смерти, фора 9,1 с, две реплики про
// золото.
//
// «Тревога без смерти» — не то же самое, что ложная. Три из четырёх были
// настоящей опасностью, из которой человек вышел живым: на 06:37 здоровье
// падало до 25%, на 15:04 сорок четыре секунды против четверых с четырьмя
// убийствами в ответ, на 51:19 четверо рядом. Машина этой разницы не видит и
// видеть не должна — она считает то, что умеет считать.
const беды: string[] = [];
if (пойманные.size !== смерти.length) беды.push(`поймано ${пойманные.size}, а убивали ${смерти.length}`);
if (впустую > 4) беды.push(`тревог без смерти ${впустую}, в замысле четыре`);
if (средняя < 7) беды.push(`фора ${средняя.toFixed(1)} с, в замысле 9,1`);
if (золотых > 5) беды.push(`реплик про золото ${золотых}, в замысле пять`);

if (беды.length) {
  console.log('');
  console.log('РАЗОШЛОСЬ С ЗАМЫСЛОМ:');
  for (const б of беды) console.log('  -', б);
  exit(1);
}
console.log('');
console.log('числа сошлись с замыслом');
