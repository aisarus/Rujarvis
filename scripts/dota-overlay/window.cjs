/**
 * Окно оверлея поверх Доты.
 *
 * ## Почему отдельный процесс, а не часть помощника
 *
 * Помощник написан на TypeScript и запускается через `tsx`. Electron так не
 * умеет: ему нужен обычный JavaScript. Заводить сборку ради одного окна —
 * лишний шаг между правкой и проверкой.
 *
 * Поэтому помощник поднимает это окно как ребёнка и кладёт состояние в файл, а
 * окно за ним следит. Тот же приём, что у живых сессий Блендера и Криты:
 * никаких сокетов и портов, только файл, который можно открыть глазами.
 *
 * ## Почему не стандартный вход
 *
 * Пробовал, и это стоило часа. `readline` на `process.stdin` в главном процессе
 * Electron **ломает загрузку страницы**: `loadURL` отвергается с `ERR_FAILED`,
 * причём молча — ни в консоли страницы, ни в `did-fail-load` ничего нет.
 * Проверено сведением к одному отличию: та же настройка окна, тот же файл, тот
 * же способ запуска; с `readline` — отказ, без него — загрузка.
 *
 * Почему именно так — не выяснял: обходной путь проще и надёжнее, чем
 * понимание чужой причуды.
 *
 * ## Почему `executeJavaScript`, а не preload и IPC
 *
 * Страница уже умеет рисовать себя: у неё есть `нарисовать(view)`. Всё, что
 * нужно от моста, — вызвать эту функцию. Preload, контекстный мост и канал IPC
 * добавили бы три файла и ни одной новой возможности.
 *
 * ## Что обязательно для игрового оверлея
 *
 * - `transparent` и `frame: false` — иначе поверх игры повиснет серый
 *   прямоугольник с заголовком;
 * - `setIgnoreMouseEvents(true)` — мышь должна проходить насквозь, иначе
 *   половина экрана перестанет кликаться, и человек потеряет игру;
 * - `focusable: false` — окно не должно воровать фокус: Дота при потере фокуса
 *   останавливает ввод;
 * - `setAlwaysOnTop(true, 'screen-saver')` — обычного `alwaysOnTop` не хватает,
 *   чтобы лечь поверх игры;
 * - **Дота должна идти в оконном без рамки.** Поверх монопольного
 *   полноэкранного не нарисует ничто: это ограничение Windows, а не наше.
 *
 * ## Масштаб экрана
 *
 * Electron живёт в логических пикселях, а страница свёрстана в физических: у
 * человека экран 1920×1080 при масштабе 125%, и окно выходит 1536×864.
 * Миникарта, размеченная по координате 1677, уезжала за правый край — окно
 * рисовало всё правильно и целиком мимо экрана.
 *
 * Лечится одним числом: масштаб страницы `1 / scaleFactor`. Тогда элемент,
 * поставленный в физический пиксель 1677, туда и попадает, и разметка,
 * снятая с настоящего кадра игры, совпадает с игрой при любом масштабе.
 */
const { app, BrowserWindow, screen } = require('electron');
const path = require('node:path');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');

const СТРАНИЦА = path.join(__dirname, '..', '..', 'jarvis', 'dota', 'overlay', 'view.html');

/** Файл состояния: его пишет помощник, за ним следит окно. */
const СОСТОЯНИЕ = process.argv[2];

let окно = null;
let готово = false;
/** Последнее состояние, пришедшее до готовности страницы. */
let отложенное = null;

function создать() {
  const экран = screen.getPrimaryDisplay();
  const { x, y, width, height } = экран.bounds;

  окно = new BrowserWindow({
    x, y, width, height,
    transparent: true,
    frame: false,
    resizable: false,
    movable: false,
    minimizable: false,
    maximizable: false,
    fullscreenable: false,
    skipTaskbar: true,
    hasShadow: false,
    focusable: false,
    alwaysOnTop: true,
    show: false,
    webPreferences: {
      contextIsolation: false,
      nodeIntegration: false,
      backgroundThrottling: false,
    },
  });

  окно.setIgnoreMouseEvents(true);
  окно.setAlwaysOnTop(true, 'screen-saver');
  окно.setVisibleOnAllWorkspaces(true, { visibleOnFullScreen: true });

  окно.webContents.on('did-finish-load', () => {
    готово = true;
    // Страница размечена в физических пикселях кадра игры, окно живёт в
    // логических. Без этого весь интерфейс уезжает за край экрана.
    окно.webContents.setZoomFactor(1 / экран.scaleFactor);
    окно.showInactive();
    if (отложенное) { нарисовать(отложенное); отложенное = null; }
  });

  окно.loadURL(pathToFileURL(СТРАНИЦА).href).catch((беда) => {
    // Не просто пишем в журнал, а УХОДИМ.
    //
    // Раньше запись в `оверлей.log` была всей обработкой: `did-finish-load`
    // не приходил, окно не показывалось, а процесс продолжал крутиться.
    // Помощник поднимает окно заново только по выходу процесса, поэтому его
    // механизм перезапуска тут не срабатывал вовсе: человек видел «голос
    // работает», оверлея не было, и в консоли об этом ни слова.
    console.error('[оверлей] страница не загрузилась:', беда && беда.message);
    app.exit(1);
  });
}

function нарисовать(состояние) {
  if (!окно || окно.isDestroyed()) return;
  if (!готово) { отложенное = состояние; return; }
  // Страница рисует себя сама; мосту остаётся позвать её функцию.
  окно.webContents
    .executeJavaScript(`нарисовать(${состояние});`, true)
    .catch(() => { /* страница перезагружается — следующий кадр нарисует */ });
}

/**
 * Ускорение видеокарты **не отключаем**, хотя для прозрачных окон это советуют
 * повсеместно. Проверено на этой машине: с `disableHardwareAcceleration` окно
 * показывает только свой фоновый цвет, а содержимое страницы не рисуется вовсе.
 * Прозрачное окно при этом выглядит просто пустым — и час уходит на поиск
 * несуществующей ошибки в разметке.
 */

/** Сколько ждать между проверками файла. Оверлей меняется два-три раза в секунду. */
const ШАГ = 200;

/**
 * Сколько молчания считать смертью помощника.
 *
 * Тридцать секунд, а не восемь. Пауза в игре, загрузка, послематчевый экран —
 * всё это законные перерывы в пакетах, и гасить на них картинку неправильно.
 * Помощник, закрываясь по-человечески, убивает окно сам и ждать не заставляет.
 */
const МОЛЧАНИЕ = 30_000;

app.whenReady().then(() => {
  создать();

  if (!СОСТОЯНИЕ) {
    console.error('[оверлей] не сказано, где файл состояния');
    app.quit();
    return;
  }

  let прошлое = '';
  let прошлоеВремя = 0;
  /**
   * Когда файл обновлялся в последний раз. `null` — ещё ни разу.
   *
   * Отсчёт молчания начинается только после первого прочтения, и это не
   * мелочь: между запуском помощника и первым пакетом Доты проходят минуты —
   * человек ещё ищет игру. С отсчётом от старта окно кончало с собой раньше,
   * чем начиналась игра, и делало это молча.
   */
  let последнее = null;
  setInterval(() => {
    // Живость помощника меряем по времени правки файла, а не по тому,
    // изменилось ли содержимое. Вид может быть побайтно тем же несколько
    // секунд подряд — герой мёртв, часы на паузе, — и считать это смертью
    // помощника значит гасить оверлей в самый неподходящий момент.
    let время = 0;
    try { время = fs.statSync(СОСТОЯНИЕ).mtimeMs; } catch { время = 0; }
    if (время && время !== прошлоеВремя) {
      прошлоеВремя = время;
      последнее = Date.now();
      let текст;
      try { текст = fs.readFileSync(СОСТОЯНИЕ, 'utf8'); } catch { текст = ''; }
      if (текст && текст !== прошлое) { прошлое = текст; нарисовать(текст); }
    }
    // Помощник ушёл — уходим и мы. Оверлей, переживший его, останется висеть
    // поверх игры, и закрыть его будет нечем.
    if (последнее !== null && Date.now() - последнее > МОЛЧАНИЕ) app.quit();
  }, ШАГ);
});

app.on('window-all-closed', () => app.quit());
