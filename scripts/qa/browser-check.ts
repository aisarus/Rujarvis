/**
 * Вкладки: настоящий браузер, настоящая страница, настоящая вторая вкладка.
 *
 * Проверок на браузер не было ни на одной платформе, а поломок в нём за один
 * день нашлось три: профиль складывался в путь виндового вида, канал был
 * жёстко `msedge` (а на маке его чаще нет), и правило «дописать https» жило в
 * двух местах, где второе отстало. Все три видны только запуском.
 *
 * ## Замер идёт ЧЕРЕЗ маршрутизатор, а не мимо него
 *
 * Первая версия звала Playwright напрямую, и `JARVIS_BROWSER=safari` для неё
 * ничего не значил: прогон на маке напечатал два одинаковых зелёных отчёта, и
 * оба были про Chromium. Safari остался непроверенным, а зелень — ложной.
 * Проверять надо тот путь, которым работает Джарвис, а не соседний.
 *
 * Страница берётся своя, `data:`-адресом. В сеть не ходим: чужой сайт однажды
 * ляжет или поменяет вёрстку, и красным будет не наш код.
 *
 * Три ответа. Нет ни одного браузера — «нечем мерить», а не провал: чинить
 * тогда машину. То, что у движка не написано (закрытие вкладок Safari), — тоже
 * «нечем мерить», и выдавать ненаписанное за пройденное нельзя.
 *
 *   pnpm jarvis:browser-check
 *   JARVIS_BROWSER=safari pnpm jarvis:browser-check
 */

import { PROFILE_DIR, closeTab, dispose, браузераНет, порядокКаналов } from '../../jarvis/desktop/browser';
import { вебДвижок, выбратьДвижок } from '../../jarvis/desktop/webDriver';
import { jarvisHome } from '../../jarvis/setup/paths';

const ДВИЖОК = выбратьДвижок();
const веб = вебДвижок(undefined, ДВИЖОК);

type Ответ = { прошло: true } | { прошло: false; почему: string } | { прошло: null; почему: string };

const итоги: Array<{ имя: string; ответ: Ответ }> = [];

function записать(имя: string, ответ: Ответ): void {
  итоги.push({ имя, ответ });
  const метка = ответ.прошло === true ? 'прошло      ' : ответ.прошло === false ? 'НЕ ПРОШЛО   ' : 'нечем мерить';
  console.log(`  ${метка} ${имя}${ответ.прошло === true ? '' : ` — ${ответ.почему}`}`);
}

/** Своя страница, без сети: чужая однажды ляжет, и красным будет не наш код. */
function страница(заголовок: string, текст: string): string {
  const html =
    `<!doctype html><html lang="ru"><head><meta charset="utf-8"><title>${заголовок}</title></head>` +
    `<body><h1>${заголовок}</h1><p>${текст}</p></body></html>`;
  return `data:text/html;charset=utf-8,${encodeURIComponent(html)}`;
}

const МЕТКА = 'Проба вкладок Rujarvis';
const СЛОВО = 'вкладки-работают';

/** Свой Chromium гасим, Safari — нет: это браузер человека, он там работает. */
async function убратьЗаСобой(): Promise<void> {
  if (ДВИЖОК === 'chromium') await dispose().catch(() => {});
}

async function main(): Promise<void> {
  console.log(`Вкладки на ${process.platform}, движок ${ДВИЖОК}\n`);

  if (ДВИЖОК === 'chromium') {
    console.log(`    порядок каналов: ${порядокКаналов().join(' → ')}`);
    console.log(`    профиль: ${PROFILE_DIR}`);
    // Профиль обязан лежать ВНУТРИ папки Джарвиса: снаружи его не видит ни
    // установщик, ни уборка, ни сам человек.
    записать(
      'профиль лежит внутри папки Джарвиса',
      PROFILE_DIR.startsWith(jarvisHome())
        ? { прошло: true }
        : { прошло: false, почему: `${PROFILE_DIR} вне ${jarvisHome()}` },
    );
  } else {
    записать('профиль лежит внутри папки Джарвиса', {
      прошло: null,
      почему: 'у Safari профиль человека, а не наш — и это весь смысл',
    });
  }

  let открылся = false;
  try {
    const первая = await веб.openUrl(страница(МЕТКА, СЛОВО));
    открылся = true;
    записать(
      'страница открывается и отдаёт свой заголовок',
      первая.title.includes(МЕТКА)
        ? { прошло: true }
        : { прошло: false, почему: `заголовок «${первая.title}»` },
    );
  } catch (беда) {
    const почему = беда instanceof Error ? беда.message : String(беда);
    записать(
      'страница открывается и отдаёт свой заголовок',
      браузераНет(беда) || почему.includes('Не нашёл ни одного браузера')
        ? { прошло: null, почему: 'на машине нет ни Edge, ни Chrome, ни chromium' }
        : { прошло: false, почему },
    );
  }

  if (открылся) {
    try {
      const текст = await веб.readPage(2_000);
      записать(
        'чтение страницы возвращает её текст, а не пустоту',
        текст.includes(СЛОВО) ? { прошло: true } : { прошло: false, почему: `прочитано: «${текст.slice(0, 120)}»` },
      );
    } catch (беда) {
      const почему = беда instanceof Error ? беда.message : String(беда);
      записать(
        'чтение страницы возвращает её текст, а не пустоту',
        // Safari без галки «Разрешить JavaScript из Apple Events» к тексту не
        // пускает. Это не поломка Джарвиса и не пустая страница: человек чинит
        // это одним движением, и сказать об этом надо его словами.
        почему.includes('Разработка') ? { прошло: null, почему } : { прошло: false, почему },
      );
    }

    try {
      const былоДо = (await веб.listTabs()).length;
      await веб.openTab(страница('Вторая вкладка', 'вторая'));
      const вкладки = await веб.listTabs();
      записать(
        'вторая вкладка открывается и видна в списке',
        вкладки.length > былоДо
          ? { прошло: true }
          : { прошло: false, почему: `было ${былоДо}, стало ${вкладки.length}` },
      );

      // Активной обязана быть новая: человек сказал «открой вкладку» и ждёт,
      // что дальше разговор про неё.
      const активная = вкладки.find((в) => в.active);
      записать(
        'новая вкладка становится активной',
        активная?.title.includes('Вторая')
          ? { прошло: true }
          : { прошло: false, почему: `активна «${активная?.title ?? 'ничего'}»` },
      );

      if (ДВИЖОК === 'safari') {
        // Закрытие вкладок Safari ещё не написано, и инструмент про это честно
        // говорит. Выдавать ненаписанное за пройденное нельзя.
        записать('закрытая вкладка исчезает из списка', {
          прошло: null,
          почему: 'закрытие вкладок Safari ещё не написано',
        });
      } else {
        await closeTab('Вторая');
        const после = await веб.listTabs();
        записать(
          'закрытая вкладка исчезает из списка',
          после.length === былоДо
            ? { прошло: true }
            : { прошло: false, почему: `было ${былоДо}, после закрытия ${после.length}` },
        );
      }
    } catch (беда) {
      записать('вторая вкладка открывается и видна в списке', {
        прошло: false,
        почему: беда instanceof Error ? беда.message : String(беда),
      });
    }
  }

  await убратьЗаСобой();

  const прошло = итоги.filter((и) => и.ответ.прошло === true).length;
  const провал = итоги.filter((и) => и.ответ.прошло === false).length;
  const нечем = итоги.filter((и) => и.ответ.прошло === null).length;
  console.log(`\nВсего ${итоги.length}: прошло ${прошло}, не прошло ${провал}, нечем мерить ${нечем}`);
  process.exit(провал > 0 ? 1 : прошло === 0 ? 2 : 0);
}

void main().catch(async (беда: unknown) => {
  console.error('\nЗамер оборвался:', беда instanceof Error ? беда.message : String(беда));
  await убратьЗаСобой();
  process.exit(3);
});
