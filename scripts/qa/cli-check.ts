/**
 * Claude Code на этой машине: весь путь до точки, где нужна подписка.
 *
 * Джарвис живёт на подписках, и войти в аккаунт в прогоне CI нельзя — да и не
 * нужно: пароли и ключи в CI не носят. Но между «CLI установлен» и «агент
 * ответил» лежит длинная дорога, которую проверить МОЖНО и на которой всё и
 * ломалось: найти исполняемый файл среди десятка мест, где его кладут разные
 * менеджеры пакетов; запустить его так, чтобы Node согласился; собрать
 * аргументы, список инструментов и конфиг MCP-сервера; получить внятный отказ
 * вместо падения.
 *
 * Поэтому ответов три. Всё, что не требует входа, обязано ПРОЙТИ. Сам ответ
 * агента — «нечем мерить», и выдавать его за успех нельзя: именно так и
 * получаются зелёные прогоны при нерабочей программе.
 *
 *   pnpm jarvis:cli-check
 */

import { spawn } from 'node:child_process';
import os from 'node:os';

import { createClaudeProbe, cliStatus, commonCliPaths, resolveCli } from '../../jarvis/backends/cliProbes';
import { cliLaunch } from '../../jarvis/backends/spawnCli';
import { isUsable } from '../../jarvis/backends/authHints';

type Ответ = { прошло: true } | { прошло: false; почему: string } | { прошло: null; почему: string };

const итоги: Array<{ имя: string; ответ: Ответ }> = [];

function записать(имя: string, ответ: Ответ): void {
  итоги.push({ имя, ответ });
  const метка = ответ.прошло === true ? 'прошло      ' : ответ.прошло === false ? 'НЕ ПРОШЛО   ' : 'нечем мерить';
  console.log(`  ${метка} ${имя}${ответ.прошло === true ? '' : ` — ${ответ.почему}`}`);
}

/**
 * Запустить CLI ровно так, как это делает Джарвис, и вернуть, чем кончилось.
 *
 * Не через свой spawn с голым путём: `cliLaunch` — это и есть проверяемое
 * место. На Windows он оборачивает `.cmd` в оболочку с кавычками, на маке
 * отдаёт путь как есть; ошибка здесь стоила «Не удалось запустить Claude
 * Code» на каждой задаче при исправной установке.
 */
function запуститьКакДжарвис(
  путь: string,
  аргументы: string[],
  таймаутМс: number,
): Promise<{ код: number | null; вывод: string; беда: string | null }> {
  const запуск = cliLaunch(путь, аргументы);
  return new Promise((готово) => {
    const дитя = spawn(запуск.command, запуск.args, {
      shell: запуск.shell,
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    let вывод = '';
    дитя.stdout?.on('data', (кусок: Buffer) => { вывод += кусок.toString('utf8'); });
    дитя.stderr?.on('data', (кусок: Buffer) => { вывод += кусок.toString('utf8'); });
    дитя.on('error', (error: Error) => готово({ код: null, вывод, беда: error.message }));
    const таймер = setTimeout(() => {
      дитя.kill();
      готово({ код: null, вывод, беда: `не уложился в ${таймаутМс} мс` });
    }, таймаутМс);
    дитя.on('close', (код) => {
      clearTimeout(таймер);
      готово({ код, вывод, беда: null });
    });
  });
}

async function main(): Promise<void> {
  console.log(`Claude Code на ${process.platform}: путь до подписки\n`);

  // 1. Файл находится там, где его кладут менеджеры пакетов.
  const путь = resolveCli('claude');
  if (!путь) {
    const где = commonCliPaths('claude', os.homedir()).slice(0, 6).join('\n      ');
    записать('проба находит исполняемый файл', {
      прошло: false,
      почему: `не нашёл ни в PATH, ни в известных местах:\n      ${где}`,
    });
  } else {
    записать('проба находит исполняемый файл', { прошло: true });
    console.log(`    путь: ${путь}`);
  }

  // 2. Найденный файл ЗАПУСКАЕТСЯ — тем же способом, каким его запускает
  //    Джарвис. Проба версии раньше включала оболочку, а настоящие запуски
  //    нет, и «готов» соседствовал с отказом на каждой задаче.
  if (путь) {
    const ответ = await запуститьКакДжарвис(путь, ['--version'], 60_000);
    записать(
      'файл запускается тем же способом, каким его запускает Джарвис',
      ответ.код === 0
        ? { прошло: true }
        : { прошло: false, почему: ответ.беда ?? `код ${ответ.код}: ${ответ.вывод.trim().slice(0, 200)}` },
    );
    if (ответ.код === 0) console.log(`    версия: ${ответ.вывод.trim().split('\n')[0]}`);
  }

  // 3. Статус, который увидит человек в настройках.
  const статус = await cliStatus('claude');
  записать(
    'статус говорит «установлен», а не «не запускается»',
    статус.installed
      ? { прошло: true }
      : { прошло: false, почему: статус.error ?? 'installed: false' },
  );

  // 4. Вход честно назван неизвестным, а не выдуман.
  //
  // Ключей в окружении нет, файла учётных данных нет — и ответ обязан быть
  // 'unknown', а не true. Ложное «вошёл» отправило бы человека искать поломку
  // там, где её нет, а ложное «не вошёл» заперло бы рабочий бэкенд навсегда.
  const проба = await createClaudeProbe().status();
  записать(
    'вход назван честно, а не выдуман',
    проба.loggedIn === 'unknown' || проба.loggedIn === true
      ? { прошло: true }
      : { прошло: false, почему: `loggedIn: ${String(проба.loggedIn)}` },
  );
  console.log(`    вход: ${String(проба.loggedIn)}, пробовать можно: ${isUsable(проба.loggedIn)}`);

  // 5. Настоящий ход. Без подписки — «нечем мерить», и это не провал.
  //
  // Меряется здесь не ответ модели, а дорога до неё: процесс поднялся, принял
  // аргументы, чем-то ответил и не упал с EINVAL или ENOENT. Отличить это от
  // «ответил по делу» обязательно, иначе прогон зеленеет при нерабочем
  // Джарвисе — именно такие зелёные прогоны этот проект и ловит весь день.
  if (путь && статус.installed) {
    const ход = await запуститьКакДжарвис(
      путь,
      ['--print', 'Ответь одним словом: готов', '--output-format', 'json'],
      120_000,
    );
    const текст = ход.вывод.toLowerCase();
    const проситВойти =
      текст.includes('login') ||
      текст.includes('log in') ||
      текст.includes('authenticat') ||
      текст.includes('credit balance') ||
      текст.includes('api key') ||
      текст.includes('subscription');

    if (ход.код === 0) {
      записать('ход целиком: агент ответил', { прошло: true });
    } else if (проситВойти) {
      записать('ход целиком: агент ответил', {
        прошло: null,
        почему: 'CLI просит войти в аккаунт — подписки в прогоне нет, и это ожидаемо',
      });
    } else {
      записать('ход целиком: агент ответил', {
        прошло: false,
        почему: `код ${String(ход.код)}${ход.беда ? `, ${ход.беда}` : ''}: ${ход.вывод.trim().slice(0, 300)}`,
      });
    }
  }

  const прошло = итоги.filter((и) => и.ответ.прошло === true).length;
  const провал = итоги.filter((и) => и.ответ.прошло === false).length;
  const нечем = итоги.filter((и) => и.ответ.прошло === null).length;
  console.log(`\nВсего ${итоги.length}: прошло ${прошло}, не прошло ${провал}, нечем мерить ${нечем}`);

  // Коды разные: 1 — чинить программу, 2 — нечем мерить и чинить нечего.
  process.exit(провал > 0 ? 1 : нечем > 0 && прошло === 0 ? 2 : 0);
}

void main().catch((error: unknown) => {
  console.error('\nЗамер оборвался:', error instanceof Error ? error.message : String(error));
  process.exit(3);
});
