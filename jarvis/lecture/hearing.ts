/**
 * Слышно ли лектора: вердикт по первым минутам, а не вечером над пустым
 * конспектом.
 *
 * Судит по уверенности самого распознавания — средней логарифмической
 * вероятности его сегментов (`confidence`). Не по числу слов: замер «зала»
 * (`pnpm jarvis:lecture-room`, 30.09.2026) показал, что в гулкой аудитории
 * Whisper пишет те же два с половиной слова в секунду, что и в тихой комнате,
 * — только половина из них неверна. Не по громкости: тихий голос далёкого
 * лектора распознаётся почти без ошибок (1%), губит расшифровку гул зала. А
 * уверенность за ошибками идёт честно (150 с лекции на иврите, модель
 * ivrit.ai, средняя по всем кускам):
 *
 *     тихая комната                  0% ошибок   уверенность −0,05
 *     лектор тише на 26 дБ           1%          −0,05
 *     шум 20 дБ                      8%          −0,06
 *     гул 0,8 с                     12%          −0,09
 *     шум 10 дБ                     16%          −0,09
 *     шум 5 дБ                      26%          −0,16
 *     бормотание зала 10 дБ         29%          −0,17
 *     зал: гул, даль, шум           46%          −0,23
 *     гул 1,2 с, лектор далеко      49%          −0,31
 *     гул 1,5 с                     62%          −0,41
 *     плохой зал                    88%          −1,02
 *
 * Порог — между «терпимо» (с ошибками в каждом четвёртом слове модель
 * конспекта ещё восстанавливает смысл) и «половина слов мимо».
 */

import type { ChunkLevel } from './audioCut';

/**
 * Громкость, ниже которой кусок — тишина: выключенный микрофон, цифровой ноль.
 * Только такой кусок не распознаётся.
 *
 * Не по доле «громких» кадров, как было до 11.10.2026. Первая настоящая пара в
 * аудитории: лектор на −35 дБ, шум зала на −39, автоусиление сжало разницу до
 * 4–5 дБ, и «громче шума вдвое» не было почти ни одного кадра. 207 кусков из
 * 219 ушли в «тишину», а в них лежал чистый иврит с уверенностью −0,05 —
 * конспект полуторачасовой лекции вышел на 593 слова. Выдумка Whisper в паузе
 * стоит строку мусора в расшифровке, которую модель конспекта пропустит;
 * выброшенная речь стоит лекции.
 */
export const SILENT_CHUNK_DB = -55;

/** Кусок — тишина, распознавать его незачем. */
export function isSilentChunk(level: ChunkLevel): boolean {
  return level.speechDb < SILENT_CHUNK_DB;
}

/** Судить не раньше, чем набралось столько секунд речи. */
const СУДИТЬ_ПОСЛЕ_РЕЧИ_С = 45;
/** Судим по последним стольким секундам звука. */
const ОКНО_С = 120;
/** Уверенность ниже этой — «слышно плохо». */
export const BAD_CONFIDENCE = -0.2;
/** Выше этой — снова хорошо: зазор, чтобы вердикт не мигал. */
export const GOOD_CONFIDENCE = -0.13;

export interface HeardChunk {
  seconds: number;
  level: ChunkLevel;
  /** Что распознано; null — кусок пропущен как тишина. */
  text: string | null;
  /** Уверенность распознавания; нет — сервер её не дал, и судить нечем. */
  confidence?: number;
}

export class HearingMonitor {
  private куски: HeardChunk[] = [];
  private плохо = false;

  /** Кусок услышан. Вердикт — только когда он сменился: 'bad' или 'recovered'. */
  observe(chunk: HeardChunk): 'bad' | 'recovered' | null {
    this.куски.push(chunk);
    let всего = 0;
    for (let i = this.куски.length - 1; i >= 0; i -= 1) {
      всего += this.куски[i]?.seconds ?? 0;
      if (всего > ОКНО_С) {
        this.куски = this.куски.slice(i + 1);
        break;
      }
    }
    const оценка = this.оценка();
    if (оценка === null) return null;
    if (!this.плохо && оценка < BAD_CONFIDENCE) {
      this.плохо = true;
      return 'bad';
    }
    if (this.плохо && оценка > GOOD_CONFIDENCE) {
      this.плохо = false;
      return 'recovered';
    }
    return null;
  }

  /** Строка для журнала: на чём основан вердикт. */
  describe(): string {
    const о = this.оценка();
    return о === null ? 'мало речи для вердикта' : `уверенность ${о.toFixed(2)} по последним ${ОКНО_С} с`;
  }

  /**
   * Средняя уверенность по речи окна, взвешенная её длительностью; мало речи —
   * null. Речь — куски, в которых распознан текст: доля «громких» кадров в
   * зале с автоусилением — проценты (11.10.2026), и по ней 45 секунд речи не
   * набиралось никогда — вердикт молчал всю пару.
   */
  private оценка(): number | null {
    let речи = 0;
    let сумма = 0;
    for (const к of this.куски) {
      if (!к.text?.trim() || к.confidence === undefined || !Number.isFinite(к.confidence)) continue;
      const речь = к.seconds;
      речи += речь;
      сумма += к.confidence * речь;
    }
    // Лекция молчит (перерыв, лектор ещё не пришёл) или сервер не говорит
    // об уверенности — судить не о чем, и молчим, а не пугаем.
    if (речи < СУДИТЬ_ПОСЛЕ_РЕЧИ_С) return null;
    return сумма / речи;
  }
}
