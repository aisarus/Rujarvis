/**
 * Исправление того, что распознаватель слышит неправильно.
 *
 * Не догадки, а замеры. Двадцать четыре команды человека были синтезированы и
 * прогнаны через настоящий распознаватель; десять вернулись искажёнными:
 *
 *     «открой блендер»    → «Открой блиндер»
 *     «в блендере»        → «в Глендире»
 *     «открой хром»       → «Открой Хрум»
 *     «закрой стим»       → «Закрою Steam»
 *     «громче»            → «Уромче»
 *     «хватит»            → «Ватя»
 *     «вставь»            → «stuff»
 *
 * Разбрасывать эти написания по всем словарям — маршрутизатора, прямых команд,
 * запуска программ — значит забыть их в половине мест. Здесь одно место, через
 * которое проходит всё услышанное.
 *
 * ## Чего здесь не будет
 *
 * Догадок. Сюда попадает только то, что действительно наблюдалось, — иначе
 * слой начнёт «чинить» правильно расслышанные слова, и это будет хуже любой
 * ошибки распознавания: человек скажет одно, Джарвис сделает другое, и причину
 * будет не найти.
 */

import { matchesWakeToken } from './wakeWord';

/**
 * Замены по отдельному слову.
 *
 * Только те, которые не бывают самостоятельными русскими словами в этом
 * контексте: «блиндер» не значит ничего, а вот «стоп» трогать нельзя.
 */
const WORDS_AT_START: Record<string, string> = {
  // Закрытие и открытие: распознаватель слышит будущее время вместо
  // повелительного — «Закрою Steam» вместо «Закрой Steam».
  //
  // Только в начале фразы, и это не придирка. «Закрою» и «открою» — обычные
  // русские слова, а замена шла по всей фразе: «я потом сам закрою»
  // превращалось в «я потом сам закрой», после чего разбор видел просьбу и
  // Джарвис закрывал программу посреди разговора в комнате. Замер, ради
  // которого правило и завели, показывает эти слова только первыми.
  'закрою': 'закрой',
  'открою': 'открой',
  // Прошедшее время вместо повелительного: «Джарвис, открыл хром» — замер
  // синтезом Piper → Whisper base, 26.09.2026. Тоже настоящее слово, поэтому
  // тоже только в начале команды.
  'открыл': 'открой',
};

const WORDS: Record<string, string> = {
  // Blender во всех падежах, как его слышит распознаватель.
  'блиндер': 'блендер',
  'блэндер': 'блендер',
  'глендер': 'блендер',
  'блендир': 'блендер',
  'блиндире': 'блендере',
  'глендире': 'блендере',
  'блендире': 'блендере',
  'блиндера': 'блендера',

  // Chrome.
  'хрум': 'хром',
  'хроум': 'хром',


  // Закрытие: «Загрой спатифы» — замер синтезом Piper → Whisper base.
  'загрой': 'закрой',

  // Громкость.
  'уромче': 'громче',
  'громчи': 'громче',

  // ЧатГПТ.
  'джипиди': 'джипити',
  'джипетти': 'джипити',
  'джипет': 'джипити',
};

/**
 * Замены целой фразы.
 *
 * Для слов, которые сами по себе осмысленны и потому опасны: «Ватя» — имя, и
 * менять его посреди диктовки нельзя. Но сказанное в одиночку «Ватя» почти
 * наверняка означает «хватит».
 */
const WHOLE: Record<string, string> = {
  'ватя': 'хватит',
  'stuff': 'вставь',
  'staff': 'вставь',

  // Замолчать — красная линия, и она ломалась молча.
  //
  // В живом логе «Тешина» встречается четыре раза, «Тишина» — четыре. То есть
  // половину просьб замолчать распознаватель писал с ошибкой в одну букву, и
  // командой они не признавались вовсе: вместо тишины человек получал разговор.
  // Хуже обычной невыполненной команды — он просил замолчать, а ему отвечали.
  'тешина': 'тишина',
  'тишена': 'тишина',
  'тешена': 'тишина',
  // Замер синтезом Piper (Ирина) → Whisper small, 26.09.2026: «Дишина».
  'дишина': 'тишина',
  // «Молкин» — один раз, и это явно «молчи»: самостоятельным словом не бывает.
  'молкин': 'молчи',

  // По-английски Whisper теряет начальный согласный короткой команды: замер
  // синтезом Piper → Whisper base и turbo (scripts/voice-roundtrip.ts), оба
  // выдали «Top» вместо «Stop» и «Crawl/Roll down» вместо «Scroll down».
  // Только целой фразой: одно слово «top» помощнику не говорят, а «stop» —
  // красная линия.
  'top': 'stop',
  // Пауза — тоже красная линия. Замер синтезом Piper (Lessac) → Whisper base,
  // 26.09.2026: на «Pause» распознаватель выдал «4s». Целой фразой: так
  // человек Джарвису не говорит никогда.
  '4s': 'pause',
  // Там же: «Pro down» вместо «Scroll down».
  'pro down': 'scroll down',
  // Сдвиг границы слов: «прокрути вниз» → «прокрутив низ», замер base.
  //
  // Зеркальных «pro up» и «прокрутив верх» здесь нет нарочно: они не
  // наблюдались, а этот слой держит только замеренное.
  'прокрутив низ': 'прокрути вниз',
  'crawl down': 'scroll down',
  'roll down': 'scroll down',
  'crawl up': 'scroll up',
  'roll up': 'scroll up',
};

/**
 * Повтор одной и той же фразы — петля распознавателя, а не речь.
 *
 * На коротком звуке Whisper зацикливается: замер turbo дал «Silence. Silence.
 * Silence. Silence» на одно сказанное слово. Такая «тишина» не совпадала ни с
 * чем, и красная линия не срабатывала. Одна копия — то, что сказали.
 */
export function collapseRepeats(text: string): string {
  const parts = text
    .split(/[.!?,;]+/u)
    .map((part) => part.trim())
    .filter(Boolean);
  if (parts.length >= 2) {
    const first = parts[0]?.toLowerCase();
    if (parts.every((part) => part.toLowerCase() === first)) return parts[0] as string;
  }
  const words = text.trim().split(/\s+/u);
  if (words.length >= 3) {
    const first = words[0]?.toLowerCase().replace(/[.,!?;:]+$/u, '');
    if (words.every((word) => word.toLowerCase().replace(/[.,!?;:]+$/u, '') === first)) return first as string;
  }
  return text;
}

/**
 * Слипшиеся слова: распознаватель иногда теряет границу между ними.
 *
 * Границы заданы просмотром вперёд и назад, а не `\b`: в JavaScript он считает
 * словом только латиницу, и с кириллицей не срабатывает вовсе. На этой же
 * ловушке здесь уже терялась команда «тишина».
 */
const SPLITS: Array<[RegExp, string]> = [
  [/(?<!\p{L})кликсорок(?!\p{L})/giu, 'клик сорок'],
  [/(?<!\p{L})кликдесять(?!\p{L})/giu, 'клик десять'],
];

export function fixMishearings(input: string): string {
  if (!input.trim()) return input;
  const text = collapseRepeats(input);

  // Знаки препинания распознаватель ставит как хочет, и на смысл они не
  // влияют — для сравнения целой фразы их лучше снять.
  const bare = text.trim().toLowerCase().replace(/[.,!?;:]+$/u, '');
  const whole = WHOLE[bare];
  if (whole) return whole;

  let result = text;
  for (const [pattern, replacement] of SPLITS) {
    result = result.replace(pattern, replacement);
  }

  // Сначала — то, что чиним ТОЛЬКО в начале команды.
  //
  // Начало команды — первое слово, а если первым идёт имя, то первое ПОСЛЕ
  // имени. Прежде бралось буквально первое слово, и «Закрою Steam» правилось,
  // а «Джарвис, закрою Steam» — нет. Хотя второе и есть то, как говорят, пока
  // окно слушания закрыто.
  const вНачале = (слово: string): string | null => {
    const fixed = WORDS_AT_START[слово.toLowerCase()];
    if (!fixed) return null;
    return /^\p{Lu}/u.test(слово) ? fixed.charAt(0).toUpperCase() + fixed.slice(1) : fixed;
  };
  result = result.replace(
    /^(\s*)(\p{L}+)([\s,]+)(\p{L}+)/u,
    (целиком, пробелы: string, первое: string, между: string, второе: string) => {
      if (!matchesWakeToken(первое.toLowerCase())) return целиком;
      const fixed = вНачале(второе);
      return fixed ? пробелы + первое + между + fixed : целиком;
    },
  );
  result = result.replace(/^(\s*)(\p{L}+)/u, (целиком, пробелы: string, слово: string) => {
    const fixed = вНачале(слово);
    return fixed ? пробелы + fixed : целиком;
  });

  // Пословно, с сохранением знаков препинания вокруг слова.
  return result.replace(/\p{L}+/gu, (word) => {
    const fixed = WORDS[word.toLowerCase()];
    if (!fixed) return word;
    // Заглавная буква сохраняется: «Блиндер» в начале фразы остаётся с неё.
    return /^\p{Lu}/u.test(word) ? fixed.charAt(0).toUpperCase() + fixed.slice(1) : fixed;
  });
}
