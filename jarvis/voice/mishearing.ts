/**
 * Исправление того, что распознаватель слышит неправильно.
 *
 * Не догадки, а замеры. Двадцать четыре команды человека были синтезированы и
 * прогнаны через настоящий распознаватель; десять вернулись искажёнными:
 *
 *     «открой блендер»    → «Открой блиндер»
 *     «в блендере»        → «в Глендире»
 *     «открой хром»       → «Открой Хрум»
 *     «закрой стим»       → «Закрою Steam»
 *     «громче»            → «Уромче»
 *     «хватит»            → «Ватя»
 *     «вставь»            → «stuff»
 *
 * Разбрасывать эти написания по всем словарям — маршрутизатора, прямых команд,
 * запуска программ — значит забыть их в половине мест. Здесь одно место, через
 * которое проходит всё услышанное.
 *
 * ## Чего здесь не будет
 *
 * Догадок. Сюда попадает только то, что действительно наблюдалось, — иначе
 * слой начнёт «чинить» правильно расслышанные слова, и это будет хуже любой
 * ошибки распознавания: человек скажет одно, Джарвис сделает другое, и причину
 * будет не найти.
 */

/**
 * Замены по отдельному слову.
 *
 * Только те, которые не бывают самостоятельными русскими словами в этом
 * контексте: «блиндер» не значит ничего, а вот «стоп» трогать нельзя.
 */
const WORDS: Record<string, string> = {
  // Blender во всех падежах, как его слышит распознаватель.
  'блиндер': 'блендер',
  'блэндер': 'блендер',
  'глендер': 'блендер',
  'блендир': 'блендер',
  'блиндире': 'блендере',
  'глендире': 'блендере',
  'блендире': 'блендере',
  'блиндера': 'блендера',

  // Chrome.
  'хрум': 'хром',
  'хроум': 'хром',

  // Закрытие: распознаватель слышит будущее время вместо повелительного.
  'закрою': 'закрой',
  'открою': 'открой',

  // Громкость.
  'уромче': 'громче',
  'громчи': 'громче',

  // ЧатГПТ.
  'джипиди': 'джипити',
  'джипетти': 'джипити',
  'джипет': 'джипити',
};

/**
 * Замены целой фразы.
 *
 * Для слов, которые сами по себе осмысленны и потому опасны: «Ватя» — имя, и
 * менять его посреди диктовки нельзя. Но сказанное в одиночку «Ватя» почти
 * наверняка означает «хватит».
 */
const WHOLE: Record<string, string> = {
  'ватя': 'хватит',
  'stuff': 'вставь',
  'staff': 'вставь',

  // Замолчать — красная линия, и она ломалась молча.
  //
  // В живом логе «Тешина» встречается четыре раза, «Тишина» — четыре. То есть
  // половину просьб замолчать распознаватель писал с ошибкой в одну букву, и
  // командой они не признавались вовсе: вместо тишины человек получал разговор.
  // Хуже обычной невыполненной команды — он просил замолчать, а ему отвечали.
  'тешина': 'тишина',
  'тишена': 'тишина',
  'тешена': 'тишина',
  // «Молкин» — один раз, и это явно «молчи»: самостоятельным словом не бывает.
  'молкин': 'молчи',
};

/**
 * Слипшиеся слова: распознаватель иногда теряет границу между ними.
 *
 * Границы заданы просмотром вперёд и назад, а не `\b`: в JavaScript он считает
 * словом только латиницу, и с кириллицей не срабатывает вовсе. На этой же
 * ловушке здесь уже терялась команда «тишина».
 */
const SPLITS: Array<[RegExp, string]> = [
  [/(?<!\p{L})кликсорок(?!\p{L})/giu, 'клик сорок'],
  [/(?<!\p{L})кликдесять(?!\p{L})/giu, 'клик десять'],
];

export function fixMishearings(text: string): string {
  if (!text.trim()) return text;

  // Знаки препинания распознаватель ставит как хочет, и на смысл они не
  // влияют — для сравнения целой фразы их лучше снять.
  const bare = text.trim().toLowerCase().replace(/[.,!?;:]+$/u, '');
  const whole = WHOLE[bare];
  if (whole) return whole;

  let result = text;
  for (const [pattern, replacement] of SPLITS) {
    result = result.replace(pattern, replacement);
  }

  // Пословно, с сохранением знаков препинания вокруг слова.
  return result.replace(/\p{L}+/gu, (word) => {
    const fixed = WORDS[word.toLowerCase()];
    if (!fixed) return word;
    // Заглавная буква сохраняется: «Блиндер» в начале фразы остаётся с неё.
    return /^\p{Lu}/u.test(word) ? fixed.charAt(0).toUpperCase() + fixed.slice(1) : fixed;
  });
}
