/**
 * Склейка реплик в одну мысль.
 *
 * Люди не говорят командами. Они говорят так:
 *
 *     «У тебя в картинках лежит красная сфера»
 *     «Сделай в блендере её 3d модель»
 *
 * Джарвис разрезал это на две независимые задачи, и вторая честно не знала,
 * что такое «её». Это видно в журнале: два «Работаю» подряд с интервалом в
 * сорок секунд, и ни одна задача не имела контекста другой.
 *
 * Здесь пауза после фразы считается частью фразы. Пока человек может
 * продолжить — ждём; замолчал — отдаём накопленное целиком.
 *
 * ## Чего это стоит и почему стоит
 *
 * Задержка. Две с половиной секунды к каждой задаче агенту — и это осознанная
 * плата: сама задача идёт полминуты, а неверно понятая не идёт никуда.
 *
 * К прямым командам это не применяется: «прокрути вниз» обязано срабатывать
 * мгновенно, и ждать там нечего — мысль уже закончена.
 */

/** Сколько тишины считать концом мысли. */
const DEFAULT_GAP_MS = 2_500;

/**
 * Сколько тишины ждать, когда человек предупредил, что говорит длинно.
 *
 * Пять секунд — столько он назвал сам. Это много для обычной команды и в самый
 * раз для мысли, которую формулируют на ходу: между «сделай сайт по моей
 * биографии» и «и чтобы там была физика» пауза бывает длиннее двух секунд.
 */
const LONG_GAP_MS = 5_000;

export interface UtteranceBufferOptions {
  gapMs?: number;
  now?: () => number;
}

export class UtteranceBuffer {
  private readonly gapMs: number;
  private readonly now: () => number;
  private parts: string[] = [];
  private lastAt = 0;
  private hasRequest = false;
  private cutOff = false;
  private longSpeech = false;

  constructor(options: UtteranceBufferOptions = {}) {
    this.gapMs = options.gapMs ?? DEFAULT_GAP_MS;
    this.now = options.now ?? Date.now;
  }

  /**
   * Добавляет услышанное к текущей мысли.
   *
   * `unfinished` — запись закрылась не по тишине, а упёршись в свой потолок.
   * Это не догадка о грамматике, а факт от того, кто держал микрофон: человек
   * в этот момент ещё говорил.
   */
  push(text: string, options: { unfinished?: boolean } = {}): void {
    const trimmed = text.trim();
    if (!trimmed) return;

    this.parts.push(trimmed);
    if (looksLikeRequest(trimmed)) this.hasRequest = true;
    this.cutOff = options.unfinished === true;
    // Срок отсчитывается от последней фразы, а не от первой: человек, который
    // говорит долго, не должен быть перебит на середине.
    this.lastAt = this.now();
  }

  /**
   * Человек предупредил, что говорит длинно.
   *
   * Меняются две вещи. Пауза до пяти секунд — её он назвал сам. И отменяется
   * правило «есть глагол просьбы — отдаём сразу»: именно оно рубило длинные
   * фразы пополам, потому что «сделай» встречается в середине мысли не реже,
   * чем в конце.
   */
  set listenLong(on: boolean) {
    this.longSpeech = on;
  }

  get listenLong(): boolean {
    return this.longSpeech;
  }

  private get gap(): number {
    return this.longSpeech ? LONG_GAP_MS : this.gapMs;
  }

  /**
   * Готова ли мысль.
   *
   * Обычно — когда человек замолчал. Но если в сказанном уже есть просьба,
   * ждать нечего: «создай в блендере красную сферу» — законченная команда, и
   * две с половиной секунды ожидания здесь это просто задержка, которую
   * человек чувствует на каждой фразе.
   *
   * Ждём только контекст без просьбы: «у тебя в картинках лежит сфера» само по
   * себе не задача, и продолжение к нему почти наверняка будет.
   */
  isComplete(): boolean {
    if (this.parts.length === 0) return false;
    // Обрыв записи важнее любого признака законченности: глагол просьбы в
    // «сделай вместо зелёной сферы мультяшную красивую разноцветную» есть, а
    // мысль обрывается на прилагательном. Ждём продолжения — но не вечно:
    // человека могли обрезать и на последнем слове.
    if (this.cutOff) return this.now() - this.lastAt >= this.gap;
    if (this.hasRequest && !this.longSpeech) return true;
    return this.now() - this.lastAt >= this.gap;
  }

  /** Сколько ещё ждать. Для таймера у вызывающего. */
  msUntilComplete(): number {
    if (this.parts.length === 0) return Number.POSITIVE_INFINITY;
    if (this.hasRequest && !this.cutOff && !this.longSpeech) return 0;
    return Math.max(0, this.gap - (this.now() - this.lastAt));
  }

  /** Что накоплено, не забирая. */
  get pending(): string {
    return join(this.parts);
  }

  /** Забирает мысль целиком и начинает новую. */
  take(): string {
    const text = join(this.parts);
    this.parts = [];
    this.lastAt = 0;
    this.hasRequest = false;
    this.cutOff = false;
    // Длинная мысль кончилась — дальше снова обычный разговор. Человек сказал
    // «диктую» про одно сообщение, а не про весь вечер.
    this.longSpeech = false;
    return text;
  }
}

/**
 * Есть ли в сказанном просьба.
 *
 * Глагол просьбы или вопросительное слово в начале — признак того, что мысль
 * закончена и ждать продолжения незачем.
 */
function looksLikeRequest(text: string): boolean {
  const words = text
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .replace(/[^\p{L}\p{N}\s-]/gu, ' ')
    .split(/\s+/u)
    .filter(Boolean);

  if (words.length === 0) return false;
  if (QUESTION_OPENERS.includes(words[0] as string)) return true;
  return words.some((word) => REQUEST_VERBS.includes(word));
}

/** Глаголы, после которых фраза уже команда. */
const REQUEST_VERBS = [
  'открой', 'закрой', 'запусти', 'включи', 'выключи', 'убей', 'переключись',
  'сделай', 'создай', 'нарисуй', 'начерти', 'построй', 'собери', 'отрендери',
  'найди', 'поищи', 'покажи', 'напиши', 'запиши', 'посчитай', 'переделай',
  'повтори', 'продолжай', 'останови', 'отмени', 'поставь', 'отправь',
  'прочитай', 'переведи', 'скачай', 'сохрани', 'удали', 'перенеси', 'добавь',
  'убери', 'проверь', 'скажи', 'смени', 'поменяй', 'исправь', 'замени',
  // Неопределённая форма: распознаватель слышит «поменять» вместо «поменяй»,
  // и фраза без этого ждала лишние две с половиной секунды.
  'открыть', 'закрыть', 'запустить', 'сделать', 'создать', 'нарисовать',
  'найти', 'показать', 'написать', 'сохранить', 'удалить', 'поменять',
  'изменить', 'исправить', 'отправить', 'проверить',
];

/** Вопросительные слова — только в начале фразы. */
const QUESTION_OPENERS = [
  'что', 'где', 'когда', 'сколько', 'какой', 'какая', 'как', 'почему', 'кто',
  'куда', 'зачем', 'можешь', 'можно', 'умеешь',
];

/**
 * Собирает части во фразу, которую поймёт и человек, и модель.
 *
 * Границы предложений сохраняются: без них «сфера лежит в картинках сделай
 * модель» читается как одна сбивчивая строка, и модель теряет то же, что
 * потерял бы человек.
 */
function join(parts: readonly string[]): string {
  if (parts.length === 0) return '';

  return parts.reduce((text, part) => {
    if (!text) return part;
    const ended = /[.!?…]$/u.test(text);
    const next = part.charAt(0).toUpperCase() + part.slice(1);
    return `${text}${ended ? '' : '.'} ${next}`;
  });
}

export { DEFAULT_GAP_MS, LONG_GAP_MS };
