/**
 * Красная линия обязана доходить в любой формулировке.
 *
 * Списков заполнителей было три, и все разные: свой в разборе команд, свой в
 * прерываниях, свой в просьбе замолчать. Комментарий в `noise.ts` предупреждал
 * ровно об этом — «четвёртый список слов остановки это четвёртое место, где он
 * разойдётся с остальными».
 *
 * Замер 20.09.2026: из 36 обёрнутых форм «стоп» и «тишины» не доходили 24.
 * «Быстро замолчи», «а теперь тишина», «хватит сейчас» — человек просил
 * прекратить, и его не слышали.
 */

import { describe, expect, it } from 'vitest';

import { stripFiller } from './filler';
import { matchVoiceControl } from './interrupts';
import { isSilenceRequest } from './noise';

const ОБЁРТКИ = [
  (s: string) => `быстро ${s}`,
  (s: string) => `а теперь ${s}`,
  (s: string) => `можешь ${s}`,
  (s: string) => `ну ${s} пожалуйста`,
  (s: string) => `джарвис ${s}`,
  (s: string) => `${s} сейчас`,
  (s: string) => `${s} блядь`,
];

const КРАСНЫЕ = ['стоп', 'хватит', 'тишина', 'замолчи', 'отмена', 'стой', 'пауза'];

describe('остановка доходит в любой обёртке', () => {
  for (const команда of КРАСНЫЕ) {
    it.each(ОБЁРТКИ.map((об) => об(команда)))('«%s» — красная линия', (сказано) => {
      const дошло = matchVoiceControl(сказано) !== null || isSilenceRequest(сказано);
      expect(дошло).toBe(true);
    });
  }
});

describe('лишнего не отсекается', () => {
  // Каждый из этих случаев — цена ошибки в обратную сторону.
  it('имя после предлога — это окно, а не обращение', () => {
    // «Переключись на джарвис» ищет окно с таким названием. Сняв имя, получим
    // «переключись на» и потеряем команду целиком. Поймано проверкой.
    expect(stripFiller(['переключись', 'на', 'джарвис'])).toEqual([
      'переключись',
      'на',
      'джарвис',
    ]);
  });

  it('имя по краям — обращение', () => {
    expect(stripFiller(['джарвис', 'сверни'])).toEqual(['сверни']);
    expect(stripFiller(['сверни', 'джарвис'])).toEqual(['сверни']);
  });

  it('однобуквенные слова внутри — это клавиши', () => {
    // «Нажми а» — буква А. В начале фразы клавишей она быть не может.
    expect(stripFiller(['нажми', 'а'])).toEqual(['нажми', 'а']);
    expect(stripFiller(['а', 'сверни'])).toEqual(['сверни']);
  });

  it('фраза из одних заполнителей не исчезает', () => {
    // Решать её судьбу — не дело этого слоя.
    expect(stripFiller(['ну', 'вот']).length).toBeGreaterThan(0);
  });

  // Задача, лишь СОДЕРЖАЩАЯ слово остановки, прерыванием не становится.
  it('«останови сервис после тестов» — работа, а не прерывание', () => {
    expect(matchVoiceControl('останови сервис после тестов')).toBeNull();
  });

  // «Тише» — громкость, а не сон. На этом уже терялась команда.
  it('«тише звук» — не просьба замолчать', () => {
    expect(isSilenceRequest('тише звук')).toBe(false);
  });
});
