/**
 * Слова, которые ничего не добавляют к сказанному.
 *
 * ## Зачем отдельный файл
 *
 * Списков было три, и все разные: свой в разборе команд, свой в прерываниях,
 * свой в просьбе замолчать. Комментарий в `noise.ts` предупреждал ровно об
 * этом — «четвёртый список слов остановки это четвёртое место, где он
 * разойдётся с остальными», — и расхождение случилось.
 *
 * Замер 20.09.2026: из 36 обёрнутых форм команд остановки и тишины («быстро
 * замолчи», «а теперь тишина», «хватит сейчас») не доходили 24. Разбор команд
 * такие обёртки снимать умел, а прерывания о них не знали. То есть красная
 * линия — «стоп и тишина должны работать всегда» — была дырявой в двух третях
 * естественных формулировок.
 *
 * ## Что здесь есть и чего нет
 *
 * Здесь общая часть: слова, которые в РЕЧИ не значат ничего нигде. Свои
 * добавки у слоёв остаются, и это не небрежность: «да», «нет» и «всё»
 * безвредны рядом с «стоп», но «показывай всё» — настоящая команда, и выбросив
 * из неё «всё», мы получим другую.
 */

/**
 * Заполнители, безвредные в любом месте фразы.
 *
 * Проверка простая: если слово выбросить, просьба остаётся той же. «Быстро
 * сверни» — это «сверни»; «сверни окно» — уже нет.
 */
export const SPEECH_FILLER: readonly string[] = [
  // Вежливость.
  'пожалуйста', 'плиз',
  // Затычки речи.
  'ну', 'э', 'эй', 'ой', 'вот', 'же', 'ка', 'там', 'давай',
  // Ругань как усиление: смысла не несёт, а мешает совпадению.
  'блин', 'блядь', 'бля',
  // Время и образ действия: к тому, ЧТО сделать, не добавляют ничего.
  'теперь', 'сейчас', 'уже', 'вообще', 'быстро', 'быстренько', 'просто', 'короче',
  // То же по-английски. Слова выбраны так же: выбросив их, получаем ту же просьбу.
  'please', 'pls', 'um', 'uh', 'umm', 'uhm', 'er', 'hmm', 'hey', 'just', 'quickly', 'now',
];

/**
 * Слова, которые ничего не значат по КРАЯМ фразы, но значат внутри.
 *
 * Обращение по имени: «Джарвис, сверни» и «сверни, Джарвис» — это «сверни».
 * А «переключись на Джарвис» — это переход в окно с таким названием, и выбросив
 * имя оттуда, мы получим «переключись на» и потеряем команду. Так и вышло,
 * когда имя попало в общий список: сквозная проверка покраснела на первом же
 * прогоне.
 */
export const EDGE_FILLER: readonly string[] = ['джарвис', 'жарвис', 'джарвес', 'jarvis', 'jervis'];

/**
 * Предлоги, после которых идёт не обращение, а цель.
 *
 * «Сверни, джарвис» — обращение, снимаем. «Переключись НА джарвис» — имя окна,
 * и снять его значит получить «переключись на» и потерять команду целиком.
 * Проверка поймала это на первом же прогоне после того, как имя попало в общий
 * список.
 */
const BEFORE_TARGET = [
  'на', 'в', 'во', 'к', 'ко', 'по', 'до', 'из', 'от', 'про', 'с', 'со',
  'to', 'into', 'on', 'onto', 'at', 'in', 'from', 'about', 'with',
];

/**
 * Слова, которые ничего не значат ТОЛЬКО в начале фразы.
 *
 * «А» и «и» — однобуквенные слова, и они же имена клавиш: выбросив «а» где
 * угодно, мы превратим «нажми а» в «нажми» и потеряем нажатие. В начале фразы
 * клавишей они быть не могут — там это частица: «а теперь сверни».
 *
 * «Можешь» и «может» здесь по другой причине: вежливая просьба — та же
 * команда, и отвечать на неё через агента значит платить полминуты за
 * вежливость.
 */
export const LEADING_FILLER: readonly string[] = [
  'а', 'и', 'можешь', 'может', 'слушай', 'слышь',
  // «Can you open chrome», «so, close it»: вежливая форма той же команды.
  'and', 'so', 'okay', 'ok', 'can', 'could', 'would', 'will', 'you', 'listen',
];

/**
 * Фраза без заполнителей.
 *
 * Общие — отовсюду: живой случай «что ты СЕЙЧАС делаешь» не совпадал, потому
 * что снимали только по краям. Начальные — только с начала, по причине выше.
 *
 * `extra` — добавка слоя. Она применяется наравне с общими, но остаётся его
 * собственным делом.
 */
export function stripFiller(words: readonly string[], extra: readonly string[] = []): string[] {
  let result = words.filter(Boolean);

  const atStart = (word: string): boolean =>
    LEADING_FILLER.includes(word) || EDGE_FILLER.includes(word) ||
    SPEECH_FILLER.includes(word) || extra.includes(word);

  while (result.length > 1 && atStart(result[0] as string)) result = result.slice(1);

  // Обращение в конце — то же обращение: «сверни, Джарвис». Но не после
  // предлога: там стоит цель, а не тот, к кому обращаются.
  while (
    result.length > 1 &&
    EDGE_FILLER.includes(result[result.length - 1] as string) &&
    !BEFORE_TARGET.includes(result[result.length - 2] as string)
  ) {
    result = result.slice(0, -1);
  }

  const drop = new Set([...SPEECH_FILLER, ...extra]);
  const kept = result.filter((word) => !drop.has(word));
  // Пустого результата не бывает: фраза из одних заполнителей — это всё же то,
  // что человек сказал, и решать её судьбу не здесь.
  return kept.length > 0 ? kept : result;
}
