import { describe, expect, it } from 'vitest';

import { startSource } from './installed';
import { LAUNCH_NAMES } from './launch';

const onWindows = process.platform === 'win32';

/**
 * Каждое имя из пусковой таблицы Windows обязана уметь разрешить.
 *
 * Механизм для этого был — `startSource` умеет ответить «протокол», «PATH»,
 * «реестр», «не знаю» или «нет такого», — но про саму таблицу его никто не
 * спрашивал. Из-за этого 26.09.2026 до живого человека доехала моя поломка:
 * я поменял `msedge` на `edge` и `calc` на `calculator`, приняв значения этой
 * таблицы за слова для поиска по названиям установленных программ.
 *
 * Они не слова, а имена для `start`. Живой прогон: «Открой Edge» → «запустил
 * edge за 11 мс» → и ничего не открылось. `edge.exe` не существует, а `start`
 * возвращает успех, что бы ему ни дали, — Джарвис бодро сказал «Открываю Edge»
 * и не сделал ничего. Ровно тот случай, который AGENTS.md называет багом:
 * отчёт об успехе того, чего не было.
 *
 * Мои тесты этого не поймали, потому что сверяли значение таблицы с записанным
 * рядом значением. Такая сверка ловит опечатку, но не ложную идею: я записал
 * рядом то же неверное. Единственный, кто может возразить, — сама Windows, и
 * теперь её спрашивают.
 */
/**
 * Имена, которые есть на ЛЮБОЙ Windows.
 *
 * Только о них проверка может судить уверенно. Замер 26.09.2026 на живой
 * машине: `firefox`, `spotify` и `wordpad` не разрешились — но не потому, что
 * псевдоним плохой, а потому что этих программ здесь нет (а WordPad Microsoft
 * из Windows 11 и вовсе убрала). Требовать их значит объявлять поломкой чужой
 * набор программ.
 */
const ВСЕГДА_ЕСТЬ = ['msedge', 'calc', 'notepad', 'explorer', 'ms-settings:'];

describe('пусковые имена Windows умеет разрешить', () => {
  it.skipIf(!onWindows)(
    'встроенное в Windows разрешается — на этом и споткнулись',
    async () => {
      const нет: string[] = [];
      const откуда: string[] = [];
      for (const цель of ВСЕГДА_ЕСТЬ) {
        const ответ = await startSource(цель);
        // «Не знаю» — третий ответ, а не первый: если спросить не вышло, это
        // про машину, а не про таблицу.
        if (ответ === null) нет.push(цель);
        else откуда.push(`${цель}←${ответ}`);
      }

      expect(
        нет,
        `Windows не знает, чем это запустить: ${нет.join(', ')}. Разрешились: ${откуда.join(', ')}`,
      ).toEqual([]);
    },
    180_000,
  );

  it.skipIf(!onWindows)(
    'каждое имя из таблицы либо разрешается, либо просто не установлено',
    async () => {
      // Эта проверка не валит на ненайденном: отличить «плохой псевдоним» от
      // «программы нет на этой машине» одним ответом `startSource` нельзя, и
      // притворяться, что можно, — хуже, чем сказать прямо.
      //
      // Она нужна за другим: печатает картину целиком, и по ней видно, что
      // сломалось, когда упадёт проверка выше. Замер той же машины:
      //   chrome←реестр, msedge←реестр, calc←PATH, notepad←PATH, wt←PATH,
      //   code←PATH, winword←реестр, excel←реестр, ms-settings:←протокол,
      //   а firefox, spotify и wordpad не установлены.
      const цели = [...new Set(LAUNCH_NAMES.map(([, цель]) => цель))];
      const разрешились: string[] = [];
      const нет: string[] = [];
      for (const цель of цели) {
        const ответ = await startSource(цель);
        if (ответ === null) нет.push(цель);
        else разрешились.push(`${цель}←${ответ}`);
      }
      console.log(`    разрешились: ${разрешились.join(', ')}`);
      console.log(`    не установлены на этой машине: ${нет.join(', ') || '(нет таких)'}`);

      // Мерить было чем: если не разрешилось НИ ОДНО имя, дело не в таблице.
      expect(разрешились.length, 'ни одно имя не разрешилось — мерить было нечем').toBeGreaterThan(0);
    },
    180_000,
  );

  it.skipIf(!onWindows)(
    'Edge и калькулятор разрешаются — на них и споткнулись',
    async () => {
      // Отдельно и по именам: эти две строки уже один раз уехали сломанными.
      for (const цель of ['msedge', 'calc']) {
        expect(await startSource(цель), `${цель} не разрешается`).not.toBeNull();
      }
    },
    120_000,
  );
});
