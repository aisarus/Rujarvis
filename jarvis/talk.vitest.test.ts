import { describe, expect, it } from 'vitest';

import { BackendManager } from './backends/manager';
import { EventChannel } from './backends/process';
import type { AgentBackend, BackendEvent, BackendResult, BackendRun } from './backends/types';
import { DEFAULT_JARVIS_SETTINGS, JarvisCore, isTalk } from './core';
import { JarvisMemory } from './memory/store';
import { route } from './router/router';
import { TaskManager } from './tasks/manager';
import { WorldStateStore, selectWorldStateLines } from './context/worldState';

/** Как решение выглядит после роутера на настоящей фразе. */
function решение(said: string) {
  return route(said, { basePermissions: { canRunCode: true } as never });
}

describe('разговор отличается от поручения', () => {
  // Человек сказал прямо: «он не понимает концепцию вопросов и не может на них
  // по факту отвечать». Так и было: намерение «разговор» доходило до создания
  // задачи и превращалось в двадцать секунд работы агента с инструментами —
  // ради ответа на вопрос о книге.
  it.each([
    'кто написал войну и мир',
    'сколько будет двести на триста',
    'что думаешь',
    'а почему ты так сделал',
    'ты меня слышишь',
  ])('«%s» — разговор, отвечаем словами', (said) => {
    expect(isTalk(решение(said))).toBe(true);
  });

  // Граница первая: поручение остаётся поручением, даже если звучит мягко.
  it.each([
    'открой блокнот',
    'создай сферу в блендере',
    'напиши письмо Ивану',
    'можешь открыть блокнот',
  ])('«%s» — работа, а не разговор', (said) => {
    expect(isTalk(решение(said))).toBe(false);
  });

  // Граница вторая, и она тоньше: это вопрос, но ответить на него без доступа
  // к файлам нельзя. Значит работа, несмотря на вопросительное слово.
  it('вопрос, требующий доступа, остаётся работой', () => {
    const d = решение('что у меня в папке загрузки');
    expect(d.needs.length).toBeGreaterThan(0);
    expect(isTalk(d)).toBe(false);
  });

  it('вопрос про экран тоже работа: надо посмотреть', () => {
    expect(isTalk(решение('что это за окно'))).toBe(false);
  });

  // Погода — не разговор, хотя звучит как он. Ответить на неё из памяти
  // значит соврать: нужен интернет, а значит это работа.
  it('вопрос, требующий интернета, остаётся работой', () => {
    const d = решение('какая погода в Тель-Авиве');
    expect(d.needs).toContain('web');
    expect(isTalk(d)).toBe(false);
  });
});

describe('вопрос интонацией', () => {
  // В русском вопрос без вопросительного слова отличается ТОЛЬКО интонацией.
  // Распознаватель слышит её и записывает знаком вопроса — раньше мы стирали
  // его своими руками вместе с остальными знаками.
  it.each([
    'ты сделал ракету?',
    'всё нормально?',
    'получилось?',
    'понятно?',
  ])('«%s» — разговор', (said) => {
    expect(isTalk(решение(said))).toBe(true);
  });

  it('знак делает вопросом то, что иначе им не выглядит', () => {
    expect(решение('ты сделал ракету?').intent).toBe('chat');
    expect(решение('сделай ракету в блендере').intent).toBe('make');
  });

  // «Это правильно?» опирается на сказанное раньше — и это по-прежнему
  // разговор, а не работа. Ответ лежит в состоянии мира: предыдущая реплика,
  // предыдущий результат, недавние окна. Агент для этого не нужен.
  it.each(['это правильно?', 'а почему не получилось?', 'почему это не работает?'])(
    '«%s» — разговор с опорой на случившееся',
    (сказано) => {
      const d = решение(сказано);
      expect(isTalk(d)).toBe(true);
      expect(d.needs).toContain('memory');
    },
  );

  // Граница: названо конкретное из мира кода — значит работа, как и было.
  it('вопрос про тесты остаётся работой', () => {
    expect(isTalk(решение('почему не проходят тесты?'))).toBe(false);
  });

  it('знак не мешает просьбе остаться просьбой', () => {
    // «Откроешь блокнот?» — вежливая просьба, а не вопрос о мироустройстве.
    // Она требует действия, значит остаётся работой.
    const d = решение('откроешь блокнот?');
    expect(d.needs.length).toBeGreaterThan(0);
    expect(isTalk(d)).toBe(false);
  });
});

/**
 * Разговор складывается в разговор.
 *
 * Две поломки разом, и обе делали беседу невозможной. Ответ, сказанный в
 * разговоре, нигде не сохранялся — записывался только итог задачи, — поэтому
 * «а сколько ему было лет» спрашивать было не о ком. А «предыдущая реплика
 * пользователя» была НЫНЕШНЕЙ: запись делается в начале разбора, и модель
 * получала свой же вопрос выданным за предысторию.
 */
describe('беседа помнит саму себя', () => {
  it('сказанное раньше становится предыдущим, а не нынешним', () => {
    const мир = new WorldStateStore();
    мир.noteUtterance('кто написал войну и мир');
    expect(мир.snapshot().previousUtterance).toBeUndefined();

    мир.noteUtterance('а сколько ему было лет');
    expect(мир.snapshot().previousUtterance).toBe('кто написал войну и мир');
  });

  it('контекст показывает прошлый вопрос, а не текущий', () => {
    const мир = new WorldStateStore();
    мир.noteUtterance('кто написал войну и мир');
    мир.noteResult({ text: 'Лев Толстой.', ok: true, backend: 'разговор' });
    мир.noteUtterance('а сколько ему было лет');

    const строки = selectWorldStateLines(мир.snapshot(), { needsWorldState: true });
    const всё = строки.join(' ');
    expect(всё).toContain('кто написал войну и мир');
    expect(всё).toContain('Лев Толстой');
    expect(всё).not.toContain('а сколько ему было лет');
  });
});

/**
 * Вопрос во время работы — это вопрос, а не поправка.
 *
 * Человек спросил «ты понял что надо делать?» пока шла работа, и получил
 * «Учту» и тишину: голосовой мост во время работы кладёт сказанное в ящик
 * поправок, где ответа не предусмотрено вовсе.
 *
 * Отличать одно от другого должен разбор, а не список фраз: поправка велит
 * что-то сделать, вопрос — нет.
 */
describe('во время работы: вопрос или поправка', () => {
  const спрошено = (сказано: string): boolean => {
    const d = решение(сказано);
    return d.asks && isTalk(d);
  };

  it.each([
    'ты понял что надо делать?',
    // Без знака — тот же вопрос. Замерено: large-v3-turbo пишет эту фразу с
    // ТОЧКОЙ, все три испробованных варианта. Опираться на знак нельзя.
    'ты понял что надо делать',
    'ты помнишь про крышу',
    'ты уверен',
    'ты меня слышишь',
    'что ты сейчас делаешь?',
    'далеко ещё?',
    'а почему так долго?',
  ])('«%s» — вопрос, на него отвечают', (сказано) => {
    expect(спрошено(сказано)).toBe(true);
  });

  // Граница: вопрос, на который нельзя ответить не посмотрев. «Ты видишь
  // ошибку?» требует экрана, а значит это работа, несмотря на знак вопроса, —
  // и в ящик такое ложится правильно.
  it('вопрос, требующий экрана, остаётся работой', () => {
    expect(спрошено('ты видишь ошибку?')).toBe(false);
  });

  // Граница: «ты» в начале ещё не делает фразу вопросом.
  it('«ты должен сделать крышу синей» — поправка', () => {
    expect(спрошено('ты должен сделать крышу синей')).toBe(false);
  });

  // И вопрос, требующий доступа к файлам, тоже остаётся работой.
  it('«ты знаешь где файл» — работа', () => {
    expect(спрошено('ты знаешь где файл')).toBe(false);
  });

  it.each([
    'крышу сделай синей',
    'сделай ему уши побольше',
    'нет смотри он левой рукой чешет лоб',
    'добавь ему шляпу',
    'открой блендер',
  ])('«%s» — поправка, её кладут в ящик', (сказано) => {
    expect(спрошено(сказано)).toBe(false);
  });

  // Знак вопроса — единственный признак, когда вопросительного слова нет в
  // начале. Раньше он проверялся отдельным параметром, которого в поле `asks`
  // никто не передавал: два механизма на одно и то же, и работал не тот.
  it('знак решает там, где слова молчат', () => {
    expect(решение('ты понял что надо делать?').asks).toBe(true);
    expect(решение('далеко ещё?').asks).toBe(true);
  });
});

/**
 * Ответ разговора должен запоминаться САМ, а не рукой проверки.
 *
 * Замечания CodeRabbit (кусок 3, PR №42): обе проверки ниже раньше обходили
 * настоящий путь — одна звала `noteResult` сама, другая считала признак
 * вопроса, не проводя реплику через обработчик. Перестань обработчик работать
 * — они остались бы зелёными, а человек не получил бы ответа.
 */
describe('вопрос во время работы проходит настоящим путём', () => {
  function ядро(ответ: string): { core: JarvisCore; world: WorldStateStore; сказано: string[] } {
    const сказано: string[] = [];
    const result: BackendResult = {
      ok: true,
      backend: 'claude-code',
      text: ответ,
      durationMs: 1,
      filesChanged: [],
      commands: [],
    };
    const backend = {
      id: 'claude-code' as const,
      name: 'claude-code',
      capabilities: new Set(),
      checkAvailability: async () => ({
        id: 'claude-code' as const,
        installed: true,
        authenticated: true,
        ready: true,
        checkedAt: 0,
      }),
      run: (): BackendRun => {
        const channel = new EventChannel<BackendEvent>();
        channel.push({ type: 'completed', backend: 'claude-code', result });
        channel.close();
        return {
          id: 'r',
          backend: 'claude-code',
          events: channel,
          cancel: () => undefined,
          result: () => Promise.resolve(result),
        };
      },
    } as unknown as AgentBackend;

    const backends = new BackendManager();
    backends.register(backend);
    const world = new WorldStateStore();
    const core = new JarvisCore({
      backends,
      tasks: new TaskManager({ backends }),
      memory: new JarvisMemory(),
      world,
      settings: () => DEFAULT_JARVIS_SETTINGS,
      speak: (текст: string) => sказано(сказано, текст),
    });
    return { core, world, сказано };
  }

  function sказано(куда: string[], текст: string): void {
    куда.push(текст);
  }

  it('ответ на вопрос во время работы сохраняется в состоянии мира', async () => {
    const { core, world, сказано } = ядро('Лев Толстой.');

    await core.answerQuestion('кто написал войну и мир');

    // Обработчик сам положил и вопрос, и ответ: следующее «а сколько ему было
    // лет» будет о ком спрашивать.
    expect(world.snapshot().currentUtterance).toBe('кто написал войну и мир');
    expect(world.snapshot().previousResult?.text).toContain('Толстой');
    expect(сказано.join(' ')).toContain('Толстой');
  });

  it('вопрос во время работы получает ответ, а не «учту»', async () => {
    const { core, сказано } = ядро('Да, понял: делаю сферу.');

    const ответ = await core.answerQuestion('ты понял что надо делать?');

    expect(ответ).toContain('понял');
    expect(сказано.length).toBeGreaterThan(0);
  });
});
