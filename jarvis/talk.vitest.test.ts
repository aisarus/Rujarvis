import { describe, expect, it } from 'vitest';

import { isTalk } from './core';
import { route } from './router/router';

/** Как решение выглядит после роутера на настоящей фразе. */
function решение(said: string) {
  return route(said, { basePermissions: { canRunCode: true } as never });
}

describe('разговор отличается от поручения', () => {
  // Человек сказал прямо: «он не понимает концепцию вопросов и не может на них
  // по факту отвечать». Так и было: намерение «разговор» доходило до создания
  // задачи и превращалось в двадцать секунд работы агента с инструментами —
  // ради ответа на вопрос о книге.
  it.each([
    'кто написал войну и мир',
    'сколько будет двести на триста',
    'что думаешь',
    'а почему ты так сделал',
    'ты меня слышишь',
  ])('«%s» — разговор, отвечаем словами', (said) => {
    expect(isTalk(решение(said))).toBe(true);
  });

  // Граница первая: поручение остаётся поручением, даже если звучит мягко.
  it.each([
    'открой блокнот',
    'создай сферу в блендере',
    'напиши письмо Ивану',
    'можешь открыть блокнот',
  ])('«%s» — работа, а не разговор', (said) => {
    expect(isTalk(решение(said))).toBe(false);
  });

  // Граница вторая, и она тоньше: это вопрос, но ответить на него без доступа
  // к файлам нельзя. Значит работа, несмотря на вопросительное слово.
  it('вопрос, требующий доступа, остаётся работой', () => {
    const d = решение('что у меня в папке загрузки');
    expect(d.needs.length).toBeGreaterThan(0);
    expect(isTalk(d)).toBe(false);
  });

  it('вопрос про экран тоже работа: надо посмотреть', () => {
    expect(isTalk(решение('что это за окно'))).toBe(false);
  });

  // Погода — не разговор, хотя звучит как он. Ответить на неё из памяти
  // значит соврать: нужен интернет, а значит это работа.
  it('вопрос, требующий интернета, остаётся работой', () => {
    const d = решение('какая погода в Тель-Авиве');
    expect(d.needs).toContain('web');
    expect(isTalk(d)).toBe(false);
  });
});
