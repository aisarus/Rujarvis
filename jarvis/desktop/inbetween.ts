/**
 * Промежутки, смазы и импакт-фреймы — из готовых ключей, а не генерацией.
 *
 * ## Зачем не генерацией
 *
 * Человек сформулировал задачу точно: «много очень коротких кадров, похожих по
 * контурам и цветам». Ключевое слово — похожих.
 *
 * Диффузия рисует каждый кадр с нуля и не помнит предыдущий. Складки на
 * футболке переедут, прядь перекинется, оттенок кожи сдвинется. Чем короче и
 * ближе кадры, тем заметнее: глаз сравнивает соседние. Это и называется
 * мерцанием, и на промежутках оно убивает работу.
 *
 * Здесь промежуток берётся ИЗ двух готовых кадров. Контуры и цвета не похожи —
 * они те же самые, сдвинутые. Совпадение по построению, а не по везению.
 *
 * ## Что здесь делается
 *
 * **Промежуток** — перетекание двух кадров со сдвигом по потоку движения.
 * **Смаз** — растяжение вдоль движения: так рисуют быстрое движение в аниме.
 * **Импакт-фрейм** — один-два кадра слома подачи в момент удара: жёсткий
 * контраст, радиальные линии, инверсия. Их не рассматривают, их чувствуют.
 *
 * ## Чего здесь нет
 *
 * Модели. Ни одной. Всё считается из пикселей, и это не экономия, а
 * единственный способ не поймать мерцание.
 */

import { spawn } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export interface Кадры {
  /** Папка с ключевыми кадрами: 01.png … 11.png. */
  keys: string;
  /** Куда складывать собранную последовательность. */
  out: string;
}

export interface Сборка {
  ok: boolean;
  frames?: number;
  /**
   * Срединное смещение потока в пикселях.
   *
   * Мера доверия к промежуткам. Ноль значит, что поток не нашёл движения и
   * просто перетёк одно в другое — на далёких позах так и выходит, и там
   * нужен не промежуток, а смаз.
   */
  shift?: number;
  error?: string;
}

/** Сколько промежутков ставить между соседними ключами по умолчанию. */
const МЕЖДУ = 3;

/**
 * Запуск ffmpeg.
 *
 * Через файл со списком аргументов не идём: имена у нас кириллические, и
 * прослойка командной строки — лишний повод для беды. Аргументы уходят
 * массивом, оболочки между ними нет.
 */
function ffmpeg(args: readonly string[]): Promise<{ ok: boolean; вывод: string }> {
  return new Promise((resolve) => {
    const дитя = spawn('ffmpeg', ['-hide_banner', '-loglevel', 'error', ...args], {
      windowsHide: true,
    });
    let вывод = '';
    дитя.stderr.on('data', (кусок: Buffer) => {
      вывод = (вывод + кусок.toString()).slice(-4000);
    });
    дитя.on('error', (ошибка) => resolve({ ok: false, вывод: ошибка.message }));
    дитя.on('close', (код) => resolve({ ok: код === 0, вывод }));
  });
}

/** Ключи по порядку имён. Порядок — это и есть последовательность движения. */
export function keyFrames(папка: string): string[] {
  if (!existsSync(папка)) return [];
  return readdirSync(папка)
    .filter((имя) => /\.(png|jpg|jpeg|webp)$/iu.test(имя))
    .sort()
    .map((имя) => path.join(папка, имя));
}

/**
 * Промежутки между двумя кадрами по оптическому потоку.
 *
 * ## Почему не ffmpeg
 *
 * Пробовали. `minterpolate` на паре картинок не выдаёт НИЧЕГО — ffmpeg пишет
 * «нечего кодировать». `framerate` выдаёт нужное число кадров, но среди восьми
 * ровно два разных: он дублирует, а не считает. Поток считается отдельно, и
 * это не обходной путь, а более управляемый.
 *
 * ## Где это работает, а где нет
 *
 * Проверено на настоящих кадрах: между БЛИЗКИМИ позами промежуток честный,
 * между далёкими (отрыв → группировка) выходит наложение двух фигур. Поток не
 * может проследить такое изменение и скатывается в перетекание.
 *
 * Отсюда правило работы: далеко разнесённые ключи не соединяются промежутком.
 * Там ставится смаз или импакт-фрейм — и это не уступка, а то, как рисуют.
 * Поле `shift` в ответе показывает, поверил ли поток в движение.
 */
export async function tween(
  первый: string,
  второй: string,
  куда: string,
  сколько = МЕЖДУ,
): Promise<Сборка> {
  mkdirSync(куда, { recursive: true });

  const итог = await питон(['промежутки.py', первый, второй, куда, String(сколько)]);
  if (!итог.ok) return { ok: false, error: итог.вывод.slice(0, 400) };

  // Срединное смещение потока: по нему видно, поверил ли поток в движение
  // или сдался и перетёк одно в другое.
  const замер = /SHIFT=([\d.]+)/u.exec(итог.вывод);
  return {
    ok: true,
    frames: сколько + 2,
    ...(замер ? { shift: Number(замер[1]) } : {}),
  };
}

/**
 * Запуск питона из ComfyUI.
 *
 * Свой питон брать неоткуда: системный 3.14 не тянет ни opencv, ни numpy той
 * версии. У ComfyUI встроенный, и он уже со всем нужным — пользуемся им, а не
 * заводим третью установку.
 */
function питон(args: readonly string[]): Promise<{ ok: boolean; вывод: string }> {
  const exe =
    process.env.JARVIS_COMFY_PYTHON?.trim() ||
    'C:/ComfyUI_windows_portable/python_embeded/python.exe';
  const [скрипт, ...остальное] = args;
  // Путь от этого файла, а не от рабочей папки: сервер запускают откуда
  // угодно. `__dirname` тут не годится — сборка идёт в модули, где его нет.
  const рядом = path.dirname(fileURLToPath(import.meta.url));
  const путь = path.join(рядом, 'питон', скрипт as string);

  return new Promise((resolve) => {
    const дитя = spawn(exe, [путь, ...остальное], { windowsHide: true });
    let вывод = '';
    const собрать = (кусок: Buffer): void => {
      вывод = (вывод + кусок.toString('utf8')).slice(-4000);
    };
    дитя.stdout.on('data', собрать);
    дитя.stderr.on('data', собрать);
    дитя.on('error', (ошибка) => resolve({ ok: false, вывод: ошибка.message }));
    дитя.on('close', (код) => resolve({ ok: код === 0, вывод }));
  });
}

/**
 * Смаз: растяжение кадра вдоль движения.
 *
 * В аниме смаз живёт один-два кадра и рисуется как вытянутый силуэт — глаз его
 * не читает, он читает скорость. Здесь то же самое достигается направленным
 * размытием: длина в пикселях, угол в градусах.
 */
export async function smear(
  кадр: string,
  куда: string,
  длина = 24,
  угол = 0,
): Promise<Сборка> {
  mkdirSync(path.dirname(куда), { recursive: true });

  // Размытие по ОДНОЙ оси — это и есть смаз. `avgblur` умеет разные радиусы
  // по осям, в отличие от `boxblur`, который мажет во все стороны и даёт не
  // скорость, а расфокус.
  //
  // Поворот с `c=none` в первой попытке завёл альфу в кадр без альфы, и
  // картинка вышла кислотной. Здесь поворот идёт по краю (`c=black`) и
  // формат держится явно — цвета остаются те же.
  const размах = Math.max(1, Math.round(длина));
  const цепочка =
    Math.abs(угол % 180) < 1
      ? `avgblur=sizeX=${размах}:sizeY=1`
      : `format=rgb24,rotate=${-угол}*PI/180:c=black:ow=rotw(${-угол}*PI/180):oh=roth(${-угол}*PI/180),` +
        `avgblur=sizeX=${размах}:sizeY=1,` +
        `rotate=${угол}*PI/180:c=black,crop=${'iw'}*0.7:${'ih'}*0.7`;

  const итог = await ffmpeg(['-y', '-i', кадр, '-vf', цепочка, куда]);
  return итог.ok ? { ok: true, frames: 1 } : { ok: false, error: итог.вывод.slice(0, 400) };
}

/**
 * Импакт-фрейм: слом подачи в момент удара.
 *
 * Самая простая часть всей работы и единственная, где код заведомо лучше
 * модели: это не рисунок, а стилизация готового кадра. Жёсткий порог до двух
 * тонов плюс инверсия — и кадр перестаёт быть картинкой, становясь ударом.
 *
 * Держится один-два кадра. Дольше — и он превращается в ошибку показа.
 */
export async function impact(кадр: string, куда: string, инверсия = true): Promise<Сборка> {
  mkdirSync(path.dirname(куда), { recursive: true });
  const цепочка = [
    'format=gray',
    // Порог жёсткий нарочно: полутона в импакт-фрейме превращают удар в кашу.
    'eq=contrast=6:brightness=-0.15',
    инверсия ? 'negate' : null,
    'format=rgb24',
  ].filter(Boolean) as string[];

  const итог = await ffmpeg(['-y', '-i', кадр, '-vf', цепочка.join(','), куда]);
  return итог.ok ? { ok: true, frames: 1 } : { ok: false, error: итог.вывод.slice(0, 400) };
}

/**
 * Собрать ролик из папки с кадрами.
 *
 * Частота низкая нарочно: аниме держит кадр по две-три экранных, и движение от
 * этого не страдает, а приобретает. Гнать двадцать четыре разных рисунка в
 * секунду — это не выразительнее, это просто дороже.
 */
export async function assemble(
  папка: string,
  куда: string,
  fps = 12,
): Promise<Сборка> {
  const кадры = keyFrames(папка);
  if (кадры.length === 0) return { ok: false, error: `в ${папка} нет кадров` };

  mkdirSync(path.dirname(куда), { recursive: true });
  const итог = await ffmpeg([
    '-y',
    '-framerate', String(fps),
    '-pattern_type', 'glob',
    '-i', path.join(папка, '*.png'),
    '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-crf', '18',
    куда,
  ]);
  return итог.ok
    ? { ok: true, frames: кадры.length }
    : { ok: false, error: итог.вывод.slice(0, 400) };
}
