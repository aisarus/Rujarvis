import { describe, expect, it } from 'vitest';

import { выбратьДвижок, вебДвижок, чемВодим } from './webDriver';

/**
 * Выбор движка — не вкусовщина.
 *
 * Playwright поднимает СВОЙ профиль: вкладки открываются в чистом браузере, где
 * человек никуда не вошёл, и «включи сериал» упирается в форму входа. Safari —
 * тот самый браузер, в котором он уже сидит. Ошибиться в этом выборе молча
 * нельзя: человек не поймёт, почему его подписки исчезли.
 */
describe('выбратьДвижок', () => {
  it('по умолчанию измеренный путь, а не лучший на словах', () => {
    // По делу Safari лучше — там входы человека. Но путь через него ни разу
    // не работал на живой машине: проверить его в прогоне нечем, раннер не
    // пускает к Safari Apple Events. Chromium измерен целиком, шесть из шести.
    // Ставить умолчанием непроверенное значит обещать то, чего можно и не
    // дождаться.
    expect(выбратьДвижок({}, 'darwin')).toBe('chromium');
    expect(выбратьДвижок({}, 'win32')).toBe('chromium');
    expect(выбратьДвижок({}, 'linux')).toBe('chromium');
  });

  it('просьба человека сильнее умолчания', () => {
    // Кому нужна точность важнее входов — должен сказать это один раз, а не
    // бороться каждый день.
    expect(выбратьДвижок({ JARVIS_BROWSER: 'chromium' }, 'darwin')).toBe('chromium');
    expect(выбратьДвижок({ JARVIS_BROWSER: 'safari' }, 'darwin')).toBe('safari');
  });

  it('но Safari не обещается там, где его нет', () => {
    // Иначе это молчаливый отказ вместо работы: на Windows Safari не бывает.
    expect(выбратьДвижок({ JARVIS_BROWSER: 'safari' }, 'win32')).toBe('chromium');
  });

  it('мусор в переменной не ломает выбор', () => {
    // Человек мог опечататься, и остаться из-за этого без браузера — глупо:
    // непонятое слово откатывает к умолчанию, а не к отказу.
    expect(выбратьДвижок({ JARVIS_BROWSER: 'сафари' }, 'darwin')).toBe('chromium');
    expect(выбратьДвижок({ JARVIS_BROWSER: '  SAFARI  ' }, 'darwin')).toBe('safari');
    expect(выбратьДвижок({ JARVIS_BROWSER: '' }, 'win32')).toBe('chromium');
  });
});

describe('вебДвижок', () => {
  it('отдаёт один и тот же вид, чем бы ни водил', () => {
    // Наверху, в инструментах, которые читает модель, различия быть не должно:
    // она не обязана знать, чем водят вкладки на этой машине.
    for (const движок of ['safari', 'chromium'] as const) {
      const водитель = вебДвижок(undefined, движок);
      expect(водитель.движок).toBe(движок);
      for (const умение of ['openUrl', 'readPage', 'listTabs', 'openTab'] as const) {
        expect(typeof водитель[умение], `${движок}.${умение}`).toBe('function');
      }
    }
  });
});

describe('чемВодим', () => {
  it('говорит модели правду про возможности, а не только имя', () => {
    // Промолчать значит дать ей строить план на неверных допущениях: в Safari
    // нет локаторов, а в своём Chromium человек не вошёл ни на один сайт.
    const про_safari = чемВодим('safari');
    expect(про_safari).toContain('window_press');
    expect(про_safari).toContain('входы');

    const про_chromium = чемВодим('chromium');
    expect(про_chromium).toContain('отдельном профиле');
    expect(про_chromium).not.toContain('window_press');
  });
});
