# -*- coding: utf-8 -*-
"""
Промежуточные кадры по оптическому потоку.

## Почему не ffmpeg

Пробовали. `minterpolate` на паре картинок не выдаёт ничего вовсе — ffmpeg
честно пишет «нечего кодировать». `framerate` выдаёт нужное число кадров, но
среди восьми ровно два разных: он дублирует, а не считает.

Здесь поток считается явно, и это не обходной путь, а более правильный:
видно, что именно происходит, и есть чем управлять.

## Как это работает

Между двумя кадрами считается плотный оптический поток — куда сместился
каждый пиксель. Промежуточный кадр строится ДВАЖДЫ: первый тянется вперёд по
потоку, второй тянется назад, и оба смешиваются по доле пути.

Двусторонность важна. Тянуть только вперёд — значит оставить дыры там, откуда
пиксели ушли: на рисунке это рваные края. Встречная тяга эти дыры закрывает.

## Чего ждать и чего не ждать

Поток хорошо держит плавное движение и плохо — резкий разворот и появление
того, чего в первом кадре не было (лицо из-за плеча). Такие места видны
глазом и заменяются смазом. Это честнее, чем сгладить: рваный кадр заметен, а
тихо размазанный — нет.
"""
import os
import sys

import cv2
import numpy as np

ПЕРВЫЙ = sys.argv[1]
ВТОРОЙ = sys.argv[2]
ПАПКА = sys.argv[3]
СКОЛЬКО = int(sys.argv[4]) if len(sys.argv) > 4 else 3
ПРЕФИКС = sys.argv[5] if len(sys.argv) > 5 else "tween"


def прочитать(путь):
    """Через imdecode: cv2.imread молча не читает кириллический путь."""
    with open(путь, "rb") as ф:
        данные = np.frombuffer(ф.read(), dtype=np.uint8)
    картинка = cv2.imdecode(данные, cv2.IMREAD_COLOR)
    if картинка is None:
        raise RuntimeError("не прочиталось: " + путь)
    return картинка


def записать(путь, картинка):
    вышло, буфер = cv2.imencode(".png", картинка)
    if not вышло:
        raise RuntimeError("не закодировалось")
    with open(путь, "wb") as ф:
        ф.write(буфер.tobytes())


def поток(из_чего, во_что):
    """Плотный оптический поток по Фарнебеку: куда сместился каждый пиксель."""
    a = cv2.cvtColor(из_чего, cv2.COLOR_BGR2GRAY)
    b = cv2.cvtColor(во_что, cv2.COLOR_BGR2GRAY)
    return cv2.calcOpticalFlowFarneback(
        a, b, None,
        pyr_scale=0.5,   # каждый следующий уровень пирамиды вдвое мельче
        levels=5,        # пять уровней ловят и крупное движение, и мелкое
        winsize=25,      # окно крупное: на рисунке мало текстуры, мелкое шумит
        iterations=3,
        poly_n=7,
        poly_sigma=1.5,
        flags=0,
    )


def потянуть(картинка, поле, доля):
    """Сдвинуть картинку по полю потока на заданную долю пути."""
    h, w = картинка.shape[:2]
    сетка_x, сетка_y = np.meshgrid(np.arange(w, dtype=np.float32),
                                   np.arange(h, dtype=np.float32))
    карта_x = сетка_x + поле[..., 0] * доля
    карта_y = сетка_y + поле[..., 1] * доля
    return cv2.remap(картинка, карта_x, карта_y, cv2.INTER_LINEAR,
                     borderMode=cv2.BORDER_REPLICATE)


os.makedirs(ПАПКА, exist_ok=True)

первый = прочитать(ПЕРВЫЙ)
второй = прочитать(ВТОРОЙ)
if первый.shape != второй.shape:
    второй = cv2.resize(второй, (первый.shape[1], первый.shape[0]),
                        interpolation=cv2.INTER_AREA)

вперёд = поток(первый, второй)
назад = поток(второй, первый)

записать(os.path.join(ПАПКА, "%s_000.png" % ПРЕФИКС), первый)

for n in range(1, СКОЛЬКО + 1):
    доля = n / (СКОЛЬКО + 1.0)
    из_первого = потянуть(первый, вперёд, доля)
    из_второго = потянуть(второй, назад, 1.0 - доля)
    # Ближе к своему краю — больше веса: у края собственный кадр точнее
    # любого натянутого.
    смесь = cv2.addWeighted(из_первого, 1.0 - доля, из_второго, доля, 0.0)
    записать(os.path.join(ПАПКА, "%s_%03d.png" % (ПРЕФИКС, n)), смесь)

записать(os.path.join(ПАПКА, "%s_%03d.png" % (ПРЕФИКС, СКОЛЬКО + 1)), второй)

# Сколько движения нашлось: по этому числу видно, стоит ли верить промежуткам.
размах = float(np.median(np.linalg.norm(вперёд, axis=2)))
# Метка латиницей: кириллица в выводе процесса на Windows приезжает мусором,
# и разбор её не находит. Число важнее красоты строки.
print("FRAMES=%d" % (СКОЛЬКО + 2))
print("SHIFT=%.2f" % размах)
