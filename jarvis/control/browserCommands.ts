/**
 * Быстрые команды браузера: без агента, за доли секунды.
 *
 * Живой прогон 26.09.2026 у владельца: «закрой вкладку» нажимало Ctrl+W, но в
 * то окно, что впереди, — а впереди был Claude, в котором человек разговаривал.
 * Вкладка в Edge стояла открытой, агент потом полторы минуты искал её сам и
 * закрыл щелчком по пикселям.
 *
 * Отсюда правило: то, что бывает только в браузере — вкладки и ссылки, —
 * идёт в браузер. В переднее окно, если оно браузерное, иначе в верхнее окно
 * браузера. Прокрутка и набор текста остаются за передним окном: они нужны и
 * в Ворде, и в блокноте, и уводить их в браузер значило бы сломать остальное.
 *
 * Всё здесь говорит только с `DesktopControl`, поэтому работает одинаково на
 * Windows (UIA через PowerShell) и на маке (AX через osascript), а проверяется
 * настоящим драйвером без Электрона.
 */
import type { DesktopControl, DesktopWindow } from '../desktop/driver';
import type { UiElement } from './elements';
import { parseSpokenNumber } from './grid';

/* ------------------------------------------------------------ вкладки --- */

/**
 * Клавиши, у которых смысл есть только в браузере.
 *
 * Имена — виндовые: маковский драйвер сам переводит `ctrl+w` в Cmd+W, а
 * `ctrl+tab` оставляет как есть, потому что Safari так и переключает вкладки.
 */
const КЛАВИШИ_ВКЛАДОК = new Set(['ctrl+t', 'ctrl+w', 'ctrl+shift+t', 'ctrl+tab', 'ctrl+shift+tab']);

export function этоКлавишаВкладки(keys: string): boolean {
  return КЛАВИШИ_ВКЛАДОК.has(keys.trim().toLowerCase());
}

/**
 * Нажать клавишу так, как это делает мост: вкладочную — в браузер.
 *
 * Одна функция на мост и на живую проверку. Проверка, гоняющая свою копию этих
 * двух строк, зеленела бы и тогда, когда мост от них отступил.
 */
export async function нажать(desktop: DesktopControl, keys: string): Promise<void> {
  if (этоКлавишаВкладки(keys)) await вывестиБраузер(desktop);
  await desktop.key(keys);
}

/* ------------------------------------------------------ окно браузера --- */

/** Программы-браузеры по имени — так их отдаёт маковский драйвер. */
const БРАУЗЕРЫ = [
  'safari', 'google chrome', 'chrome', 'chromium', 'microsoft edge', 'msedge', 'firefox',
  'arc', 'brave browser', 'brave', 'opera', 'vivaldi', 'yandex', 'яндекс браузер',
];

/**
 * Хвост заголовка у браузеров на Windows.
 *
 * Имени программы виндовый драйвер не отдаёт — только заголовок и pid. Зато
 * каждый браузер дописывает себя в конец заголовка. Замер 26.09.2026: первым в
 * списке окон стояло не окно браузера, а полоска Edge «www.veed.io
 * предоставляет доступ к вашему экрану…» — у неё тот же процесс, но хвоста нет.
 * Узнавать по процессу значило бы нажать Ctrl+W в полоску.
 */
const ХВОСТЫ = [
  'microsoft edge', 'google chrome', 'mozilla firefox', 'firefox', 'opera', 'brave',
  'vivaldi', 'яндекс браузер', 'yandex browser', 'chromium',
];

/**
 * Заголовок без невидимых знаков.
 *
 * Edge пишет «Microsoft​ Edge» с неразрывным пробелом нулевой ширины между
 * словами (U+200B). Без очистки сравнение с «microsoft edge» не срабатывает.
 */
function чистый(текст: string): string {
  return текст
    .replace(/[​-‍﻿]/gu, '')
    .replace(/\s+/gu, ' ')
    .trim()
    .toLowerCase();
}

export function этоОкноБраузера(окно: { title: string; app?: string }): boolean {
  if (окно.app) {
    const программа = чистый(окно.app);
    if (БРАУЗЕРЫ.some((б) => программа === б || программа.startsWith(`${б} `))) return true;
  }
  const заголовок = чистый(окно.title);
  return ХВОСТЫ.some((хвост) => заголовок.endsWith(хвост));
}

/**
 * В какое окно браузера действовать.
 *
 * Переднее, если оно браузерное: человек смотрит в него. Иначе — первое
 * браузерное по порядку драйвера, а драйверы отдают окна сверху вниз. Свёрнутое
 * — только если несвёрнутых нет: его придётся разворачивать, и это заметно.
 */
export function окноБраузера<T extends DesktopWindow & { app?: string }>(окна: readonly T[]): T | null {
  const браузерные = окна.filter(этоОкноБраузера);
  return (
    браузерные.find((о) => о.focused) ??
    браузерные.find((о) => !о.minimized) ??
    браузерные[0] ??
    null
  );
}

/**
 * Вывести браузер вперёд и вернуть его окно.
 *
 * Отказ — словами для человека: «не вижу открытого браузера» он поймёт, а
 * «окно не найдено» — нет.
 */
export async function вывестиБраузер(desktop: DesktopControl): Promise<DesktopWindow> {
  const окна = (await desktop.windows()) as Array<DesktopWindow & { app?: string }>;
  const окно = окноБраузера(окна);
  if (!окно) throw new Error('не вижу открытого браузера');
  if (!окно.focused) await desktop.focus(окно.title);
  return окно;
}

/* ----------------------------------------------------------- ссылки --- */

/**
 * Область страницы в дереве доступности.
 *
 * На Windows это `Document`, на маке `AXWebArea` — драйвер отдаёт её как
 * `WebArea`, потому что в его словаре этой роли нет.
 */
function этоОбластьСтраницы(элемент: UiElement): boolean {
  return элемент.type === 'Document' || элемент.type === 'WebArea';
}

function внутри(точка: { x: number; y: number }, рамка: UiElement): boolean {
  const левый = рамка.x - рамка.width / 2;
  const верх = рамка.y - рамка.height / 2;
  return (
    точка.x >= левый && точка.x <= левый + рамка.width &&
    точка.y >= верх && точка.y <= верх + рамка.height
  );
}

/**
 * Ссылки самой страницы, по порядку документа.
 *
 * Только те, что лежат внутри области страницы. Замер 26.09.2026 на живом Edge:
 * из шести `Hyperlink` пять были ссылками страницы, ровно в порядке документа,
 * а шестая — «Управление избранным» с панели браузера наверху. Посчитай её — и
 * «открой первую ссылку» открыло бы избранное.
 *
 * Нет области страницы — пустой список, а не все ссылки подряд: лучше честно
 * сказать «не вижу страницы», чем нажать на кнопку браузера.
 */
export function ссылкиСтраницы(элементы: readonly UiElement[]): UiElement[] {
  const страницы = элементы.filter(этоОбластьСтраницы).filter((э) => э.width > 0 && э.height > 0);
  if (страницы.length === 0) return [];
  return элементы.filter(
    (э) => э.type === 'Hyperlink' && э.enabled !== false && страницы.some((с) => внутри(э, с)),
  );
}

/** Порядковые на обоих языках. «Последнюю» — это -1: считаем с конца. */
const ПОРЯДКОВЫЕ: Record<string, number> = {
  перв: 1, втор: 2, трет: 3, четверт: 4, пят: 5, шест: 6, седьм: 7, восьм: 8, девят: 9, десят: 10,
  first: 1, second: 2, third: 3, fourth: 4, fifth: 5, sixth: 6, seventh: 7, eighth: 8, ninth: 9, tenth: 10,
};
const ПОСЛЕДНЯЯ = ['последн', 'last'];

/**
 * Номер ссылки из слов: «третью», «третьей», «номер три», «3», «последнюю».
 *
 * Основа, а не форма: распознаватель отдаёт падеж какой придётся — «третью»,
 * «третьей», «третья». `null` — не число вовсе; тогда это не команда про
 * ссылку, и фраза идёт дальше, а не превращается в нажатие наугад.
 */
export function номерСсылки(слова: string): number | null {
  const текст = слова.toLowerCase().replace(/ё/gu, 'е').replace(/^номер\s+|^number\s+/u, '').trim();
  if (!текст) return null;
  if (ПОСЛЕДНЯЯ.some((п) => текст.startsWith(п))) return -1;
  for (const [основа, номер] of Object.entries(ПОРЯДКОВЫЕ)) {
    if (текст.startsWith(основа)) return номер;
  }
  const число = parseSpokenNumber(текст);
  return число !== null && число > 0 ? число : null;
}

/** Какую ссылку взять. Номер с единицы, -1 — последняя. */
export function выбратьСсылку(ссылки: readonly UiElement[], номер: number): UiElement | null {
  if (номер === -1) return ссылки[ссылки.length - 1] ?? null;
  return ссылки[номер - 1] ?? null;
}

const ГЛАГОЛЫ_RU = '(?:открой|нажми|кликни|щелкни|перейди|зайди|жми)';
const ГЛАГОЛЫ_EN = '(?:open|click|follow|press)';

/**
 * «Открой третью ссылку» → номер 3.
 *
 * Два порядка слов, оба живые: номер перед словом «ссылка» («открой третью
 * ссылку», «перейди по второй ссылке») и после («открой ссылку номер три»,
 * «open link 3»). Фраза уже нормализована: нижний регистр, «ё» → «е», без
 * знаков и без имени Джарвиса.
 */
export function разобратьСсылку(фраза: string): { kind: 'openLink'; index: number } | null {
  const вариантыДо = [
    new RegExp(`^${ГЛАГОЛЫ_RU}(?: на| по| в)? (.+?) ссылк\\S*$`, 'u'),
    new RegExp(`^${ГЛАГОЛЫ_EN}(?: on)?(?: the)? (.+?) link$`, 'u'),
  ];
  const вариантыПосле = [
    new RegExp(`^${ГЛАГОЛЫ_RU}(?: на| по| в)? ссылк\\S* (.+)$`, 'u'),
    new RegExp(`^${ГЛАГОЛЫ_EN}(?: on)?(?: the)? link (.+)$`, 'u'),
  ];
  for (const образец of [...вариантыДо, ...вариантыПосле]) {
    const м = образец.exec(фраза);
    if (!м?.[1]) continue;
    const номер = номерСсылки(м[1]);
    if (номер !== null) return { kind: 'openLink', index: номер };
  }
  return null;
}

/**
 * Дерево страницы, когда оно достроилось.
 *
 * Chromium строит дерево доступности по ПЕРВОМУ запросу вспомогательной
 * программы: первый вопрос его заводит, видит уже второй. Тот же урок, что в
 * `cua.ts`: спрашиваем, пока ссылки не появились, а не ждём наугад.
 */
async function ссылкиКогдаДостроится(desktop: DesktopControl): Promise<{ окно: string; ссылки: UiElement[] }> {
  let последнее = { окно: '', ссылки: [] as UiElement[] };
  const конец = Date.now() + 3_000;
  do {
    const { title, elements } = await desktop.elements();
    последнее = { окно: title, ссылки: ссылкиСтраницы(elements) };
    if (последнее.ссылки.length > 0) return последнее;
    await new Promise((r) => setTimeout(r, 300));
  } while (Date.now() < конец);
  return последнее;
}

/**
 * «Открой N-ю ссылку»: браузер вперёд, ссылки страницы, нажатие по центру.
 *
 * Нажатие — по координатам центра из того же дерева, тем же путём, что «нажми
 * на …». Возвращает, что нажато: человек должен услышать, куда его повели.
 */
export async function открытьСсылку(desktop: DesktopControl, номер: number): Promise<UiElement> {
  await вывестиБраузер(desktop);
  const { окно, ссылки } = await ссылкиКогдаДостроится(desktop);
  if (ссылки.length === 0) {
    throw new Error(`на странице «${окно.slice(0, 60)}» не вижу ни одной ссылки`);
  }
  const ссылка = выбратьСсылку(ссылки, номер);
  if (!ссылка) {
    throw new Error(`на странице всего ${ссылки.length} ссылок, а просили ${номер}-ю`);
  }
  await desktop.click({ x: ссылка.x, y: ссылка.y });
  return ссылка;
}
