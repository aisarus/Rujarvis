/**
 * Русская морфология для разбора команд: слово к одной основе.
 *
 * ## Зачем
 *
 * 20.09.2026 выяснилось, что из 62 обещанных команд надёжно не работала ни
 * одна: каждая срабатывала слово в слово и разваливалась от одного
 * естественного слова рядом. Починили 21 семейство формулировок руками — и это
 * не масштабируется. Таблица фраз так и останется таблицей.
 *
 * Грамматика со слотами решает это, но в русском она невозможна без
 * приведения слова к основе: «сверни», «свернуть», «сворачивай», «свернул» —
 * одно и то же действие, и перечислять их в каждом правиле значит вернуться к
 * той же таблице, только длиннее.
 *
 * ## Почему свой, а не библиотека
 *
 * Алгоритм Портера для русского — сотня строк и никаких зависимостей, а ради
 * разбора коротких команд полноценная лемматизация не нужна: «сверн» и
 * «сверн» совпадут одинаково хорошо, кто бы их ни получил.
 *
 * Есть исключения, которые важнее алгоритма. «Ё» приводится к «е» до всего
 * остального: живой случай — запись «далеко ещё» в таблице не могла совпасть
 * никогда, потому что разбор менял «ё» раньше сравнения. И короткие слова не
 * трогаются: от «вниз» и «вверх» после отсечения окончаний остаётся одно и то
 * же, а это разные направления.
 */

const ГЛАСНЫЕ = 'аеиоуыэюя';

/** Слова короче этого не трогаем: у них нечего отсекать без потери смысла. */
const НЕ_ТРОГАТЬ = 5;

/**
 * Слова, которые нельзя стричь ни при какой длине.
 *
 * Здесь направления и служебные слова, у которых отсечение окончания сводит
 * разные смыслы к одному: «вниз» и «вверх» дали бы одну основу «вв»/«вн», и
 * прокрутка поехала бы не туда.
 */
const ЦЕЛИКОМ = new Set([
  'вниз', 'вверх', 'влево', 'вправо', 'назад', 'вперед', 'ниже', 'выше',
  'да', 'нет', 'все', 'вся', 'весь', 'это', 'эта', 'этот', 'тут', 'там',
  'стоп', 'стой', 'тише', 'тихо', 'еще', 'уже', 'так', 'как', 'что', 'кто',
  'мышь', 'мыши', 'окно', 'окна', 'окон', 'шаг', 'план', 'лог',
]);

/**
 * Чередование основы: то, чего никакой стеммер не осилит.
 *
 * «Нажать» и «нажми», «свернуть» и «сворачивай» — это один глагол с разными
 * основами, и отсечение окончаний их не сблизит. Таких пар в командах два
 * десятка, и явный список честнее, чем алгоритм, который делает вид, что
 * справился.
 *
 * Список маленький нарочно: сюда попадают только глаголы команд. Всё
 * остальное сводится алгоритмом.
 */
const ОДНО_И_ТО_ЖЕ: Record<string, string> = {
  нажм: 'наж', нажим: 'наж', жм: 'наж',
  // Ключ — та основа, что получается ПОСЛЕ отсечения: «сворачивай» даёт
  // «сворачив», а не «сворачива». Записывать сюда надо то, что видит
  // алгоритм, а не то, что кажется корнем.
  сворачив: 'сверн', сворачива: 'сверн', свернут: 'сверн',
  разворачив: 'разверн', разворачива: 'разверн', развернут: 'разверн',
  открыва: 'откр', откро: 'откр', открыт: 'откр',
  закрыва: 'закр', закро: 'закр', закрыт: 'закр',
  переключа: 'переключ', переключис: 'переключ', переключит: 'переключ',
  прокручива: 'прокрут', прокрут: 'прокрут',
  показыва: 'покаж', покаж: 'покаж', показат: 'покаж',
  запуска: 'запуст', запуст: 'запуст',
  остановис: 'останов', останавлива: 'останов',
  говорит: 'говор', сказа: 'говор', скаж: 'говор',
};

/** Окончания по группам, от длинных к коротким: длинное отсекается первым. */
const ГЛАГОЛ = [
  'ившись', 'ывшись', 'иваем', 'ываем', 'ивать', 'ывать', 'ившие', 'ывшие',
  'уйтесь', 'йтесь', 'ается', 'аться', 'иться', 'еться', 'ится', 'ется',
  'ываю', 'иваю', 'уйте', 'йте', 'ешь', 'ишь', 'ает', 'ует', 'ить', 'еть',
  'ать', 'ять', 'уть', 'ыть', 'нула', 'нул', 'ила', 'ыла', 'ена',
  // Повелительное наклонение: «открой», «сделай», «налей» — до голого «й».
  'ой', 'ей', 'ай', 'уй',
  'ил', 'ыл', 'им', 'ым', 'ем', 'ал', 'ял', 'ен', 'ят', 'ют', 'ут', 'ат',
  'и', 'й', 'л', 'ь',
];

const СУЩЕСТВИТЕЛЬНОЕ = [
  'иями', 'ями', 'ами', 'ией', 'ией', 'иям', 'ям', 'ам', 'ом', 'ем', 'ей',
  'ой', 'ый', 'ий', 'ая', 'яя', 'ое', 'ее', 'ую', 'юю', 'ые', 'ие', 'ых',
  'их', 'ов', 'ев', 'ью', 'ия', 'ие', 'у', 'ю', 'а', 'я', 'о', 'е', 'ы', 'и',
];

/** Сколько гласных в слове. Основа без гласной — не основа. */
function гласных(word: string): number {
  let счёт = 0;
  for (const буква of word) if (ГЛАСНЫЕ.includes(буква)) счёт += 1;
  return счёт;
}

function отсечь(word: string, окончания: readonly string[]): string {
  for (const конец of окончания) {
    if (!word.endsWith(конец)) continue;
    const основа = word.slice(0, -конец.length);
    // Основа должна остаться словом: с гласной и не короче трёх букв.
    if (основа.length >= 3 && гласных(основа) >= 1) return основа;
  }
  return word;
}

/**
 * Основа слова.
 *
 * Не лемма: «сверни» даёт «сверн», а не «свернуть». Для сопоставления команд
 * этого достаточно и надёжнее — лемматизация ошибается на редких словах, а
 * основа просто короче.
 */
export function основа(word: string): string {
  const слово = word.toLowerCase().replace(/ё/gu, 'е').trim();
  if (!слово) return '';
  if (ЦЕЛИКОМ.has(слово)) return слово;
  if (слово.length < НЕ_ТРОГАТЬ) return слово;

  // Возвратное «-ся» и «-сь» снимаем первыми: иначе «переключись» отсекается
  // до «переключис», и с «переключиться» оно уже не сойдётся.
  let слово2 = слово;
  for (const хвост of ['ся', 'сь']) {
    if (слово2.endsWith(хвост) && слово2.length - хвост.length >= 4) {
      слово2 = слово2.slice(0, -хвост.length);
      break;
    }
  }

  // Обе группы окончаний, и берём результат короче. Иначе порядок решает
  // случайно: «окнами» попадало под глагольное «и» и застревало на «окнам».
  const какГлагол = отсечь(слово2, ГЛАГОЛ);
  const какСлово = отсечь(слово2, СУЩЕСТВИТЕЛЬНОЕ);
  const короче = какГлагол.length <= какСлово.length ? какГлагол : какСлово;
  const итог = короче.length >= 3 ? короче : слово2;

  return ОДНО_И_ТО_ЖЕ[итог] ?? итог;
}

/** Одно ли это слово по смыслу. */
export function тоЖеСлово(a: string, b: string): boolean {
  return основа(a) === основа(b);
}

/** Фраза в последовательность основ. */
export function основы(phrase: string): string[] {
  return phrase
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .replace(/[^\p{L}\p{N}\s+]/gu, ' ')
    .split(/\s+/u)
    .filter(Boolean)
    .map(основа);
}
