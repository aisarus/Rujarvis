import { describe, expect, it } from 'vitest';

import { основа, основы, тоЖеСлово } from './morph';

describe('формы одного слова сходятся', () => {
  // Ровно тот класс, на который ушёл целый день: команда есть, но сказана
  // чуть иначе. Перечислять все формы в таблице — это и есть таблица.
  it.each([
    ['сверни', 'свернуть'],
    ['сверни', 'сворачивай'],
    ['переключись', 'переключиться'],
    ['переключи', 'переключить'],
    ['открой', 'открыть'],
    ['закрой', 'закрыть'],
    ['нажми', 'нажать'],
    ['прокрути', 'прокрутить'],
    ['вкладку', 'вкладка'],
    ['вкладке', 'вкладки'],
    ['окном', 'окнами'],
  ])('«%s» и «%s» — одно слово', (a, b) => {
    expect(тоЖеСлово(a, b)).toBe(true);
  });
});

describe('разное остаётся разным', () => {
  // Самое опасное место: направления. Если «вниз» и «вверх» сойдутся, прокрутка
  // поедет не туда, и человек этого сразу не заметит.
  it.each([
    ['вниз', 'вверх'],
    ['влево', 'вправо'],
    ['ниже', 'выше'],
    ['открой', 'закрой'],
    ['сверни', 'разверни'],
    ['копировать', 'вставить'],
  ])('«%s» и «%s» — разные слова', (a, b) => {
    expect(тоЖеСлово(a, b)).toBe(false);
  });
});

describe('ловушки, которые уже стоили нам крови', () => {
  // Живой случай: запись «далеко ещё» в таблице не могла совпасть никогда,
  // потому что разбор приводил «ё» к «е» раньше сравнения.
  it('ё и е — одна буква', () => {
    expect(основа('ещё')).toBe(основа('еще'));
    expect(тоЖеСлово('чёрный', 'черный')).toBe(true);
  });

  it('основа не короче трёх букв', () => {
    // «да» из списка убрано, а порог поднят до обещанных трёх.
    //
    // Раньше порог был ослаблен под это самое слово и не заметил бы основу из
    // двух букв у «окна» или «плана» — то есть проверял не то, что обещает
    // названием.
    for (const слово of ['окно', 'план', 'шаг', 'лог', 'нет']) {
      expect(основа(слово).length, слово).toBeGreaterThanOrEqual(3);
    }
  });

  it('у основы остаётся гласная — иначе это не слово', () => {
    for (const слово of ['переключись', 'сворачивай', 'прокрути']) {
      expect(/[аеиоуыэюя]/u.test(основа(слово))).toBe(true);
    }
  });

  it('пустое и мусорное не роняют', () => {
    expect(основа('')).toBe('');
    expect(основа('   ')).toBe('');
    expect(основы('')).toEqual([]);
  });
});

describe('фраза целиком', () => {
  it('режется на основы, знаки выбрасываются', () => {
    expect(основы('Сверни, пожалуйста, окно!')).toEqual([
      основа('сверни'),
      основа('пожалуйста'),
      основа('окно'),
    ]);
  });

  it('разные формы одной просьбы дают одно и то же', () => {
    expect(основы('переключись на вкладку')).toEqual(основы('переключиться на вкладки'));
  });
});
