import { describe, expect, it } from 'vitest';

import { firstMatch, matchPattern, type Rule } from './grammar';

describe('шаблон покрывает форму, а не строку', () => {
  // Ради этого всё и затевалось: одно правило вместо списка формулировок.
  it.each([
    'сверни окно',
    'свернуть окно',
    'сворачивай окно',
    'пожалуйста сверни окно',
    'сверни это окно',
    'пожалуйста сверни это окно',
    'убери окно',
  ])('«%s» подходит под одно правило', (сказано) => {
    expect(matchPattern('[пожалуйста] (сверни|убери) [это] окно', сказано)).toEqual({});
  });

  it('чужая просьба не подходит', () => {
    const шаблон = '[пожалуйста] (сверни|убери) [это] окно';
    expect(matchPattern(шаблон, 'закрой окно')).toBeNull();
    expect(matchPattern(шаблон, 'сверни')).toBeNull();
  });

  // Частичное совпадение — это половина сделанного дела, выданная за целое.
  // Так «закрой эту вкладку» уходило искать программу по имени «эту вкладку».
  it('шаблон обязан покрыть фразу целиком', () => {
    expect(matchPattern('сверни окно', 'сверни окно и открой блендер')).toBeNull();
    expect(matchPattern('сверни окно', 'быстро сверни окно')).toBeNull();
  });
});

describe('слоты', () => {
  it('забирают сказанное человеком', () => {
    expect(matchPattern('переключись на {куда}', 'переключись на хром')).toEqual({ куда: 'хром' });
    expect(matchPattern('переключись на {куда}', 'переключись на риот клиент')).toEqual({
      куда: 'риот клиент',
    });
  });

  it('слот не проглатывает хвост шаблона', () => {
    expect(matchPattern('открой {что} и закрой', 'открой блендер и закрой')).toEqual({
      что: 'блендер',
    });
  });

  it('пустого слота не бывает', () => {
    expect(matchPattern('переключись на {куда}', 'переключись на')).toBeNull();
  });

  // Слот по умолчанию берёт не больше трёх слов: это имя окна, а не пересказ.
  it('длинный хвост в слот не влезает', () => {
    expect(
      matchPattern('открой {что}', 'открой блендер и сделай там мультяшную ракету'),
    ).toBeNull();
  });

  it('звёздочка снимает предел, когда это нарочно', () => {
    expect(matchPattern('напечатай {текст*}', 'напечатай привет как твои дела сегодня')).toEqual({
      текст: 'привет как твои дела сегодня',
    });
  });
});

describe('порядок правил', () => {
  const ПРАВИЛА: Array<Rule<string>> = [
    // Частное — раньше общего, иначе общее перехватит.
    { pattern: '(переключи|переключись) [на] вкладку {куда}', make: (s) => `окно:${s.куда}` },
    { pattern: '(переключи|переключись) [на] [следующую] вкладку', make: () => 'ctrl+tab' },
  ];

  it('частное правило выигрывает у общего', () => {
    expect(firstMatch(ПРАВИЛА, 'переключи вкладку хром')).toBe('окно:хром');
  });

  it('общее срабатывает, когда частное не подошло', () => {
    expect(firstMatch(ПРАВИЛА, 'переключи вкладку')).toBe('ctrl+tab');
    expect(firstMatch(ПРАВИЛА, 'переключись на следующую вкладку')).toBe('ctrl+tab');
  });

  it('ничего не подошло — ничего и не возвращаем', () => {
    expect(firstMatch(ПРАВИЛА, 'найди отчёт за март')).toBeNull();
  });
});

describe('морфология внутри шаблона', () => {
  // Без этого грамматика в русском взрывается комбинаторикой форм.
  it('форма слова в шаблоне не важна', () => {
    expect(matchPattern('закрой вкладку', 'закрыть вкладки')).toEqual({});
    expect(matchPattern('закрыть вкладка', 'закрой вкладку')).toEqual({});
  });

  // Живой случай: «далеко ещё» не могло совпасть никогда, потому что разбор
  // приводил «ё» к «е» раньше сравнения.
  it('ё и е не мешают', () => {
    expect(matchPattern('далеко ещё', 'далеко еще')).toEqual({});
    expect(matchPattern('далеко еще', 'далеко ещё')).toEqual({});
  });

  // Направления — самое опасное место: если они сойдутся, прокрутка поедет не
  // туда, и человек заметит это не сразу.
  it('вниз и вверх остаются разными', () => {
    expect(matchPattern('прокрути вниз', 'прокрути вверх')).toBeNull();
    expect(matchPattern('прокрути вниз', 'прокрутить вниз')).toEqual({});
  });
});
