/**
 * Запас вещи: есть ли на странице что делать дольше тридцати секунд.
 *
 * Перенесено из Aegis (`operator/src/page-depth.js`) вместе с историей.
 *
 * ## Откуда это
 *
 * Прогон закончил работу со счётом 92 из 100 по всем шести осям качества.
 * Владелец открыл её и спросил: «сам подумай, что делать на этой странице хотя
 * бы пять минут?» Замер показал восемь видов событий и пять строк данных —
 * правила все до одного выполнены, а заняться нечем.
 *
 * Ни один прибор дома этого не ловил, и поймать не мог: все они смотрят на
 * ОДИН кадр. Плотность, типографика, палитра, движение — всё меряется по
 * фотографии. А запас — свойство не кадра, а **дороги**: сколько разного вещь
 * покажет, если её трогать.
 *
 * ## Поэтому мерить можно только руками
 *
 * Потрогали — сняли — сравнили с тем, что уже видели. Двенадцать действий
 * показали три разных кадра — это тридцать секунд. Двенадцать действий показали
 * двенадцать разных — это вещь.
 *
 * Здесь только счёт и слова. Трогает и снимает тот, у кого есть страница,
 * сравнивает кадры чужое правило — поэтому прибор проверяется без браузера и
 * без единого пикселя.
 */

import { cannotMeasure, failed, passed, type Gate } from './gate';

/** Ниже этого числа проб мерить нечего: две пробы не отличат вещь от заставки. */
const FEW_PROBES = 6;

export interface Probe {
  /** Что сделали: «прокрутить», «нажать», «подвигать мышью», «клавиша». */
  what: string;
  /** Ответила ли страница хоть чем-нибудь. */
  changed: boolean;
  /** Показала ли то, чего ещё не было. */
  fresh?: boolean;
}

export interface Depth {
  /** Есть ли запас. `null` — мерить нечем. */
  has: boolean | null;
  states: number | null;
  probes: number;
  /** Доля проб, на которые страница ответила. */
  share: number | null;
  /** Откуда взялось разное: «4 от прокрутки, 1 от нажатия». */
  from?: Map<string, number>;
  fact: string;
}

/**
 * Сколько РАЗНОГО показала страница.
 *
 * `states` — сколько среди снятых кадров различных. Считает вызывающий,
 * сравнивая растры: это его работа, не наша.
 *
 * Третий ответ (`has: null`) обязателен: страница, которая не открылась, и
 * страница, в которой нечего делать, — разные новости, и путать их нельзя.
 */
export function pageDepth(
  probes: readonly Probe[] = [],
  states: number | null = null,
): Depth {
  const count = Array.isArray(probes) ? probes.length : 0;

  if (
    count < FEW_PROBES ||
    typeof states !== 'number' ||
    !Number.isFinite(states) ||
    states < 1
  ) {
    return {
      has: null,
      states: null,
      probes: count,
      share: null,
      fact:
        count < FEW_PROBES
          ? `страницу потрогали ${count} раз — этого мало, чтобы отличить вещь от заставки`
          : 'кадры не сравнились: мерить нечем',
    };
  }

  // Доля отвечающих проб, а не число состояний: страница из трёх состояний,
  // которая отвечает на КАЖДОЕ действие, живее страницы из пяти, которая
  // отвечает на одно из десяти.
  const answered = probes.filter((probe) => probe?.changed).length;
  const share = answered / count;
  const poor = states <= 2;

  // ОТКУДА ВЗЯЛОСЬ РАЗНОЕ — ЭТО НЕ МЕЛОЧЬ.
  //
  // Прокрутка даёт новый кадр всегда: слайд-шоу из тринадцати картинок покажет
  // тринадцать разных кадров и пройдёт как вещь. Поэтому считаем по видам
  // отдельно и говорим ФАКТОМ, а не приговором: «пять от прокрутки, одно от
  // нажатий» и «шесть от прокрутки, ноль от всего остального» — разные вещи, и
  // решает тот, кто читает. Для новеллы со свитком первое и есть правильно.
  const byKind = new Map<string, number>();
  for (const probe of probes) {
    if (!probe?.fresh) continue;
    byKind.set(probe.what, (byKind.get(probe.what) ?? 0) + 1);
  }
  const from = [...byKind.entries()]
    .sort((left, right) => right[1] - left[1])
    .map(([what, many]) => `${many} от «${what}»`)
    .join(', ');

  return {
    has: !poor,
    states,
    probes: count,
    share,
    from: byKind,
    fact:
      `${count} действий показали ${states} ${wordForStates(states)}` +
      (from ? ` (${from})` : '') +
      `; отозвалась на ${answered} из ${count}` +
      (poor
        ? '. Это тридцать секунд, а не пять минут: трогать можно, а смотреть не на что'
        : ''),
  };
}

/** Число словами: «3 разных кадра», а не «3 кадр». */
export function wordForStates(count: number): string {
  const hundred = count % 100;
  const ten = count % 10;
  if (hundred >= 11 && hundred <= 14) return 'разных кадров';
  if (ten === 1) return 'разный кадр';
  if (ten >= 2 && ten <= 4) return 'разных кадра';
  return 'разных кадров';
}

/**
 * Что пробовать на странице.
 *
 * Порядок не случаен: сперва то, что есть у любой вещи (прокрутка), потом то,
 * что вещь обещает сама (её же кнопки и ручки). Клавиши последними — на них
 * отвечают редко, и тратить на них пробы раньше времени незачем.
 */
export function probePlan({ handles = 0, probes = 12 } = {}): Array<{ what: string; n: number }> {
  const plan: Array<{ what: string; n: number }> = [];
  const scrolls = Math.min(4, Math.max(2, Math.round(probes / 4)));

  for (let i = 0; i < scrolls; i += 1) plan.push({ what: 'прокрутить', n: i });

  // Предел считается ОДИН РАЗ, до цикла.
  //
  // В условии цикла он пересчитывался, а `plan.length` рос на каждом шаге —
  // предел падал, и нажатий выходило примерно вдвое меньше запрошенного
  // (5 ручек при 12 пробах давали 4 нажатия, 50 при 8 — два вместо четырёх).
  // Недоданные пробы уходили в «подвигать мышью», на которое страница
  // отвечает редко: запас занижался, и живая вещь могла получить провал.
  const нажатий = Math.max(0, Math.min(handles, probes - plan.length - 2));
  for (let i = 0; i < нажатий; i += 1) {
    plan.push({ what: 'нажать', n: i });
  }
  while (plan.length < probes - 1) plan.push({ what: 'подвигать мышью', n: plan.length });
  plan.push({ what: 'клавиша', n: 0 });

  return plan.slice(0, probes);
}

/** Запас как ворота: чтобы его нельзя было спутать с провалом. */
export function depthGate(depth: Depth): Gate {
  if (depth.has === null) return cannotMeasure(depth.fact);
  if (!depth.has) return failed(depth.fact);
  return passed(depth.fact);
}

export { FEW_PROBES };
