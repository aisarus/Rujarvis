/**
 * Режим плана: сначала замысел, потом работа.
 *
 * ## Зачем
 *
 * Человек попросил то же, что есть у кодовых агентов: «план, он слушает
 * задачу, формирует план, приём или правки — приём». И попросил по делу: его
 * главная жалоба всю дорогу — «приходится курировать на каждом этапе». Курируют
 * потому, что работа начинается раньше, чем становится понятно, что именно
 * будет сделано. Полчаса не той работы дороже минуты на план.
 *
 * ## Что здесь есть
 *
 * Только разбор слов и сборка шагов из ответа модели. Ни запуска, ни хранения:
 * решает тот, кто знает, идёт ли работа и что с ней делать, — а это ядро.
 *
 * ## Чего здесь нарочно нет
 *
 * **Своего списка «да» и «нет».** Он уже есть в `voice/confirm.ts`, и четвёртый
 * список согласия — это четвёртое место, где он разойдётся с остальными. Здесь
 * только то, чего там нет: слова пуска («погнали», «делай») и слова правки.
 */

import { readConfirmation } from '../voice/confirm';
import { normalizeForMatching } from '../router/text';

/** Что человек сказал про лежащий на столе план. */
export type PlanVerdict = 'принято' | 'правка' | 'отказ' | 'неясно';

/**
 * Слова пуска.
 *
 * Отдельно от «да», потому что это не согласие, а команда начинать: «погнали»
 * не отвечает на вопрос, оно его закрывает.
 */
const ПУСК = [
  'погнали', 'поехали', 'делай', 'начинай', 'приступай', 'принято',
  'утверждаю', 'go', 'вперед', 'давай',
  'proceed', 'approved', 'approve',
];

/** Слова, которыми план отклоняют целиком. */
const ОТКАЗ = ['отмена', 'отставить', 'забудь', 'не надо', 'передумал', 'cancel', 'forget', 'nevermind'];

/** Просьба спланировать, а не делать. */
const ПЛАН_СЛОВА = ['план', 'планир', 'распиш', 'обдума', 'продума', 'прикин', 'plan'];

/** Включение и выключение режима целиком. */
const ВКЛЮЧИТЬ = [['режим', 'план'], ['план', 'мод'], ['планов', 'режим'], ['plan', 'mode'], ['planning', 'mode']];

function слова(utterance: string): string[] {
  const чистое = normalizeForMatching(utterance);
  return чистое.length === 0 ? [] : чистое.split(' ');
}

function содержит(список: readonly string[], токены: readonly string[]): boolean {
  return токены.some((токен) =>
    список.some((слово) => (слово.length <= 3 ? токен === слово : токен.startsWith(слово))),
  );
}

/**
 * Просят ли план вместо работы.
 *
 * «Составь план», «сначала распиши» — да. «Сделай план этажа» — тоже слово
 * «план», но это работа, и отличает их глагол: планируют РАБОТУ, а рисуют
 * план чего-то. Здесь берётся простое: слово плана в первых трёх словах.
 * Дальше — только если рядом стоит «сначала».
 */
export function asksForPlan(utterance: string): boolean {
  const токены = слова(utterance);
  if (токены.length === 0) return false;

  if (содержит(['сначала', 'сперва', 'first'], токены) && содержит(ПЛАН_СЛОВА, токены)) return true;
  return содержит(ПЛАН_СЛОВА, токены.slice(0, 3));
}

/**
 * Включение или выключение режима плана.
 *
 * Возвращает `null`, когда речь не о режиме: тогда решает всё остальное.
 */
export function planModeSwitch(utterance: string): 'on' | 'off' | null {
  const токены = слова(utterance);
  const проРежиме = ВКЛЮЧИТЬ.some((пара) =>
    пара.every((слово) => токены.some((токен) => токен.startsWith(слово))),
  );
  if (!проРежиме) return null;
  return содержит(['выключ', 'отключ', 'убер', 'хватит', 'не', 'off', 'disabl'], токены) ? 'off' : 'on';
}

/**
 * Что человек ответил на показанный план.
 *
 * «Неясно» — это не «нет». Молчание и невнятица не должны запускать работу, но
 * и правкой считаться не должны: правка изменит план, которого человек, может
 * быть, вовсе не касался.
 */
export function readPlanVerdict(utterance: string): PlanVerdict {
  const токены = слова(utterance);
  if (токены.length === 0) return 'неясно';

  // Отказ — это отказ, а не правка.
  //
  // «Отмена» и «забудь» возвращали «правку», ядро шло планировать заново с
  // текстом «…Поправка: отмена», и человек, попросивший всё отменить, получал
  // новый план. Теперь у отказа свой вердикт, и план просто убирается.
  if (содержит(ОТКАЗ, токены)) return 'отказ';

  // Согласие коротко, правка — предложением.
  //
  // «Погнали» и «да, делай» — это ответ. «Сначала сделай фон, а потом
  // персонажа» — тоже про план, но это не «да»: человек говорит, ЧТО
  // поменять. Разбор согласия на такой фразе находил в ней «да» и запускал
  // работу по неисправленному плану — то есть ровно то, от чего режим плана
  // и должен спасать.
  const толькоПуск = токены.every(
    (токен) =>
      содержит(ПУСК, [токен]) ||
      readConfirmation(токен) === 'yes' ||
      ['ну', 'ок', 'окей', 'хорошо', 'ладно', 'пожалуйста', 'ok', 'okay', 'please', 'well'].includes(токен),
  );
  if (толькоПуск) return 'принято';
  if (токены.length <= 2 && содержит(ПУСК, токены)) return 'принято';

  const ответ = readConfirmation(utterance);
  if (токены.length <= 2) {
    if (ответ === 'yes') return 'принято';
    if (ответ === 'no') return 'отказ';
  }

  // Всё остальное во время лежащего плана — это правка к нему. Человек,
  // увидев замысел, чаще всего не отвечает «да», а говорит, что не так.
  return токены.length >= 2 ? 'правка' : 'неясно';
}

/**
 * Запрос на план, а не на работу.
 *
 * Нарочно просит короткие шаги и запрещает делать: у планирующего прогона
 * права только на чтение, но модель, не предупреждённая об этом, потратит
 * минуту на попытки и отчитается неудачей.
 */
export function planPrompt(utterance: string): string {
  return [
    'Составь план работы. НИЧЕГО НЕ ДЕЛАЙ — только план.',
    '',
    'Задача человека:',
    utterance,
    '',
    'Ответь списком из 3–7 шагов, по одному в строке, каждый с новой строки,',
    'начиная с цифры и точки. Шаг — это то, что видно глазом, когда оно',
    'сделано, а не «изучить вопрос». Никаких пояснений до и после списка.',
  ].join('\n');
}

/** Сколько шагов имеет смысл держать: длинный план человек не дослушает. */
const МАКСИМУМ_ШАГОВ = 7;

/**
 * Шаги из ответа модели.
 *
 * Модель почти всегда отвечает нумерованным списком, но иногда — тире, а
 * иногда добавляет фразу до или после. Берём строки, похожие на пункт, и
 * снимаем с них маркер.
 */
export function stepsFromAnswer(text: string): string[] {
  const шаги: string[] = [];
  for (const строка of text.split(/\r?\n/)) {
    const чистая = строка.trim();
    if (!чистая) continue;
    const пункт = /^(?:\d+[.)]|[-—*•])\s*(.+)$/u.exec(чистая);
    if (!пункт) continue;
    const текст = (пункт[1] ?? '').trim();
    // Пустой пункт и пункт из одного знака — это разметка, а не шаг.
    if (текст.length < 3) continue;
    шаги.push(текст);
    if (шаги.length >= МАКСИМУМ_ШАГОВ) break;
  }
  return шаги;
}

export { МАКСИМУМ_ШАГОВ };
