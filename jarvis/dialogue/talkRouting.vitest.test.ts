/**
 * Что уходит в разговор, а что не доходит до него никогда.
 *
 * ## Зачем отдельный сторож
 *
 * 22.09.2026 разбор речи во время работы заменили целиком: вместо таблицы
 * слов-примет решает сам разговор. Выигрыш очевиден, а цена — три-пять секунд
 * на фразу и чужая голова в решении.
 *
 * Значит появился новый способ всё сломать: затащить в разговор то, что
 * обязано срабатывать мгновенно. «Стоп», сказанный человеку, который ждёт
 * остановки сейчас, не может стоить пяти секунд и зависеть от модели.
 *
 * Здесь проверяются те же функции, которыми пользуется голосовой мост, и в том
 * же порядке. Фраза, выпавшая из ранних слоёв, доедет до разговора — и этот
 * набор об этом скажет.
 */

import { describe, expect, it } from 'vitest';

import { spokenCloseTarget, spokenTarget } from '../apps/launch';
import { FORGET_TALK_PHRASES, KILL_PHRASES, parseDirectCommand } from '../control/commands';
import { obviousAside } from './aside';
import { isSilenceRequest } from '../voice/noise';
import { matchVoiceControl } from '../voice/interrupts';

/**
 * Перехвачена ли фраза до разговора.
 *
 * Ровно те слои, что стоят в мосту выше буфера мысли, и ровно в том порядке:
 * тишина, слова остановки, прямые команды, закрыть, открыть.
 */
function перехвачено(said: string): string | null {
  if (isSilenceRequest(said)) return 'тишина';
  if (matchVoiceControl(said)) return 'остановка';
  const прямая = parseDirectCommand(said);
  if (прямая) return `прямая: ${прямая.kind}`;
  if (spokenCloseTarget(said)) return 'закрыть';
  if (spokenTarget(said)) return 'открыть';
  return null;
}

describe('мгновенное остаётся мгновенным', () => {
  const НЕМЕДЛЕННЫЕ = [
    'стоп',
    'отмена',
    'хватит',
    'тишина',
    'помолчи',
    'прокрути вниз',
    'нажми enter',
    ...KILL_PHRASES,
    ...FORGET_TALK_PHRASES,
  ];

  for (const фраза of НЕМЕДЛЕННЫЕ) {
    it(`«${фраза}» не уходит в разговор`, () => {
      expect(перехвачено(фраза)).not.toBeNull();
    });
  }

  it('«забудь разговор» рвёт нить сам, не спрашивая разговор', () => {
    // Просьба закрыть сессию не может зависеть от той сессии, которую
    // закрывают: зависшая нить не отпустила бы сама себя.
    for (const фраза of FORGET_TALK_PHRASES) {
      expect(parseDirectCommand(фраза)?.kind).toBe('forgetTalk');
    }
  });

  it('ни одна фраза забвения не похожа на просьбу замолчать', () => {
    const украденные = FORGET_TALK_PHRASES.map((фраза) => ({
      фраза,
      control: matchVoiceControl(фраза)?.control,
    })).filter((п) => п.control);

    expect(украденные).toEqual([]);
  });
});

describe('разговору достаётся то, ради чего он заведён', () => {
  const В_РАЗГОВОР = [
    // Вопрос во время работы. Раньше получал «Учту» и тишину.
    'ты понял что надо делать',
    'а почему не получилось',
    // Не-вопрос, который раньше молча падал в ящик правок.
    'мне не нравится как ты это делаешь',
    'давай лучше по-другому',
    // Поправка и новая задача: решает разговор, а не таблица примет.
    'сделай шрифт покрупнее',
    'а пока найди мне картинки заката',
  ];

  for (const фраза of В_РАЗГОВОР) {
    it(`«${фраза}» доходит до разговора`, () => {
      expect(перехвачено(фраза)).toBeNull();
      expect(obviousAside(фраза)?.kind).not.toBe('ignore');
    });
  }
});

describe('пустое не стоит трёх секунд', () => {
  for (const фраза of ['спасибо', 'ага, понял', 'джарвис', 'ну']) {
    it(`«${фраза}» отсеивается до разговора`, () => {
      expect(obviousAside(фраза)?.kind).toBe('ignore');
    });
  }
});
