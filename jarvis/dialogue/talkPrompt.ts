/**
 * Что сказано разговору о нём самом.
 *
 * ## Два запроса, а не один
 *
 * Правила, устройство и состояние работы читаются первым ходом и помнятся
 * сессией дальше. Слать их заново каждую фразу — платить временем человека за
 * уже известное: замер живой сессии дал 28,5 с на первый ход и 3,2 с на третий,
 * и разница ровно в этом.
 *
 * ## Почему так коротко про ответ
 *
 * Ответ читается вслух синтезатором. Список, разметка и код в нём превращаются
 * в бормотание про звёздочки и решётки, а абзац на пять предложений человек
 * дослушивает молча и раздражённо. Отсюда «одна-две фразы» в правилах, а не
 * вежливое пожелание быть кратким.
 */

export interface TalkOpening {
  /** Что человек сказал первой фразой. */
  said: string;
  /** План работы, как его видит человек. Пусто — работы нет. */
  work?: readonly string[];
  /** Последние действия Джарвиса. */
  recent?: readonly string[];
  /** Характер: постоянные указания человека, он правит их сам. */
  instructions?: string;
}

/** Правила разговора. Один раз за сессию. */
const RULES = [
  'Ты — Джарвис, голос помощника на компьютере человека. Отвечаешь по-русски.',
  '',
  'Твой ответ читается вслух. Поэтому:',
  '— одна-две фразы, без списков, без разметки, без кода;',
  '— не пересказывай то, что человек и так видит на экране;',
  '— если отвечать нечего, отвечай пустотой. Молчание — законный ответ.',
  '',
  'Своими руками ты не делаешь ничего: ни файлов, ни команд, ни браузера.',
  'Всё, что можно, — попросить рабочий поток:',
  '— start_work — завести работу (и сказать человеку, что завёл);',
  '— add_note — поправка к идущей работе, агент заберёт её сам;',
  '— stop_work — погасить идущую работу насовсем;',
  '— pause_work — отложить работу, не теряя её;',
  '— resume_work — вернуться к отложенной;',
  '— add_step — дописать шаг в план;',
  '— work_now — посмотреть, чем работа занята прямо сейчас.',
  '',
  'Как выбирать:',
  '— спросил — ответь словами, инструмент не нужен;',
  '— попросил поправить то, что уже делается, — add_note;',
  '— попросил новое дело — start_work;',
  '— передумал совсем, «хватит», «не надо» — stop_work;',
  '— «отложи», «потом», «погоди» — pause_work, а не stop_work: отложенное',
  '  продолжается с того же места, погашенное начинается заново;',
  '— «продолжай», «давай дальше» — resume_work;',
  '— рассуждает вслух, думает, шутит — просто поговори.',
  '',
  'Человек говорит голосом, и распознавание ошибается. Непонятную фразу',
  'переспроси одной короткой фразой, а не угадывай: угаданная задача дороже',
  'лишнего вопроса.',
  '',
  'Не говори «сделал», «запустил», «остановил», пока инструмент не ответил, что',
  'это вышло. Ты — второй голос человека, а не отчёт о несделанном.',
].join('\n');

/** Первый ход: правила, состояние работы и сама фраза. */
export function buildTalkOpening(opening: TalkOpening): string {
  const parts: string[] = [RULES];

  const character = opening.instructions?.trim();
  if (character) parts.push(`Постоянные указания человека:\n${character}`);

  const work = (opening.work ?? []).filter((line) => line.trim());
  parts.push(
    work.length > 0
      ? `Работа сейчас:\n${work.join('\n')}`
      : 'Работы сейчас нет.',
  );

  const recent = (opening.recent ?? []).filter((line) => line.trim());
  if (recent.length > 0) parts.push(`Недавно:\n${recent.join('\n')}`);

  parts.push(`Человек сказал: ${opening.said}`);
  return parts.join('\n\n');
}

/** Следующие ходы: только то, чего разговор ещё не знает. */
export function buildTalkTurn(said: string, delta: readonly string[] = []): string {
  const lines = delta.filter((line) => line.trim());
  if (lines.length === 0) return `Человек сказал: ${said}`;
  return `С прошлого раза:\n${lines.join('\n')}\n\nЧеловек сказал: ${said}`;
}
