/**
 * Режим плана: сначала замысел, потом работа.
 *
 * Разбор слов проверяется отдельно от запуска нарочно: ошибка здесь стоит либо
 * незапущенной работы (человек сказал «погнали», его не поняли), либо
 * запущенной не той (правку приняли за согласие).
 */

import { describe, expect, it } from 'vitest';

import {
  asksForPlan,
  planModeSwitch,
  planPrompt,
  readPlanVerdict,
  stepsFromAnswer,
} from './planMode';

describe('когда просят план, а не работу', () => {
  it.each([
    'составь план',
    'план работы давай',
    'сначала распиши что будешь делать',
    'прикинь план',
    'сперва обдумай',
  ])('«%s» — просят план', (сказано) => {
    expect(asksForPlan(сказано)).toBe(true);
  });

  // Граница: «план» бывает и предметом работы.
  it.each([
    'открой блендер',
    'сделай мультик про ракету',
    'нарисуй персонажа',
  ])('«%s» — это работа', (сказано) => {
    expect(asksForPlan(сказано)).toBe(false);
  });
});

describe('переключение режима', () => {
  it.each(['включи режим плана', 'режим плана', 'план мод включи'])(
    '«%s» — включить',
    (сказано) => {
      expect(planModeSwitch(сказано)).toBe('on');
    },
  );

  it.each(['выключи режим плана', 'убери план мод'])('«%s» — выключить', (сказано) => {
    expect(planModeSwitch(сказано)).toBe('off');
  });

  // Речь не о режиме — решать должно всё остальное, а не этот разбор.
  it.each(['составь план', 'открой блендер', 'что ты делаешь'])(
    '«%s» — не про режим',
    (сказано) => {
      expect(planModeSwitch(сказано)).toBeNull();
    },
  );
});

describe('что человек ответил на план', () => {
  it.each(['погнали', 'делай', 'да', 'принято', 'начинай', 'утверждаю'])(
    '«%s» — принято',
    (сказано) => {
      expect(readPlanVerdict(сказано)).toBe('принято');
    },
  );

  // Отказ — отдельно от правки, и это не придирка.
  //
  // Раньше «отмена» и «забудь» давали «правку»: ядро шло планировать заново с
  // текстом «…Поправка: отмена», и человек, попросивший всё отменить, получал
  // новый план вместо тишины. Проверка закрепляла это как норму.
  it.each(['нет', 'отмена', 'забудь', 'не надо'])('«%s» — отказ', (сказано) => {
    expect(readPlanVerdict(сказано)).toBe('отказ');
  });

  it.each([
    'сначала сделай фон а потом персонажа',
    'убери третий шаг',
  ])('«%s» — правка', (сказано) => {
    expect(readPlanVerdict(сказано)).toBe('правка');
  });

  // «Неясно» — не «нет» и не «да». Невнятица не должна запускать работу, но и
  // менять план, которого человек не касался, тоже нельзя.
  it.each(['', 'э'])('«%s» — неясно', (сказано) => {
    expect(readPlanVerdict(сказано)).toBe('неясно');
  });
});

describe('шаги из ответа модели', () => {
  it('берёт нумерованный список', () => {
    const шаги = stepsFromAnswer(
      [
        'Вот план:',
        '1. Собрать референсы персонажа',
        '2. Нарисовать силуэт',
        '3. Раскрасить',
        '',
        'Готов начинать.',
      ].join('\n'),
    );
    expect(шаги).toEqual(['Собрать референсы персонажа', 'Нарисовать силуэт', 'Раскрасить']);
  });

  it('понимает тире и точки-маркеры', () => {
    expect(stepsFromAnswer('— первый шаг\n- второй шаг\n• третий шаг')).toHaveLength(3);
  });

  it('длинный список обрезает', () => {
    const длинный = Array.from({ length: 20 }, (_, i) => `${i + 1}. шаг номер ${i + 1}`).join('\n');
    expect(stepsFromAnswer(длинный)).toHaveLength(7);
  });

  it('из ответа без списка шагов не выдумывает', () => {
    expect(stepsFromAnswer('Сделаю всё как ты просил, начинаю.')).toEqual([]);
  });
});

describe('запрос на план', () => {
  // Без этого модель тратит минуту на попытки сделать работу правами только на
  // чтение и отчитывается неудачей.
  it('прямо запрещает делать', () => {
    expect(planPrompt('сделай мультик')).toContain('НИЧЕГО НЕ ДЕЛАЙ');
  });

  it('несёт саму задачу', () => {
    expect(planPrompt('сделай мультик про ракету')).toContain('мультик про ракету');
  });
});
