/**
 * Сказанное во время работы: поправка или отдельная задача?
 *
 * До этого решения доходит только то, что не является прямым действием —
 * «открой хром» и «прокрути вниз» разобраны раньше и делаются сразу, не
 * дожидаясь ничьего мнения.
 *
 * Разбор в три слоя, от дешёвого к дорогому:
 *
 *   1. Очевидное решается здесь и без модели: вежливость и обрывки пропускаем,
 *      прямые слова («а пока», «правка») выполняем буквально.
 *   2. Остальное отдаём быстрой модели одним коротким вопросом.
 *   3. Молчание или чепуха в ответ — считаем поправкой.
 *
 * Третий слой не осторожность ради осторожности. Лишняя заметка в ящике стоит
 * человеку одной строки, которую он увидит; тихо заведённая задача стоит ему
 * работы, о которой он не просил, и узнает он о ней постфактум.
 */

import { isPleasantry } from '../voice/noise';

export type Aside =
  /** Ни то ни другое: вежливость, обрывок, шум распознавателя. */
  | { kind: 'ignore'; why: string }
  /** Поправка к тому, что идёт: в ящик заметок. */
  | { kind: 'note' }
  /** Отдельная работа: запустить рядом, не трогая текущую. */
  | { kind: 'task' };

/**
 * Слова, которыми человек прямо просит вторую работу.
 *
 * Проверяются по началу фразы: «а пока найди картинки». В середине те же
 * слова значат другое — «сделай заодно покрупнее» это всё-таки поправка.
 */
const MEANS_SEPARATE = [
  'а пока', 'пока ты', 'параллельно', 'заодно', 'отдельно',
  'вторая задача', 'ещё задача', 'а ещё сделай', 'между делом',
];

/** Слова, которыми человек прямо просит поправить идущую работу. */
const MEANS_CORRECTION = [
  'правка', 'поправка', 'туда же', 'к этой же', 'в этой же',
  'в той же', 'к той же', 'там же', 'и ещё туда',
];

function startsWithAny(phrase: string, starts: readonly string[]): boolean {
  return starts.some((start) => phrase.startsWith(start));
}

/**
 * Что можно решить, не спрашивая модель.
 *
 * `null` значит «не очевидно» — дальше вопрос к модели.
 */
export function obviousAside(said: string): Aside | null {
  const phrase = said.trim().toLowerCase();
  if (!phrase) return { kind: 'ignore', why: 'пусто' };

  if (isPleasantry(said)) return { kind: 'ignore', why: 'вежливость' };
  if (phrase.split(/\s+/u).length < 2) return { kind: 'ignore', why: 'слишком коротко' };

  if (startsWithAny(phrase, MEANS_SEPARATE)) return { kind: 'task' };
  if (startsWithAny(phrase, MEANS_CORRECTION)) return { kind: 'note' };

  return null;
}

/**
 * Вопрос модели — короткий, потому что человек ждёт.
 *
 * Названия работы достаточно: решение принимается по тому, об одном ли это
 * предмете, а не по подробностям.
 */
export function askAbout(said: string, working: string): string {
  return [
    `Идёт работа: «${working}».`,
    `Человек сказал: «${said}».`,
    'Это уточнение к идущей работе или просьба о другой, отдельной?',
    'Ответь одним словом: правка или отдельно.',
  ].join('\n');
}

/**
 * Ответ модели словом.
 *
 * Верим первому встреченному слову: модель, сказавшая «отдельно, а не правка»,
 * имела в виду первое. Ничего не разобрали — считаем поправкой.
 */
export function readAnswer(answer: string): Aside {
  const text = answer.toLowerCase();
  const separate = text.indexOf('отдельн');
  const correction = text.indexOf('правк');

  // Отрицание перед словом переворачивает смысл.
  //
  // «Не отдельно, правка» разбиралось как задача: слово «отдельн» стояло
  // раньше. Человек получал новую работу, о которой не просил, — а это, как
  // сказано в шапке, самый дорогой исход здесь.
  const отрицание = separate > 0 && /не\s+$/u.test(text.slice(Math.max(0, separate - 6), separate));
  if (отрицание) return { kind: 'note' };

  if (separate < 0) return { kind: 'note' };
  if (correction < 0) return { kind: 'task' };
  return separate < correction ? { kind: 'task' } : { kind: 'note' };
}
