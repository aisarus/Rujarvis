/**
 * Правки на ходу: то, что человек говорит, пока работа уже идёт.
 *
 * ## Зачем
 *
 * Человек описал это так: «возможность продолжать диалог не прерывая работу и
 * внесение изменений в работу по ходу дела». Когда одна команда запускает
 * работу на полчаса, дожидаться её конца, чтобы сказать «крышу сделай синей»,
 * — значит получить полчаса не той работы.
 *
 * Сегодня сказанное во время работы становится второй задачей. Это видно в
 * журнале: человек, прождав минуту, сказал «спасибо» — и в логе появилось
 * третье «Работаю» подряд, пока первая задача ещё считалась.
 *
 * ## Как это устроено
 *
 * Ящик. Человек говорит — реплика ложится сюда; агент между шагами
 * заглядывает и забирает всё разом. Ни прерывания, ни перезапуска: работа
 * продолжается, но уже с поправкой.
 *
 * Забирать нужно именно разом и с очисткой: иначе агент, заглянувший дважды,
 * учтёт одну и ту же правку дважды — а «сделай на два тона темнее», применённое
 * трижды, это уже чёрный цвет.
 *
 * ## Чего здесь нет
 *
 * Решения о том, правка это или новая задача. Ящик только хранит. Решает тот,
 * кто знает, идёт ли сейчас работа, — а это не дело чистой структуры данных.
 */

export interface Note {
  at: number;
  text: string;
}

/** Больше этого в ящике держать незачем: человек не помнит своих двадцати правок. */
const DEFAULT_LIMIT = 20;

export class NoteBox {
  private readonly limit: number;
  private notes: Note[] = [];

  constructor(options: { limit?: number } = {}) {
    this.limit = options.limit ?? DEFAULT_LIMIT;
  }

  add(text: string, at: number): void {
    const trimmed = text.trim();
    if (!trimmed) return;

    // Повтор — это человек, повторивший себя, потому что не услышал ответа.
    // Одна и та же правка, применённая дважды, хуже неприменённой.
    if (this.notes.some((note) => note.text === trimmed)) return;

    this.notes.push({ at, text: trimmed });
    if (this.notes.length > this.limit) this.notes.splice(0, this.notes.length - this.limit);
  }

  /** Забирает всё и очищает: дважды учтённая правка — испорченная работа. */
  take(): Note[] {
    const taken = this.notes;
    this.notes = [];
    return taken;
  }

  /** Что лежит, не забирая. */
  get pending(): readonly Note[] {
    return this.notes;
  }

  get empty(): boolean {
    return this.notes.length === 0;
  }

  clear(): void {
    this.notes = [];
  }
}

/**
 * Как показать правки агенту.
 *
 * Не просто список: агент должен понять, что это сказано уже после того, как
 * он взялся за работу, и что это меняет задачу, а не описывает её заново.
 */
export function renderNotes(notes: readonly Note[]): string {
  if (notes.length === 0) return 'Пока ничего не говорил.';

  const lines = notes.map((note) => `— ${note.text}`);
  return [
    'Человек сказал это уже после того, как ты взялся за работу.',
    'Это поправки к тому, что ты делаешь прямо сейчас, а не новая задача:',
    ...lines,
    'Учти их немедленно и продолжай.',
  ].join('\n');
}
