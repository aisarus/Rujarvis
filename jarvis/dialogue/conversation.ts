/**
 * Открытый разговор.
 *
 * ## Зачем
 *
 * Человек сказал прямо: «просто говорить с ним нельзя, а надо». И это не
 * прихоть — без разговора не выходит ни одной сложной работы. Замер показал,
 * во что это упиралось: любая фраза, опирающаяся на сказанное раньше, падала
 * ниже порога уверенности и получала «Не понял, что именно сделать».
 *
 *     «сделай её зелёной»       уверенность 0.35 → не понял
 *     «а теперь синюю»          уверенность 0.35 → не понял
 *     «что у меня получилось?»  уверенность 0.35 → не понял
 *     «ау, жив?»                уверенность 0.30 → не понял
 *
 * Маршрутизатор здесь не ошибается. Он честно сообщает, что фраза сама по себе
 * не значит ничего, — и он прав. «Сделай её зелёной» действительно не значит
 * ничего, пока не знаешь, про что «её».
 *
 * Но кто-то это знает: агент, который минуту назад сделал сферу. У него в
 * сессии лежит весь разговор целиком. Значит, правильный ответ на непонятную
 * фразу — не переспрашивать человека, а отдать её тому, кто понимает.
 *
 * ## Что здесь решается
 *
 * Два вопроса, и оба — да/нет:
 *
 *   1. Открыт ли разговор — есть ли живая сессия, в которую можно вернуться.
 *   2. Является ли эта фраза его продолжением.
 *
 * Ни решений о маршруте, ни запусков. Чистые функции, которые можно проверить
 * тестом за миллисекунду, — потому что ошибка здесь стоит дорого: разговор
 * либо рвётся на каждой второй фразе, либо, наоборот, тащит в старую сессию
 * совершенно новое поручение.
 */

import type { TaskMemory } from '../memory/store';
import { isPleasantry } from '../voice/noise';

/**
 * Сколько живёт разговор.
 *
 * Не бесконечно, и по двум причинам. Контекст сессии растёт, а вместе с ним
 * время и стоимость каждого ответа. И через полчаса «поменяй цвет» относится
 * уже к другому — тащить туда старое значит путать агента, а не помогать ему.
 */
export const CONVERSATION_WINDOW_MS = 20 * 60_000;

/**
 * Ниже этой уверенности фраза не стоит сама по себе.
 *
 * То же число, по которому ассистент раньше говорил «не понял»: здесь оно
 * меняет смысл — не повод переспросить, а признак, что фраза на что-то
 * опирается.
 */
export const LEANS_ON_CONTEXT_BELOW = 0.4;

export interface OpenConversation {
  /** Сессия агента: в ней лежит всё, что уже было сказано и сделано. */
  sessionId: string;
  /** Тот, кто эту сессию ведёт. Продолжать её у другого бэкенда бессмысленно. */
  backend: string;
  /** О чём шла речь — на случай, если сессия не поднимется. */
  utterance: string;
  outcome: string;
}

/** Фраза глазами маршрутизатора: ровно то, что нужно для решения. */
interface PhraseRouting {
  confidence: number;
  intent: string;
}

export function openConversation(
  last: TaskMemory | undefined,
  now: number,
  windowMs: number = CONVERSATION_WINDOW_MS,
): OpenConversation | null {
  // Сессия провалившейся задачи — это история ошибки. Продолжать в ней новую
  // работу значит начинать с чужих граблей.
  if (!last?.sessionId || !last.ok) return null;
  if (now - last.finishedAt > windowMs) return null;

  return {
    sessionId: last.sessionId,
    backend: last.backend,
    utterance: last.utterance,
    outcome: last.outcome,
  };
}

export function continuesConversation(
  utterance: string,
  routing: PhraseRouting,
  conversation: OpenConversation | null,
): boolean {
  if (!conversation) return false;
  if (!utterance.trim()) return false;

  // Вежливость — не поручение. Иначе «спасибо» поднимет целый запуск агента:
  // долго, дорого и незачем.
  //
  // Проверка намеренно узкая. Общий фильтр болтовни здесь не годится: он
  // отсекает всё, что начинается с «а», «нет», «это», — то есть ровно то, чем
  // человек продолжает разговор. Внутри открытого разговора почти любая фраза
  // законна, и единственное настоящее исключение — «спасибо».
  if (isPleasantry(utterance)) return false;

  // «Продолжай» без открытого разговора не значит ничего, а с ним — значит
  // ровно одно.
  if (routing.intent === 'continue') return true;

  return routing.confidence < LEANS_ON_CONTEXT_BELOW;
}
