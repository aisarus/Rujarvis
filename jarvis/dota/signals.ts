/**
 * Сигналы, которые нельзя получить из одного пакета.
 *
 * Здесь живёт то, для чего нужна память или сопоставление с картой: кого давно
 * не видели, кто садится рядом, можно ли сейчас поставить стак.
 *
 * ## Почему пропавшие не говорятся вслух
 *
 * Хотелось сделать классическое «мид пропал». Померили по матчу `9009407694`
 * сорок восемь правил: лучшее срабатывает пятнадцать раз за игру, а смертью
 * кончаются четыре. Против порога опасности, который ловит 18 из 18, это
 * никуда не годится.
 *
 * Но мерка была неверной. Человек умирает от тех, кого **видит**: в семи
 * смертях из восьми враг был в поле зрения за восемь секунд до. Пропавшие —
 * сведения для осторожности, а не предсказание смерти, и мерить их числом
 * предотвращённых смертей бессмысленно.
 *
 * Поэтому они идут на картинку и молчат. Человек глянет, когда собирается
 * заходить, — а не услышит пятнадцать ложных тревог за час.
 */
import type { Camp } from './camps';
import type { DotaPacket } from './packet';

/** Враг, которого давно не видели. */
export interface UnseenEnemy {
  hero: string;
  /** Сколько миллисекунд назад видели в последний раз. */
  ageMs: number;
}

/**
 * Кого не видно и сколько.
 *
 * Считается только по тем, кого хоть раз видели: пока имя не встретилось, мы
 * не знаем даже, кто против нас, и записывать его в пропавшие нечестно.
 */
export function unseenEnemies(
  lastSeen: ReadonlyMap<string, number>,
  now: number,
  quietMs = 8_000,
): UnseenEnemy[] {
  const итог: UnseenEnemy[] = [];
  for (const [hero, когда] of lastSeen) {
    const возраст = now - когда;
    if (возраст > quietMs) итог.push({ hero, ageMs: возраст });
  }
  return итог.sort((a, б) => б.ageMs - a.ageMs);
}

/** Союзник садится рядом. */
export interface AllyLanding {
  /** Сколько секунд до приземления. */
  seconds: number;
  /** Насколько далеко от тебя он сядет. */
  distance: number;
}

/**
 * Телепорт союзника к тебе.
 *
 * Дота присылает пинг телепортации с полем `remainingtime` — живым обратным
 * отсчётом. Замер по матчу `9009407694`: телепортов за игру сорок восемь, но
 * **ближе 1500 к человеку сел ровно один**. Поэтому про них можно говорить
 * вслух, не боясь шума: сигнал редкий по своей природе.
 *
 * Дальние не интересны: союзник, садящийся на другом краю карты, — не помощь
 * и не угроза, а новость, которой место на миникарте.
 */
export function allyLanding(packet: DotaPacket, nearRadius = 1500): AllyLanding | null {
  const свой = packet.self;
  if (!свой) return null;
  let ближайший: AllyLanding | null = null;
  for (const о of packet.pings) {
    if (о.kind !== 'teleporting') continue;
    const d = Math.round(Math.hypot(о.x - свой.x, о.y - свой.y));
    if (d > nearRadius) continue;
    if (!ближайший || d < ближайший.distance) {
      ближайший = { seconds: Math.max(0, Math.round(о.remaining * 10) / 10), distance: d };
    }
  }
  return ближайший;
}

/** Окно для стака: лагерь, который можно сложить прямо сейчас. */
export interface StackWindow {
  x: number;
  y: number;
  /** Сколько секунд до минуты. */
  seconds: number;
  distance: number;
}

/**
 * Можно ли сейчас поставить стак.
 *
 * Нейтралы появляются на отметке минуты, и чтобы лагерь сложился, его надо
 * увести за несколько секунд до неё. Окно короткое и известно точно — часы
 * приходят в каждом пакете.
 *
 * **Только живой лагерь.** Пустой складывать нечего, и подсказка про него —
 * чистый шум. Замер по матчу `9009407694`: окон рядом с каким-нибудь лагерем
 * тринадцать за игру, и это уже много; условие «лагерь жив» отсекает те, где
 * человеку всё равно нечего делать.
 */
export function stackWindow(
  packet: DotaPacket,
  camps: readonly Camp[],
  options: { radius?: number; from?: number; to?: number } = {},
): StackWindow | null {
  const свой = packet.self;
  if (!свой?.alive || packet.clock === null) return null;

  const секунда = ((packet.clock % 60) + 60) % 60;
  const от = options.from ?? 50;
  const до = options.to ?? 54;
  if (секунда < от || секунда > до) return null;

  const радиус = options.radius ?? 1400;
  let лучший: StackWindow | null = null;
  for (const лагерь of camps) {
    if (лагерь.state !== 'alive') continue;
    const d = Math.round(Math.hypot(лагерь.x - свой.x, лагерь.y - свой.y));
    if (d > радиус) continue;
    if (!лучший || d < лучший.distance) {
      лучший = { x: лагерь.x, y: лагерь.y, seconds: 60 - секунда, distance: d };
    }
  }
  return лучший;
}
