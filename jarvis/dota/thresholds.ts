/**
 * Пороги опасности и золота.
 *
 * ## Числа не придуманы
 *
 * Все они сняты с матча `9009407694` (21.09.2026, 54 минуты, 12 785 пакетов).
 * Порог «трое в 1200 либо один в 600 при здоровье ниже 40%» поймал **18 случаев
 * из 18**, когда героя убили, при **одной** ложной тревоге за игру и форе в
 * **9,1 секунды** в среднем.
 *
 * Перебиралось четыре радиуса, два количества, три близких радиуса и два порога
 * здоровья — сорок восемь наборов. Этот лучший по тишине среди поймавших всё.
 *
 * ## Чего здесь намеренно нет
 *
 * **Минимальной длительности тревоги.** Она убрала бы единственный шум —
 * секундное мелькание троих на 38:45 при полном здоровье, — но заодно лишила бы
 * предупреждения ту смерть, где форы было 1,8 секунды. Один ложный сигнал за
 * 54 минуты дешевле одной потерянной смерти.
 *
 * **Условия «на чужой половине».** Там проходит 46% живого времени, и как
 * самостоятельное условие оно только ухудшало результат в переборе.
 *
 * **Порога простоя.** Замер: из 42 остановок дольше 15 секунд настоящими
 * потерями были 8, суммарно три минуты за час. Отрицательный результат, записан
 * здесь, чтобы за него не взялись снова.
 *
 * ## Почему ворота, а не булево
 *
 * Мёртвый герой и пакет без героя — это не «опасности нет», а «нечем мерить».
 * Свернуть их в спокойствие значит молчать ровно тогда, когда прибор сломан, —
 * а молчание помощника выглядит в точности как «всё хорошо».
 */
import { cannotMeasure, failed, passed, type Gate } from '../measure/gate';
import type { DotaPacket } from './packet';
import { GOLD_MARK, type DotaState } from './state';

export interface DangerRule {
  /** Радиус, в котором считаем врагов. */
  nearRadius: number;
  /** Сколько врагов в этом радиусе — уже опасность. */
  nearCount: number;
  /** Радиус «вплотную». */
  closeRadius: number;
  /** Здоровье, ниже которого хватает одного врага вплотную. */
  closeHp: number;
}

export const DEFAULT_DANGER: DangerRule = {
  nearRadius: 1200,
  nearCount: 3,
  closeRadius: 600,
  closeHp: 40,
};

const СЧЁТОМ = ['ноль', 'один', 'двое', 'трое', 'четверо', 'пятеро'];

export function judgeDanger(packet: DotaPacket, rule: DangerRule = DEFAULT_DANGER): Gate {
  const свой = packet.self;
  if (!свой) return cannotMeasure('в пакете нет своего героя');
  if (!свой.alive) return cannotMeasure('герой мёртв');

  const расстояния = packet.enemies
    .map((в) => Math.hypot(в.x - свой.x, в.y - свой.y))
    .sort((a, б) => a - б);

  const рядом = расстояния.filter((р) => р < rule.nearRadius).length;
  if (рядом >= rule.nearCount) {
    return failed(`${СЧЁТОМ[Math.min(рядом, СЧЁТОМ.length - 1)]} в ${rule.nearRadius}`);
  }

  const ближайший = расстояния[0];
  if (ближайший !== undefined && ближайший < rule.closeRadius && свой.hp < rule.closeHp) {
    return failed(`один вплотную при здоровье ${свой.hp}%`);
  }

  return passed();
}

export interface GoldRule {
  /** Сколько золота считается «лежит». */
  amount: number;
  /** Сколько оно должно пролежать, прежде чем об этом сказать. */
  heldMs: number;
}

/**
 * Замер 21.09.2026: 2000 дольше 45 секунд — пять реплик за матч.
 *
 * Отметка берётся из `state.ts`, а не переписывается сюда числом: по ней
 * ведётся отсчёт в `applyPacket`, и две копии одного числа однажды разойдутся
 * молча — порог будет ждать одного, а отсчёт вестись по другому.
 */
export const DEFAULT_GOLD: GoldRule = { amount: GOLD_MARK, heldMs: 45_000 };

export function judgeGold(state: DotaState, rule: GoldRule = DEFAULT_GOLD): Gate {
  if (!state.latest) return cannotMeasure('пакетов ещё не было');

  // Мёртвому про покупки не говорят. Это не «нечем мерить» — золото прекрасно
  // видно, — а «правило не про этот случай»: лежащему нужен выкуп, а не совет
  // сходить в лавку.
  //
  // Замер по матчу `9009407694`: без этой оговорки порог давал пять реплик
  // вместо двух, и три из пяти приходились на респавн. Отсчёт при этом идёт
  // дальше, так что фраза прозвучит сразу после воскрешения — там она и к месту.
  if (state.latest.self && !state.latest.self.alive) return passed();

  if (state.goldSince === null) return passed();
  const лежит = state.latest.at - state.goldSince;
  return лежит >= rule.heldMs
    ? failed(`${state.latest.gold} лежит ${Math.round(лежит / 1000)} секунд`)
    : passed();
}
