/**
 * Аварийный выключатель: убить всё, что запустил Джарвис.
 *
 * ## Зачем он нужен отдельно от «стоп»
 *
 * «Стоп» — вежливая просьба: задача её слышит и заканчивается сама. Но если
 * агент завис, ушёл в бесконечный круг или перестал читать свой вход, вежливая
 * просьба не доходит — а человеку нужно, чтобы дошла всегда.
 *
 * Это тот же класс, что «стоп» и «тишина»: обязан срабатывать, когда не
 * работает больше ничего.
 *
 * ## Почему по своим детям, а не по имени программы
 *
 * Соблазн велик: `taskkill /F /IM node.exe` — одна строка. И она снесёт
 * MCP-серверы, чужие сборки, редактор человека и всё остальное, что оказалось
 * на node. Убивать надо ровно то, что запустили мы.
 *
 * Поэтому здесь реестр: каждый порождённый процесс отмечается, каждый
 * завершившийся забывается. Список всегда короткий и всегда наш.
 *
 * ## Почему /T
 *
 * Агент запускается через оболочку, и настоящая работа идёт во внуках: `cmd`
 * → `node` → инструменты. Убить одного родителя значит оставить сирот, которые
 * продолжат жечь процессор и писать в файлы. `/T` валит дерево целиком.
 */
import { spawn } from 'node:child_process';

/**
 * Кого мы запускали и кто ещё жив.
 *
 * Значение — ведёт ли этот процесс свою группу. Вне Windows агент
 * запускается с `detached`, и его инструменты живут в ЕГО группе: убить
 * одного лидера мало, иначе `reapAll` запишет pid в убитые, а сборка или
 * тесты продолжат работать. Живой разговор (`liveSession.ts`) группу не
 * заводит, и бить по группе там нельзя — задело бы соседей.
 */
const свои = new Map<number, { своя_группа: boolean; промахов: number }>();

/**
 * Сколько раз повторять удар по не поддавшемуся процессу.
 *
 * Держать такой pid вечно нельзя: система выдаёт номера повторно, и через
 * время он может достаться постороннему. Удар по маске однажды уже снёс
 * проводник и меню «Пуск» — повторять это чужими руками не будем. Двух
 * попыток хватает на процесс, который просто не успел умереть.
 */
const ПРЕДЕЛ_ПРОМАХОВ = 2;

/** Отметить порождённый процесс. Нулевой и отрицательный pid не бывает. */
export function trackChild(pid: number | undefined, своя_группа = false): void {
  if (typeof pid !== 'number' || !Number.isInteger(pid) || pid <= 0) return;
  свои.set(pid, { своя_группа, промахов: 0 });
}

/** Забыть завершившийся: иначе реестр растёт весь сеанс и мы бьём по пустоте. */
export function forgetChild(pid: number | undefined): void {
  if (typeof pid !== 'number') return;
  свои.delete(pid);
}

/** Сколько процессов под присмотром. */
export function trackedChildren(): number[] {
  return [...свои.keys()];
}

export interface ReapResult {
  killed: number[];
  /** Не убитые: уже мертвы или не дались. Разница видна только в журнале. */
  failed: number[];
}

function убитьДерево(pid: number, своя_группа: boolean): Promise<boolean> {
  if (process.platform !== 'win32') {
    // Отрицательный pid бьёт по всей группе — но только у того, кто её
    // возглавляет. Безусловно так делать нельзя: у процесса без `detached`
    // группа общая с нами, и удар задел бы самого Джарвиса.
    try {
      process.kill(своя_группа ? -pid : pid, 'SIGKILL');
      return Promise.resolve(true);
    } catch {
      return Promise.resolve(false);
    }
  }
  return new Promise((готово) => {
    const тк = spawn('taskkill', ['/F', '/T', '/PID', String(pid)], { windowsHide: true, stdio: 'ignore' });
    тк.on('exit', (код) => готово(код === 0));
    тк.on('error', () => готово(false));
  });
}

/**
 * Погасить процесс вместе с его детьми — по его собственному pid, не по маске.
 *
 * Для «стоп» на Windows: `child.kill()` убивает только прямой процесс. CLI,
 * поставленный через npm (`codex.cmd`), запускается через оболочку, и
 * настоящий агент — её ребёнок: он переживал «стоп» и работал дальше.
 */
export function killProcessTree(pid: number): Promise<boolean> {
  return убитьДерево(pid, false);
}

/**
 * Погасить дочерний процесс: на Windows — деревом по его pid, `kill()` —
 * только если дерево не далось. Сразу звать `kill()` нельзя: убитый родитель
 * уносит связь с детьми, и taskkill /T их уже не находит.
 */
export function stopChildTree(child: {
  pid?: number;
  killed: boolean;
  exitCode: number | null;
  signalCode?: NodeJS.Signals | null;
  kill(): boolean;
}): void {
  // Уже вышел — не трогать. Номер вышедшего процесса Windows отдаёт другим, и
  // taskkill /T по нему погасил бы чужое дерево: гасить можно только свой pid,
  // пока он свой.
  if (child.killed || child.exitCode !== null || (child.signalCode ?? null) !== null) return;
  if (process.platform === 'win32' && typeof child.pid === 'number') {
    void killProcessTree(child.pid).then((убит) => {
      if (!убит && !child.killed && child.exitCode === null) child.kill();
    });
    return;
  }
  child.kill();
}

/**
 * Убить всех своих.
 *
 * Из реестра выбывают только подтверждённо убитые. Раньше список чистился
 * целиком ДО попытки: не поддавшийся процесс попадал в `failed`, но повторить
 * по нему удар было уже нечем — записи не осталось. А мост при пустом
 * `killed` ещё и говорил человеку «некого убивать», хотя кто-то как раз
 * выжил.
 */
export async function reapAll(): Promise<ReapResult> {
  const цели = [...свои.entries()];

  const killed: number[] = [];
  const failed: number[] = [];
  for (const [pid, запись] of цели) {
    // По одному, а не пачкой: taskkill с несколькими /PID падает целиком, если
    // хоть один уже мёртв, и тогда выжившие остаются жить.
    if (await убитьДерево(pid, запись.своя_группа)) {
      killed.push(pid);
      свои.delete(pid);
      continue;
    }

    failed.push(pid);
    запись.промахов += 1;
    // Дальше держать бессмысленно и опасно: номер могут выдать другому.
    if (запись.промахов >= ПРЕДЕЛ_ПРОМАХОВ) свои.delete(pid);
  }
  return { killed, failed };
}
