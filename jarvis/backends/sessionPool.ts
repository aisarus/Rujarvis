/**
 * Склад живых сессий Claude Code.
 *
 * Держит по сессии на сочетание «папка + инструменты + режим разрешений»: всё
 * это задаётся при запуске процесса и потом не меняется. Совпало — реплика
 * уходит в уже прогретый процесс, и человек ждёт три секунды вместо двадцати.
 *
 * Замер 20.09.2026 против настоящего CLI:
 *
 *     ход 1   28.5 с, первое событие через 11.2 с
 *     ход 2    5.4 с, первое событие через 0.4 с
 *     ход 3    3.2 с, первое событие через 0.0 с
 *
 * ## Почему не одна сессия на всё
 *
 * Занятая сессия обрабатывает ходы по очереди. Для одного разговора это верно
 * — человек и сам говорит по очереди, — но параллельные задачи так встали бы
 * друг за другом. Поэтому занятая сессия не переиспользуется: заводится
 * вторая, и работы идут рядом.
 *
 * ## Почему склад ограничен
 *
 * Каждая сессия — это процесс CLI плюс его MCP-сервер со своим PowerShell.
 * За сутки небрежности в этой системе уже накапливалось шесть осиротевших
 * серверов на 956 МБ. Здесь предел явный, и самая старая свободная сессия
 * закрывается, когда он достигнут.
 */

import { LiveSession, sameSession, type SessionKey } from './liveSession';

/** Больше этого живых процессов CLI держать незачем. */
export const MAX_SESSIONS = 4;

export class SessionPool {
  private readonly sessions: LiveSession[] = [];

  constructor(private readonly limit = MAX_SESSIONS) {}

  /** Сколько сессий сейчас живо. Для проверки здоровья и журнала. */
  size(): number {
    this.forget();
    return this.sessions.length;
  }

  /** Убрать мёртвые: процесс мог упасть сам, и держать его в списке — врать. */
  private forget(): void {
    for (let i = this.sessions.length - 1; i >= 0; i -= 1) {
      if (!this.sessions[i]?.isAlive()) this.sessions.splice(i, 1);
    }
  }

  /**
   * Готовая сессия под этот ключ, или null.
   *
   * Занятая не отдаётся: её ход встал бы в очередь за чужой работой, и
   * короткая реплика ждала бы конца долгой задачи.
   */
  find(key: SessionKey): LiveSession | null {
    this.forget();
    return (
      this.sessions.find((s) => sameSession(s.key, key) && !s.isBusy()) ?? null
    );
  }

  /**
   * Положить новую сессию на склад.
   *
   * При переполнении закрывается самая старая свободная. Занятую не трогаем:
   * закрыть её значило бы оборвать чужую работу на полуслове.
   */
  keep(session: LiveSession): void {
    this.forget();
    // Закрываем свободные ПОКА не влезем, а не одну за вызов.
    //
    // После пика склад оставался раздутым навсегда: шесть параллельных задач
    // при пределе в четыре давали шесть сессий, и каждый следующий `keep`
    // закрывал одну и тут же клал новую. Шесть процессов CLI со своими
    // серверами так и жили, хотя шапка обещает явный предел.
    while (this.sessions.length >= this.limit) {
      const idle = this.sessions.findIndex((s) => !s.isBusy());
      if (idle < 0) break; // Все заняты — отбирать не у кого.
      this.sessions[idle]?.dispose('Место под новую сессию');
      this.sessions.splice(idle, 1);
    }
    this.sessions.push(session);
  }

  /** Закрыть всё. Зовётся, когда уходит тот, кто склад завёл. */
  disposeAll(why = 'Джарвис закрывается'): void {
    for (const session of this.sessions.splice(0)) session.dispose(why);
  }
}
