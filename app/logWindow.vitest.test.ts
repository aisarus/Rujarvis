import { describe, expect, it } from 'vitest';

import { buildLogWindowHtml, подписьШагов, СЛОВА_ШАГОВ } from './logWindow';

/**
 * Страница окна целиком лежит внутри шаблонной строки.
 *
 * Одна обратная кавычка где угодно в ней — хоть в комментарии — рвёт строку
 * пополам, и остаток кода не доезжает до браузера. Ровно так уже легла сборка
 * страницы микрофона, и проверка типов этого не увидела.
 */
describe('buildLogWindowHtml', () => {
  const html = buildLogWindowHtml();

  it('доезжает до конца, а не обрывается на середине', () => {
    expect(html).toContain('jarvis-log:backlog');
    expect(html).toContain('</script>');
    expect(html).toContain('</html>');
  });

  it('рисует и подпись шага, и подробность', () => {
    // Без подробности строка бесполезна: «Пишу файл» без имени файла не
    // говорит ничего.
    expect(html).toContain("className = 'text'");
    expect(html).toContain("className = 'detail'");
  });

  it('следует за низом ленты, пока человек её не тронул', () => {
    expect(html).toContain('follow');
    expect(html).toContain('scrollHeight');
  });

  it('вставляет текст как текст, а не как разметку', () => {
    // Строки приходят из вывода агента и из имён файлов. Складывать их в
    // innerHTML значит дать чужому тексту исполняться в окне.
    expect(html).not.toContain('innerHTML');
    expect(html).toContain('textContent');
  });

  it('не копит строки бесконечно', () => {
    expect(html).toContain('removeChild');
  });

  it('уносит в страницу проверенное правило склонения, а не переписанное', () => {
    // Если правило переписать в странице руками, оно разойдётся с тестом
    // ниже и врать будет только окно — там, где никто не проверяет.
    expect(html).toContain('подписьШагов(shown, СЛОВА)');
    expect(html).toContain('сотня >= 11');
  });
});

/**
 * «1 шагов» в углу окна читается как поломка самой программы.
 *
 * Счётчик стоял в заголовке со словом «шагов» при любом числе, и по-английски
 * тоже: «1 steps».
 */
describe('подписьШагов', () => {
  it('склоняет по-русски', () => {
    const ru = СЛОВА_ШАГОВ.ru;
    expect(подписьШагов(1, ru)).toBe('1 шаг');
    expect(подписьШагов(2, ru)).toBe('2 шага');
    expect(подписьШагов(4, ru)).toBe('4 шага');
    expect(подписьШагов(5, ru)).toBe('5 шагов');
    expect(подписьШагов(11, ru)).toBe('11 шагов');
    expect(подписьШагов(12, ru)).toBe('12 шагов');
    expect(подписьШагов(14, ru)).toBe('14 шагов');
    expect(подписьШагов(21, ru)).toBe('21 шаг');
    expect(подписьШагов(22, ru)).toBe('22 шага');
    expect(подписьШагов(25, ru)).toBe('25 шагов');
    expect(подписьШагов(101, ru)).toBe('101 шаг');
    expect(подписьШагов(111, ru)).toBe('111 шагов');
  });

  it('по-английски различает один и много', () => {
    const en = СЛОВА_ШАГОВ.en;
    expect(подписьШагов(1, en)).toBe('1 step');
    expect(подписьШагов(2, en)).toBe('2 steps');
    expect(подписьШагов(21, en)).toBe('21 step');
    expect(подписьШагов(11, en)).toBe('11 steps');
  });
});
