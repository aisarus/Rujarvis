import { readFileSync } from 'node:fs';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

/**
 * Речь, не адресованная Джарвису, не попадает в журнал.
 *
 * Инвариант из AGENTS.md, и он не абстрактный. Живой прогон 26.09.2026: при
 * настройке «только команды» в журнал построчно писалась аудиокнига, игравшая
 * в комнате, — «Анка повернулась к ним спиной», «сказал Пашка». Каждая фраза с
 * `awake=false command=null`, то есть заведомо не Джарвису, и с полным текстом.
 *
 * Помощники `unlogged` и `logged` в файле были и применялись в десяти местах
 * из двенадцати. Двух хватило, чтобы записать чужой вечер.
 *
 * Поэтому проверка не точечная. Она перебирает ВСЕ строки журнала в голосовом
 * мосте, находит те, что подставляют распознанное, и требует помощника у
 * каждой. Новое место само попадёт под этот сторож, а не будет ждать, пока его
 * заметят в чужом логе.
 */
const ФАЙЛ = path.join(__dirname, 'voiceBridge.ts');

/** Переменные, в которых лежит распознанная речь. */
const РЕЧЬ = ['text', 'corrected', 'whole', 'command'];

interface Строка {
  номер: number;
  текст: string;
}

/** Строки с console.log/console.error, подставляющие распознанное напрямую. */
function сыраяРечьВЖурнале(источник: string): Строка[] {
  const плохие: Строка[] = [];

  источник.split(/\r?\n/u).forEach((текст, i) => {
    if (!/console\.(log|error)\(/u.test(текст)) return;
    // Вне шаблонной строки подстановки нет — значит нечего и утекать.
    if (!текст.includes('${')) return;

    for (const имя of РЕЧЬ) {
      // Ровно `${text}` или `${text.trim()}` и подобное — без вызова помощника.
      const прямая = new RegExp('\\$\\{' + имя + '(\\s*[)}.]|\\s*\\?\\?)', 'u');
      if (!прямая.test(текст)) continue;
      // `${unlogged(text)}` и `${logged(text)}` — это как раз правильно.
      if (new RegExp('(unlogged|logged)\\(\\s*' + имя, 'u').test(текст)) continue;
      // `short(text)` — это накладка на экране самого человека, не файл.
      if (new RegExp('short\\(\\s*' + имя, 'u').test(текст)) continue;
      плохие.push({ номер: i + 1, текст: текст.trim() });
      return;
    }
  });

  return плохие;
}

describe('журнал не пишет чужую речь', () => {
  it('каждая строка с распознанным идёт через unlogged или logged', () => {
    const источник = readFileSync(ФАЙЛ, 'utf8');
    const плохие = сыраяРечьВЖурнале(источник);

    // Сообщение называет место и строку: молчаливое «не прошло» тут дороже
    // самой ошибки, потому что искать пришлось бы по всему файлу.
    const где = плохие.map((с) => `  voiceBridge.ts:${с.номер}  ${с.текст}`).join(String.fromCharCode(10));
    expect(плохие, `сырая речь в журнале:${String.fromCharCode(10)}${где}`).toEqual([]);
  });

  it('сторож замечает сырую подстановку', () => {
    // Тест, который не падает на сломанном коде, — украшение. Проверяем на
    // подделке: так видно, что ловится именно подстановка, а не что-нибудь.
    const подделка = [
      'console.log(`[jarvis] услышал: ${text}`);',
      'console.log(`[jarvis] мысль: ${logged(whole)}`);',
      'console.log(`[jarvis] шум: ${unlogged(text)}`);',
      'overlay.note(session.status, `Услышал: ${text}`);',
    ].join(String.fromCharCode(10));

    const плохие = сыраяРечьВЖурнале(подделка);

    expect(плохие).toHaveLength(1);
    expect(плохие[0]?.номер).toBe(1);
  });

  it('оба помощника на месте и смотрят в настройку', () => {
    const источник = readFileSync(ФАЙЛ, 'utf8');

    // Без этой связки помощники превратились бы в пустышки, а сторож выше
    // остался бы зелёным: он проверяет вызов, а не то, что внутри.
    expect(источник).toContain("settings().speechLogging === 'all'");
    expect(источник).toContain("settings().speechLogging === 'off'");
  });
});
