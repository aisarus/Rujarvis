/**
 * Разрешения macOS: спросить самим, а не ждать, пока человек догадается.
 *
 * На маке Джарвису нужны три разных замка, и просит их система по-разному:
 *
 *   - микрофон — без него нет голоса вовсе;
 *   - «Универсальный доступ» — окна, мышь, клавиши;
 *   - «Запись экрана» — снимки окон и сетка нажатий.
 *
 * Молчать и ждать нельзя, и это не про удобство. Без «Универсального доступа»
 * CGEvent НЕ ПАДАЕТ, а молча ничего не делает: человек говорит, Джарвис
 * отвечает «сделал», и не происходит ничего. Худший из возможных отказов —
 * тот, который выглядит как успех. Поэтому разрешения спрашиваются до первой
 * команды, а не выясняются по её провалу.
 *
 * Спросить может только система, и только один раз: второй раз macOS окна уже
 * не покажет, а отправит в «Системные настройки». Поэтому важно не
 * промахнуться мимо этого единственного раза — и важно знать, чем он
 * кончился, чтобы сказать человеку словами.
 *
 * Электрон сюда не импортируется: он приходит снаружи. Иначе модуль нельзя
 * проверить, не подняв целое приложение.
 */

/** Чем кончился вопрос. Три ответа, а не два: «не спрашивали» — не «отказ». */
export type Разрешение = 'дано' | 'отказано' | 'не спрашивали' | 'не нужно';

export interface Опрос {
  микрофон: Разрешение;
  доступность: Разрешение;
  экран: Разрешение;
}

/**
 * Та часть Электрона и системы, которая тут нужна.
 *
 * Названа интерфейсом, а не взята импортом, чтобы проверять эту логику
 * числами и ответами, а не запуском целого приложения с окнами.
 */
export interface Система {
  /** `systemPreferences.askForMediaAccess('microphone')`. */
  спроситьМикрофон(): Promise<boolean>;
  /**
   * `systemPreferences.isTrustedAccessibilityClient(prompt)`.
   *
   * С `prompt: true` macOS показывает своё окно со ссылкой в настройки —
   * но ТОЛЬКО если разрешения ещё нет. Ответ приходит не сразу: человек
   * уходит в настройки, и `true` здесь означает «уже дано», а не «дал».
   */
  довереныЛиМы(спрашивать: boolean): boolean;
  /** `systemPreferences.getMediaAccessStatus('screen')`. */
  состояниеЭкрана(): string;
  /**
   * Разовый снимок экрана — им и спрашивается «Запись экрана».
   *
   * Отдельной просьбы у macOS нет: окно показывается на первой попытке
   * снять экран. Берём кадр 1×1 — нам нужен вопрос, а не картинка.
   */
  тронутьЭкран(): Promise<void>;
}

/** Ответ macOS про носитель, переведённый в наши три слова. */
export function поСостоянию(состояние: string): Разрешение {
  if (состояние === 'granted') return 'дано';
  if (состояние === 'denied' || состояние === 'restricted') return 'отказано';
  // 'not-determined' и 'unknown' — это «ещё не спрашивали», и сворачивать их
  // в отказ нельзя: на отказ человека отправляют в настройки, а тут надо
  // просто спросить.
  return 'не спрашивали';
}

/**
 * Спросить всё, чего не хватает.
 *
 * Порядок не случаен: сначала микрофон — без него Джарвиса нет вовсе и
 * остальные вопросы бессмысленны. Потом «Универсальный доступ»: его окно
 * уводит в настройки, и пусть это будет один раз, а не между двумя другими.
 * Экран последним: он нужен снимкам и сетке, а голос без него работает.
 *
 * Уже выданное не переспрашивается: повторный вопрос macOS не покажет, а
 * лишний снимок экрана — это лишняя секунда на старте.
 */
export async function запроситьРазрешения(
  система: Система,
  platform: NodeJS.Platform = process.platform,
): Promise<Опрос> {
  if (platform !== 'darwin') {
    return { микрофон: 'не нужно', доступность: 'не нужно', экран: 'не нужно' };
  }

  const опрос: Опрос = { микрофон: 'не спрашивали', доступность: 'не спрашивали', экран: 'не спрашивали' };

  try {
    опрос.микрофон = (await система.спроситьМикрофон()) ? 'дано' : 'отказано';
  } catch {
    // Отказ самого вызова — не отказ человека. Врать про второе нельзя.
    опрос.микрофон = 'не спрашивали';
  }

  try {
    // Сначала тихо: если доступ уже есть, окно показывать незачем.
    опрос.доступность = система.довереныЛиМы(false) ? 'дано' : 'не спрашивали';
    if (опрос.доступность !== 'дано') {
      // Окно системы. `false` здесь не «отказал», а «ещё не дал»: человек
      // уходит в настройки и возвращается позже, иногда после перезапуска.
      система.довереныЛиМы(true);
    }
  } catch {
    опрос.доступность = 'не спрашивали';
  }

  try {
    опрос.экран = поСостоянию(система.состояниеЭкрана());
    if (опрос.экран === 'не спрашивали') {
      await система.тронутьЭкран();
      опрос.экран = поСостоянию(система.состояниеЭкрана());
    }
  } catch {
    опрос.экран = 'не спрашивали';
  }

  return опрос;
}

/**
 * Что сказать человеку про итог — или молчать, если всё на месте.
 *
 * `null` значит «говорить нечего»: тишина при полном порядке ценнее ещё
 * одного сообщения, которое перестанут читать.
 */
export function чегоНеХватает(опрос: Опрос): string | null {
  const нет: string[] = [];
  if (опрос.микрофон === 'отказано') нет.push('микрофон — без него голоса не будет');
  // «Не нужно» — это не «не хватает»: вне мака этих замков не существует.
  if (опрос.доступность !== 'дано' && опрос.доступность !== 'не нужно') {
    нет.push('«Универсальный доступ» — без него нажатия молча не доходят');
  }
  if (опрос.экран !== 'дано' && опрос.экран !== 'не нужно') {
    нет.push('«Запись экрана» — без неё нет снимков окон и сетки');
  }
  if (нет.length === 0) return null;
  return (
    `Джарвису не хватает разрешений: ${нет.join('; ')}. ` +
    'Выдать их можно в «Системные настройки → Конфиденциальность и безопасность».'
  );
}
