/**
 * Папка Джарвиса из ключа запуска — раньше всего остального.
 *
 * Установка в свою папку (`install.ps1 -InstallRoot D:\Jarvis`) кладёт туда
 * исходники, а где лежат настройки, модели и журнал, программа решала сама —
 * и решала «в %LOCALAPPDATA%\Rujarvis»: установка раскалывалась надвое, а
 * кнопка «Обновить» считала такую копию чужой. Ярлык переменную окружения
 * задать не может, зато может передать ключ: `--jarvis-home="D:\Jarvis"`.
 *
 * Модуль импортируется в `main.ts` первым: пути считаются при загрузке других
 * модулей, и к этому времени `JARVIS_HOME` уже должна стоять. Дочерние
 * процессы (сервер MCP, сценарии) наследуют её с окружением.
 */

import { homeFromArgs } from '../jarvis/setup/paths';

const дом = homeFromArgs(process.argv);
// Явная переменная окружения главнее ключа ярлыка: ею папку переносят нарочно.
if (дом && !process.env.JARVIS_HOME?.trim()) process.env.JARVIS_HOME = дом;
