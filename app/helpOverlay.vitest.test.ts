import { Script } from 'node:vm';

import { describe, expect, it } from 'vitest';

import { buildHelpHtml, выбратьКолонки } from './helpOverlay';
import { commandCatalogue } from '../jarvis/control/catalogue';

/**
 * Список команд, который не влезает в окно.
 *
 * Замер 24.09.2026 на экране 1536×864: окно справки выходит 1051×712, а сам
 * список в три колонки занимает 910 точек — пятая часть команд остаётся ниже
 * сгиба. Прокрутить её нечем: окно нарочно не берёт фокус, потому что человек
 * в этот момент говорит, а не печатает, — остаётся только колёсико мыши, о
 * котором окно нигде не говорит. При этом само окно обещает обратное:
 * «сказал — увидел всё».
 *
 * Поэтому колонки подбираются под окно уже на странице.
 */
describe('buildHelpHtml', () => {
  const html = buildHelpHtml(commandCatalogue());

  const открывающий = html.indexOf('<script>') + '<script>'.length;
  const закрывающий = html.indexOf('</script>', открывающий);
  const тело = html.slice(открывающий, закрывающий);

  it('целиком разбирается как код, а не только начинается похоже', () => {
    // Одна обратная кавычка внутри шаблонной строки рвёт страницу пополам, и
    // проверка типов этого не видит. Поиск закрывающего тега тоже: он
    // дописывается снаружи шаблона и есть всегда. Компиляция видит.
    expect(() => new Script(тело)).not.toThrow();
    expect(html).toContain('</html>');
    expect(html.slice(закрывающий)).not.toContain('function');
  });

  it('подбирает число колонок замером окна, а не задаёт его числом', () => {
    // Сам подбор проверен числами ниже; здесь — что страница зовёт именно
    // проверенную функцию и кормит её настоящим замером, а не своей копией.
    expect(тело).toContain('var выбратьКолонки =');
    expect(тело).toContain('document.body.scrollHeight');
    expect(тело).toContain('вылезает: вылезает()');
  });

  it('измеряет ширину таблицы, а не доверяет числу колонок', () => {
    expect(тело).toContain('getBoundingClientRect');
  });

  it('вставляет команды как текст, а не как разметку', () => {
    expect(html).not.toContain('innerHTML');
  });

  it('показывает все команды из справочника, а не часть', () => {
    const команд = commandCatalogue().reduce((всего, группа) => всего + группа.items.length, 0);
    const строк = html.match(/<tr>/gu)?.length ?? 0;
    expect(строк).toBe(команд);
    expect(команд).toBeGreaterThan(50);
  });
});

/**
 * Числа — из замера 25.09.2026, окно 1100×734: высота содержимого по числу
 * колонок и то, вылезла ли хоть одна таблица за свою колонку.
 *
 * Проверка текстом страницы этого не ловила: она зеленела и при
 * перевёрнутом `if (вылезает()) continue`, и при выборе самой высокой
 * раскладки вместо самой низкой.
 */
describe('выбратьКолонки', () => {
  const ЗАМЕР: Record<number, { высота: number; вылезает: boolean }> = {
    2: { высота: 1117, вылезает: false },
    3: { высота: 853, вылезает: false },
    4: { высота: 1095, вылезает: true },
    5: { высота: 1012, вылезает: true },
  };

  it('берёт самую низкую раскладку из годных', () => {
    expect(выбратьКолонки((n) => ЗАМЕР[n])).toBe(3);
  });

  it('не берёт раскладку, где таблица шире своей колонки, даже если она ниже', () => {
    // Четыре колонки дают 1095 против 1117 у двух — но таблица вылезла,
    // а значит команду в ней не прочесть.
    const узкие = { 2: ЗАМЕР[2], 3: { высота: 1200, вылезает: false }, 4: ЗАМЕР[4], 5: ЗАМЕР[5] };
    expect(выбратьКолонки((n) => узкие[n as 2 | 3 | 4 | 5])).toBe(2);
  });

  it('при равной высоте берёт меньшее число колонок', () => {
    // Замер на 1413×795: и три, и четыре колонки дают 798.
    const поровну = {
      2: { высота: 1117, вылезает: false },
      3: { высота: 798, вылезает: false },
      4: { высота: 798, вылезает: false },
      5: { высота: 798, вылезает: false },
    };
    expect(выбратьКолонки((n) => поровну[n as 2 | 3 | 4 | 5])).toBe(3);
  });

  it('оставляет три колонки, когда не годится ни одна раскладка', () => {
    // Молча вернуть одну колонку значит сделать список вдвое длиннее окна.
    expect(выбратьКолонки(() => ({ высота: 900, вылезает: true }))).toBe(3);
  });
});
