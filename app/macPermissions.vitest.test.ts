import { describe, expect, it, vi } from 'vitest';

import { запроситьРазрешения, поСостоянию, чегоНеХватает, type Система } from './macPermissions';

/**
 * Разрешения macOS.
 *
 * Спросить может только система и только один раз: второй раз окно она не
 * покажет, а отправит в настройки. Поэтому промахнуться мимо этого раза
 * нельзя — и нельзя свернуть «ещё не спрашивали» в «отказано», иначе человека
 * отправят чинить настройки вместо того, чтобы просто спросить.
 */
function система(переопределения: Partial<Система> = {}): Система & { тронули: number } {
  const основа = {
    тронули: 0,
    спроситьМикрофон: async () => true,
    довереныЛиМы: () => true,
    состояниеЭкрана: () => 'granted',
    тронутьЭкран: async () => {
      основа.тронули += 1;
    },
    ...переопределения,
  };
  return основа as Система & { тронули: number };
}

describe('поСостоянию', () => {
  it('переводит ответы macOS в три слова, а не в два', () => {
    expect(поСостоянию('granted')).toBe('дано');
    expect(поСостоянию('denied')).toBe('отказано');
    expect(поСостоянию('restricted')).toBe('отказано');
    // Вот ради чего всё: «ещё не спрашивали» — не отказ. На отказ человека
    // шлют в настройки, а здесь надо просто задать вопрос.
    expect(поСостоянию('not-determined')).toBe('не спрашивали');
    expect(поСостоянию('unknown')).toBe('не спрашивали');
  });
});

describe('запроситьРазрешения', () => {
  it('вне мака не спрашивает ничего', async () => {
    const с = система();
    const опрос = await запроситьРазрешения(с, 'win32');
    expect(опрос).toEqual({ микрофон: 'не нужно', доступность: 'не нужно', экран: 'не нужно' });
    expect(с.тронули).toBe(0);
  });

  it('на чистой машине спрашивает всё', async () => {
    const довереныЛиМы = vi.fn().mockReturnValue(false);
    let экран = 'not-determined';
    const с = система({
      довереныЛиМы,
      состояниеЭкрана: () => экран,
      тронутьЭкран: async () => {
        экран = 'granted';
      },
    });
    const опрос = await запроситьРазрешения(с, 'darwin');

    // Сначала тихо, потом с окном: лишнее окно там, где доступ уже есть, —
    // это раздражение на ровном месте.
    expect(довереныЛиМы).toHaveBeenNthCalledWith(1, false);
    expect(довереныЛиМы).toHaveBeenNthCalledWith(2, true);
    expect(опрос.микрофон).toBe('дано');
    expect(опрос.экран).toBe('дано');
  });

  it('не переспрашивает то, что уже выдано', async () => {
    const довереныЛиМы = vi.fn().mockReturnValue(true);
    const с = система({ довереныЛиМы });
    const опрос = await запроситьРазрешения(с, 'darwin');
    // Ровно один вопрос, и тихий: окно система второй раз всё равно не
    // покажет, а лишний снимок экрана — лишняя секунда на старте.
    expect(довереныЛиМы).toHaveBeenCalledTimes(1);
    expect(довереныЛиМы).toHaveBeenCalledWith(false);
    expect(с.тронули).toBe(0);
    expect(опрос).toEqual({ микрофон: 'дано', доступность: 'дано', экран: 'дано' });
  });

  it('отказ микрофона называется отказом, а сбой вызова — нет', async () => {
    const отказал = await запроситьРазрешения(система({ спроситьМикрофон: async () => false }), 'darwin');
    expect(отказал.микрофон).toBe('отказано');

    const сломался = await запроситьРазрешения(
      система({
        спроситьМикрофон: () => {
          throw new Error('нет такого API');
        },
      }),
      'darwin',
    );
    // Сбой самого вызова — не отказ человека. Врать про второе нельзя.
    expect(сломался.микрофон).toBe('не спрашивали');
  });

  it('падение одного вопроса не отменяет остальные', async () => {
    const опрос = await запроситьРазрешения(
      система({
        довереныЛиМы: () => {
          throw new Error('API нет');
        },
      }),
      'darwin',
    );
    expect(опрос.доступность).toBe('не спрашивали');
    // Микрофон и экран обязаны быть спрошены всё равно.
    expect(опрос.микрофон).toBe('дано');
    expect(опрос.экран).toBe('дано');
  });
});

describe('чегоНеХватает', () => {
  it('молчит, когда всё на месте', () => {
    // Тишина при порядке ценнее ещё одного сообщения, которое перестанут
    // читать.
    expect(чегоНеХватает({ микрофон: 'дано', доступность: 'дано', экран: 'дано' })).toBeNull();
    expect(чегоНеХватает({ микрофон: 'не нужно', доступность: 'не нужно', экран: 'не нужно' })).toBeNull();
  });

  it('называет каждое недостающее и чем это грозит', () => {
    const текст = чегоНеХватает({ микрофон: 'отказано', доступность: 'не спрашивали', экран: 'отказано' });
    expect(текст).toContain('микрофон');
    expect(текст).toContain('Универсальный доступ');
    expect(текст).toContain('Запись экрана');
    expect(текст).toContain('Конфиденциальность');
  });

  it('про «Универсальный доступ» говорит и тогда, когда просто не дали', () => {
    // Это и есть самый тихий случай: разрешения нет, отказа тоже не было,
    // человек ушёл в настройки и не вернулся. Молчать тут нельзя.
    const текст = чегоНеХватает({ микрофон: 'дано', доступность: 'не спрашивали', экран: 'дано' });
    expect(текст).toContain('молча не доходят');
  });
});
