import path from 'node:path';

/**
 * Окно терминала для входа в аккаунт CLI.
 *
 * Вынесено из `settingsWindow.ts` отдельно и без Электрона, потому что это
 * единственный шаг онбординга, который человек не может обойти: без входа агент
 * не запустится вовсе. А проверить сборку команды иначе нечем — ошибка живёт
 * ровно в кавычках, и видно её только на живой машине.
 *
 * Живой прогон 26.09.2026 у владельца: вкладка «войти» открывала окно, в котором
 * стояло
 *
 *   "\"C:\Users\ariel\.local\bin\claude.exe\"" не является внутренней или
 *   внешней командой
 *
 * — то есть первый же обязательный шаг не работал.
 */
export interface ЗапускТерминала {
  file: string;
  args: string[];
  /**
   * Файл сценария, который надо записать ДО запуска (только Windows).
   *
   * Он и есть развязка всей этой истории: внутри файла кавычки наши, и их
   * больше никто не переэкранирует.
   */
  сценарий?: { файл: string; текст: string };
}

/**
 * Что запустить, чтобы человек увидел вход в аккаунт своими глазами.
 *
 * ## Почему на Windows через файл, а не строкой
 *
 * Перепробовано и замерено 26.09.2026 на этой же машине, пять форм против
 * пути С ПРОБЕЛОМ и без:
 *
 * 1. Свои кавычки вокруг пути — НЕ работает. Node экранирует их как `\"`, а
 *    `\"` cmd не понимает вовсе. Это и была поломка у владельца.
 * 2. Рабочая папка плюс голое имя файла — НЕ работает: в системе стоит
 *    `NoDefaultCurrentDirectoryInExePath=1`, и cmd нарочно НЕ ищет в текущей
 *    папке.
 * 3. `cmd /c <полный путь>`, `cmd /c start "" <полный путь>`,
 *    `cmd /c start "" cmd /k <полный путь>`, `cmd /k <полный путь>` и
 *    `start "" powershell -NoExit -Command & <путь>` — работают ВСЕ ПЯТЬ, и с
 *    пробелом тоже.
 *
 * Про четвёртую я сначала написал, что она ломается на пробеле по правилу cmd о
 * двух кавычках. Это неверно, и замер это опроверг: cmd СОХРАНЯЕТ кавычки,
 * когда внутри них настоящий путь к исполняемому файлу, — то самое условие из
 * его правила, про которое я забыл. Оставляю запись, потому что иначе следующий
 * прочтёт вычеркнутое как правду.
 *
 * Файл сценария выбран не потому, что остальное не работает, а за три вещи,
 * которых у остальных форм нет:
 *
 *   `chcp 65001` — иначе русский текст самого CLI приедет в окно мусором;
 *   `pause`      — окно остаётся открытым, и отказ входа можно ПРОЧИТАТЬ, а не
 *                  поймать взглядом на мелькнувшем окне;
 *   кавычки наши — внутри файла между нашей строкой и cmd больше нет ничьего
 *                  экранирования, и ломаться там нечему.
 *
 * Имя файла — латиницей: cmd читает имена своей кодовой страницей и
 * кириллическое имя просто не находит (тоже замер, на нём спотыкнулась первая
 * версия этой проверки).
 */
export function терминалДляВхода(
  command: string,
  args: readonly string[],
  папка: string,
  platform: NodeJS.Platform = process.platform,
): ЗапускТерминала {
  if (platform === 'win32') {
    const файл = path.win32.join(папка, 'vhod.cmd');
    return {
      file: 'cmd.exe',
      // Пустая строка — это заголовок окна для `start`. Не `'""'`: Node
      // превратил бы его в `"\"\""`.
      args: ['/c', 'start', '', файл],
      сценарий: { файл, текст: сценарийВхода(command, args) },
    };
  }

  if (platform === 'darwin') {
    return { file: 'osascript', args: ['-e', скриптТерминала(command, args)] };
  }

  return { file: 'x-terminal-emulator', args: ['-e', command, ...args] };
}

/**
 * Содержимое `vhod.cmd`.
 *
 * `pause` в конце — не украшение: без него окно закрывается вместе с CLI, и
 * отказ входа человек не прочитает. Весь день до этого чинились ровно такие
 * места, где причина была и пропадала.
 */
export function сценарийВхода(command: string, args: readonly string[]): string {
  const nl = String.fromCharCode(13) + String.fromCharCode(10);
  const строка = [`"${command}"`, ...args.map((д) => `"${д}"`)].join(' ');
  return [
    '@echo off',
    // Кодовая страница UTF-8: иначе русский текст самого CLI приедет мусором.
    'chcp 65001>nul',
    строка,
    'echo.',
    'pause',
    '',
  ].join(nl);
}

/** Строка для оболочки: одинарные кавычки, свои — через `'\''`. */
function дляОболочки(часть: string): string {
  return `'${часть.replace(/'/gu, `'\\''`)}'`;
}

/**
 * Строка внутри двойных кавычек AppleScript.
 *
 * Обратная косая — ПЕРВОЙ, иначе экранирование кавычки само станет её жертвой:
 * сначала `"` → `\"`, потом эта новая косая удвоится в `\\"`, и кавычка снова
 * закроет строку. Порядок здесь не вкусовщина.
 */
function дляAppleScript(строка: string): string {
  return строка.replace(/\\/gu, '\\\\').replace(/"/gu, '\\"');
}

/**
 * Скрипт, открывающий Терминал с командой входа.
 *
 * `activate` обязателен: без него окно открывается ПОЗАДИ, а человеку в него
 * надо смотреть и вводить код. Для единственного шага, который нельзя обойти,
 * окно за спиной равносильно отказу.
 */
export function скриптТерминала(command: string, args: readonly string[]): string {
  const строка = [command, ...args].map(дляОболочки).join(' ');
  const nl = String.fromCharCode(10);
  return [
    'tell application "Terminal"',
    '  activate',
    `  do script "${дляAppleScript(строка)}"`,
    'end tell',
  ].join(nl);
}
